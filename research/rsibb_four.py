"""
RSIBB на ЧЕТЫРЁХ периодах: проверка того, что уже торгует.

ЗАЧЕМ. Планка в этом проекте поднялась по ходу работы, и подняли её измерения,
а не вкус. Сначала выяснилось, что оба исходных периода — падающие: у «бычьего
2025-26» BTC −39.8%, у «медвежьего» −34.7%. Приёмка «на двух независимых
периодах» оказалась приёмкой на двух падающих, и про растущий рынок она не
говорила ничего. Затем выяснилось, что вариант, выбранный из девяти на полном
пуле, разваливается на парах, которых отбор не видел.

RSIBB был принят в бумагу ДО обоих открытий: на двух падающих периодах, с
подбором варианта из шестнадцати, глядя на оба периода сразу. Он единственный
из работающего, кто нынешней планке не отвечал. Поэтому его проверяют заново —
не улучшают, не подбирают, а именно проверяют.

НИ ОДНОГО ВАРИАНТА, И ЭТО ГЛАВНОЕ ОТЛИЧИЕ ОТ bollinger_tune. Здесь считается
ровно то, что стоит в Live_Bot/rsibb/params.py, и ничего кроме. Любой перебор
на четырёх периодах превратил бы проверку в новый подбор, а его результат — в
то же самое, чем оказался «пробой глубже 0.30 ATR»: лучшая из шестнадцати
монеток. Если боевая настройка не пройдёт, ответом будет «не проходит», а не
семнадцатый вариант.

ОТЛОЖЕННЫЕ ПАРЫ ВСТРОЕНЫ СРАЗУ. Пары делятся через одну: список отсортирован
по обороту, и деление подряд отдало бы одной половине крупные инструменты, а
другой мелкие — тогда провал означал бы «на мелких не работает», а не «подгонка
под пул». Половина настройки печатается для сравнения, но в приёмке не
участвует.

ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА. На ОТЛОЖЕННОЙ половине:

    в плюсе на всех четырёх периодах, интервал не накрывает ноль хотя бы на
    одном И не меньше 30 сделок на период.

Требование по интервалу — один период, а не два: половина пула даёт половину
сделок, интервалы шире примерно в полтора раза, и требовать от них того же,
что от полного пула, значило бы поставить условие, невыполнимое по построению.

ЧТО БУДЕТ ПРИ ПРОВАЛЕ, СКАЗАНО ЗАРАНЕЕ, ЧТОБЫ ПОТОМ НЕ ТОРГОВАТЬСЯ. RSIBB
торгует бумагой, а не деньгами, и стоит там как КАНДИДАТ, а не как доказанная
стратегия. Провал на четырёх периодах означает вывод из бумаги, а не поиск
настройки, которая пройдёт.

ИТОГ: НЕ ПОДТВЕРЖДЁН, НО ЭТО НЕ ОПРОВЕРЖЕНИЕ. На отложенной половине плюс на
всех четырёх периодах — +0.063, +0.045, +0.112, +0.128 R, — и ни один интервал
не уходит от нуля при требовавшемся одном. Приёмка не пройдена, и смягчать её
нельзя: ровно такое смягчение превратило бы замер в подтверждение чего угодно.

Но картина отказа здесь ДРУГАЯ, чем у пробоя, и разницу стоит назвать. У пробоя
отложенная половина ПОМЕНЯЛА ЗНАК — так выглядит отсутствие края. Здесь
положительны все восемь клеток, обе половины на всех четырёх периодах, причём
на отложенной величина составляет 60-70% от настроечной, а просадка держится
между 2.7% и 5.9%. Так выглядит край, слишком мелкий для имеющейся выборки.

Объединение отложенной половины по четырём периодам: 526 сделок, +0.087 R на
сделку, интервал [+0.000; +0.174]. Нижняя граница стоит РОВНО на нуле — то есть
стратегия сидит точно на пороге различимости. При разбросе сделки 1.02 R и крае
0.087 R для отхода интервала от нуля нужно около 520 сделок, и их ровно столько
и есть; любое дробление выборки — по периодам, по половинам пула — этот порог
теряет.

ЧТО С ЭТИМ ДЕЛАТЬ, РЕШАЕТ НЕ ЗАМЕР. Здесь было записано «провал означает вывод
из бумаги». Вердикт замера остаётся прежним и не переписывается: RSIBB НЕ
ДОКАЗАН. Но само последствие было выбрано неудачно, и об этом сказано вслух, а
не потихоньку: бумага ничего не стоит и служит единственным дешёвым источником
недостающих сделок, а вывод оттуда уничтожил бы ровно те данные, которых не
хватает. Отделять вердикт от действия допустимо; переписывать вердикт под
желаемое действие — нет.

Твёрдое ограничение остаётся: на этих данных RSIBB не переходит на настоящие
деньги.

Запуск:
    python research/rsibb_four.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bollinger_tune as bt  # noqa: E402
from common import (BEAR_CACHE, BEAR_PAIRS, BULL_CACHE, BULL_PAIRS,  # noqa: E402
                    RISING_CACHES, RISING_PAIRS, ci)

MIN_TRADES = 30

PERIODS = [
    ('2022-01 падение', BEAR_CACHE, BEAR_PAIRS),
    ('2023-07 РОСТ',    RISING_CACHES[0], RISING_PAIRS),
    ('2024-07 РОСТ',    RISING_CACHES[1], RISING_PAIRS),
    ('2025-05 падение', BULL_CACHE, BULL_PAIRS),
]


def live_config():
    """
    Настройка ровно как в бою, прочитанная из боевых параметров.

    Читается из модуля, а не переписывается сюда числами: копия разошлась бы с
    боем при первой же правке, и замер тихо проверял бы не то, что торгует.
    """
    from rsibb import params
    # Замер знает ОДИН порог расхождения, бой хранит два. Пока они равны,
    # разницы нет; разойдись они — замер молча проверял бы половину настройки.
    if params.RSI_LOW != params.RSI_HIGH:
        raise SystemExit(
            f'RSI_LOW={params.RSI_LOW} и RSI_HIGH={params.RSI_HIGH} '
            'разошлись: замер умеет только один порог, и до правки его '
            'результат к бою отношения не имеет')
    return {'tf': params.TIMEFRAME, 'bb_period': params.BB_PERIOD,
            'bb_mult': params.BB_MULT, 'rsi_period': params.RSI_PERIOD,
            'rsi_edge': params.RSI_HIGH, 'stop_frac': params.STOP_FRAC,
            'target_frac': params.TARGET_FRAC}


def main():
    cfg = live_config()
    print('боевая настройка:', ', '.join(f'{k}={v}' for k, v in cfg.items()))

    results = {}
    for label, cache, pairs in PERIODS:
        for part, subset in (('настройка', pairs[0::2]),
                             ('проверка', pairs[1::2])):
            frames = bt.scan(subset, cache, f'{label} · {part}')
            if not frames:
                continue
            results[(label, part)] = bt.run(frames, cfg)

    for part in ('настройка', 'проверка'):
        print()
        print('=' * 104)
        print('ОТЛОЖЕННАЯ ПОЛОВИНА — по ней и только по ней идёт приёмка'
              if part == 'проверка' else
              'ПОЛОВИНА НАСТРОЙКИ — для сравнения, в приёмке не участвует')
        print('=' * 104)
        print(f'{"период":<20}{"сделок":>8}{"винрейт":>9}{"R вал.":>9}'
              f'{"издер.":>8}{"R/сделку":>10}{"DD%":>7}{"интервал":>22}')
        print('-' * 104)
        for label, _c, _p in PERIODS:
            res = results.get((label, part))
            if not res:
                print(f'{label:<20}{"— мало сделок":>8}')
                continue
            lo, hi = ci(res['r'])
            span = f'[{lo:+.3f}; {hi:+.3f}]'
            print(f'{label:<20}{res["n"]:>8}{res["wr"]:>8.1f}%'
                  f'{res["gross"]:>9.3f}{res["costs"]:>8.3f}'
                  f'{res["mean"]:>10.3f}{res["dd"]:>7.1f}{span:>22}')

    print()
    print('=' * 104)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: на ОТЛОЖЕННОЙ половине в плюсе на')
    print('всех четырёх, интервал от нуля хотя бы на одном И не меньше')
    print(f'{MIN_TRADES} сделок на период.')
    print('=' * 104)

    positive, strong, thin, seen = [], 0, False, 0
    for label, _c, _p in PERIODS:
        res = results.get((label, 'проверка'))
        if not res:
            thin = True
            continue
        seen += 1
        lo, _hi = ci(res['r'])
        positive.append(res['mean'] > 0)
        strong += 1 if lo > 0 else 0
        thin = thin or res['n'] < MIN_TRADES
        print(f'  {label:<20}{res["mean"]:+.3f} R ({res["n"]} сделок)')

    print()
    if thin or seen < len(PERIODS):
        print('МАЛО СДЕЛОК — замер не состоялся.')
    elif all(positive) and strong >= 1:
        print('ПОДТВЕРЖДЁН на четырёх периодах и отложенных парах.')
        print('Стратегия перестаёт быть кандидатом на двух падающих периодах')
        print('и становится проверенной по нынешней планке.')
    else:
        print('НЕ ПОДТВЕРЖДЁН.')
        print(f'в плюсе на {sum(positive)} из 4, интервал от нуля на {strong}')
        print('По записанному заранее условию это означает вывод из бумаги,')
        print('а не поиск настройки, которая пройдёт.')


if __name__ == '__main__':
    main()
