# Второй день заседания (день заявления).
FOMC = """2021-01-27 2021-03-17 2021-04-28 2021-06-16 2021-07-28 2021-09-22 2021-11-03 2021-12-15
2022-01-26 2022-03-16 2022-05-04 2022-06-15 2022-07-27 2022-09-21 2022-11-02 2022-12-14
2023-02-01 2023-03-22 2023-05-03 2023-06-14 2023-07-26 2023-09-20 2023-11-01 2023-12-13
2024-01-31 2024-03-20 2024-05-01 2024-06-12 2024-07-31 2024-09-18 2024-11-07 2024-12-18
2025-01-29 2025-03-19 2025-05-07 2025-06-18 2025-07-30 2025-09-17 2025-10-29 2025-12-10
2026-01-28 2026-03-18 2026-04-29 2026-06-17 2026-07-29 2026-09-16"""

END = datetime(2026, 10, 1)


def build():
    rows = []
    for kind, text, fmt, hm in (('CPI', CPI, '%m/%d/%Y', (8, 30)), ('NFP', NFP, '%m/%d/%Y', (8, 30)),
                                ('FOMC', FOMC, '%Y-%m-%d', (14, 0))):
        for d in text.split():
            day = datetime.strptime(d, fmt)
            if day >= END:
                continue
            local = day.replace(hour=hm[0], minute=hm[1], tzinfo=NY)
            utc = local.astimezone(ZoneInfo('UTC'))
            rows.append({'kind': kind, 'date_ny': day.date().isoformat(),
                         'utc': utc.strftime('%Y-%m-%d %H:%M'),
                         'minute': int(utc.timestamp() // 60)})
    ev = pd.DataFrame(rows).sort_values('minute').reset_index(drop=True)
    ev.to_csv(os.path.join(HERE, 'events.csv'), index=False)
    return ev


if __name__ == '__main__':
    ev = build()
    print(ev.groupby('kind').size().to_dict(), 'событий; первое', ev.utc.iloc[0], 'последнее', ev.utc.iloc[-1])
    print(ev.groupby([ev.kind, ev.utc.str[11:]]).size().to_string())
