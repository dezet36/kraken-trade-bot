"""
Пробой канала с фильтром по ОТКРЫТОМУ ИНТЕРЕСУ. Отложенные пары встроены сразу.

ПОЧЕМУ ИМЕННО ЭТОТ ПРИЗНАК И ПОЧЕМУ ТОЛЬКО ОН. Диагностика пробоя
(break_diagnosis.py) прогнала восемь наблюдаемых признаков по четырём периодам.
Свечные — объём, сжатие, ширина канала, согласие со старшим ТФ, удалённость от
средней — знак между периодами не удержали: то плюс, то минус. Ровно на таких
признаках погибли обе прежние попытки пробоя, добавлявшие фильтр по интуиции.

Изменение открытого интереса за сутки до пробоя оказалось единственной строкой,
где все четыре периода одного знака и три из четырёх почти одинаковы по
величине: +0.33, +1.05, +1.03, +0.99 процента хода вперёд. Значимости там нет
ни на одном периоде, и по правилу чтения, записанному в самой диагностике, это
означает «не разделяет». Но у этого признака есть то, чего не было у прочих:
механизм назван ДО прогона, а не подобран после. Цена уходит за границу при
РАСТУЩЕМ интересе — входят новые деньги; при ПАДАЮЩЕМ — закрывают встречную
позицию, и топливо кончилось. В свечах эти два события неотличимы.

Поэтому признак проверяется не глазами по таблице, а там, где он решает: на
живой геометрии сделок.

ФИЛЬТР БЕЗ ЕДИНОГО ПОДБИРАЕМОГО ЧИСЛА. Условие — «интерес за сутки до пробоя
вырос», то есть сравнение с нулём. Ни порога, ни окна на выбор: любое такое
число пришлось бы подбирать, а подбор на четырёх периодах уже один раз выдал
за находку то, что оказалось случайностью. Сама стратегия тоже не
пересматривается — берётся ровно тот вариант «пробой глубже 0.30 ATR», что был
отвергнут на отложенных парах, чтобы разница объяснялась фильтром и ничем ещё.

ОТЛОЖЕННАЯ ПОЛОВИНА ВСТРОЕНА С САМОГО НАЧАЛА, А НЕ ПРИСТРОЕНА ПОТОМ. Прошлый
замер выбрал вариант на полном пуле и лишь затем проверил его на половине —
и проверка его похоронила. Здесь пары делятся ЧЕРЕЗ ОДНУ сразу (список
отсортирован по обороту, деление подряд отдало бы одной половине крупные
инструменты), и приёмка смотрит ТОЛЬКО на отложенную.

ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА. На ОТЛОЖЕННОЙ половине:

    1. отфильтрованный набор в плюсе на всех четырёх периодах;
    2. интервал не накрывает ноль хотя бы на одном;
    3. не меньше 30 сделок на каждом периоде;
    4. отфильтрованный лучше ОТБРОШЕННОГО хотя бы на трёх периодах из четырёх.

Четвёртое условие — главное, и без него первые три ничего не стоят. Фильтр,
который оставляет прибыльный набор, но ровно так же прибылен на выброшенном,
не фильтр, а совпадение: он не разделяет, а просто уменьшает выборку. Именно
поэтому здесь считается и отброшенная половина, хотя торговать её никто не
собирается.

ИТОГ: НЕ ПРИНЯТ, И ПРИЧИНА НЕ В ПОДГОНКЕ. На отложенной половине фильтр в
плюсе на двух периодах из четырёх и бьёт отброшенное тоже на двух. Но главное
видно, если выписать все восемь разниц «интерес рос минус интерес падал», по
обеим половинам:

    +0.077  +0.192  -0.332  -0.093  -0.325  -0.099  +0.276  +0.032

Четыре плюса, четыре минуса. Признак не работает и на половине настройки —
значит это не история про то, что вариант подобрали и он не повторился. Это
отсутствие эффекта.

Согласованность в диагностике (+0.33, +1.05, +1.03, +0.99 процента хода
вперёд) держалась на чистом ходе цены и не пережила встречи с геометрией
сделки: стоп в три ATR срабатывает раньше, чем разница в один процент за трое
суток успевает проявиться. Тот же механизм, что убил и сам пробой.

Пробой на этом закрыт. Против него четыре независимых замера; свечные признаки
исхода не разделяют; единственный доступный признак иной природы, с механизмом,
названным заранее, — тоже. Из непроверенного остаётся дельта агрессора, истории
которой не существует ни на одной из двух бирж.

Запуск:
    python research/break_oi_filter.py
"""

import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import trend_break as tb  # noqa: E402
from break_diagnosis import load_oi  # noqa: E402
from common import ci  # noqa: E402

CFG = dict(tb.BASE, **{'break': 0.30})
OI_WINDOW = 24        # сутки до пробоя — то окно, что дало согласованный знак
MIN_TRADES = 30


def oi_change(cache_dir, marks):
    """Изменение интереса за сутки к началу каждого часа, по парам."""
    out = {}
    for mark in marks:
        stamps = pd.Series(pd.to_datetime(mark['stamps']))
        values = load_oi(cache_dir, mark['pair'], stamps)
        if values is None:
            continue
        past = pd.Series(values).shift(OI_WINDOW)
        out[mark['pair']] = ((values - past) / past * 100).to_numpy()
    return out


def split_orders(orders, changes):
    """
    Делит заявки на «интерес рос» и «интерес падал».

    Заявки без истории интереса выбрасываются ИЗ ОБЕИХ половин, а не
    сваливаются в одну: иначе сравнение половин заодно сравнивало бы пары с
    историей и без неё, и разница объяснялась бы составом, а не признаком.
    """
    kept, dropped = [], []
    for order in orders:
        pair, index = order.key
        series = changes.get(pair)
        if series is None or index >= len(series):
            continue
        value = series[index]
        if not np.isfinite(value):
            continue
        (kept if value > 0 else dropped).append(order)
    return kept, dropped


def measure(cache_dir, pairs, label):
    """Отфильтрованный и отброшенный наборы на одном подмножестве пар."""
    data, marks = tb.scan(cache_dir, pairs, label)
    if not data:
        return None, None
    changes = oi_change(cache_dir, marks)
    orders, _breaks = tb.build_orders(marks, CFG)
    kept, dropped = split_orders(orders, changes)
    return (tb.run(marks, data, CFG, orders=kept),
            tb.run(marks, data, CFG, orders=dropped))


def main():
    results = {}
    for label, cache, pairs in tb.PERIODS:
        usable = pairs[:tb.PAIRS_LIMIT]
        for part, subset in (('настройка', usable[0::2]),
                             ('проверка', usable[1::2])):
            kept, dropped = measure(cache, subset, f'{label} · {part}')
            results[(label, part)] = (kept, dropped)

    for part in ('настройка', 'проверка'):
        print()
        print('=' * 104)
        title = ('ОТЛОЖЕННАЯ ПОЛОВИНА — по ней и только по ней идёт приёмка'
                 if part == 'проверка' else
                 'ПОЛОВИНА НАСТРОЙКИ — для сравнения, в приёмке не участвует')
        print(title)
        print('=' * 104)
        print(f'{"период":<20}{"интерес РОС":>34}{"интерес ПАДАЛ":>34}'
              f'{"разница":>12}')
        print('-' * 104)
        for label, _c, _p in tb.PERIODS:
            kept, dropped = results.get((label, part), (None, None))
            cells = ''
            for res in (kept, dropped):
                if res is None:
                    cells += f'{"— мало сделок":>34}'
                    continue
                lo, hi = ci(res['r'])
                cell = '{:+.3f} [{:+.3f}; {:+.3f}] n={}'.format(
                    res['mean'], lo, hi, res['n'])
                cells += f'{cell:>34}'
            gap = ('' if kept is None or dropped is None
                   else f'{kept["mean"] - dropped["mean"]:+.3f}')
            print(f'{label:<20}{cells}{gap:>12}')

    print()
    print('=' * 104)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: на ОТЛОЖЕННОЙ половине в плюсе на')
    print('всех четырёх, интервал от нуля хотя бы на одном, не меньше')
    print(f'{MIN_TRADES} сделок на период И фильтр лучше отброшенного хотя бы')
    print('на трёх периодах из четырёх.')
    print('=' * 104)

    positive, strong, thin, better, seen = [], 0, False, 0, 0
    for label, _c, _p in tb.PERIODS:
        kept, dropped = results.get((label, 'проверка'), (None, None))
        if kept is None:
            positive.append(False)
            thin = True
            continue
        seen += 1
        lo, _hi = ci(kept['r'])
        positive.append(kept['mean'] > 0)
        strong += 1 if lo > 0 else 0
        thin = thin or kept['n'] < MIN_TRADES
        if dropped is not None and kept['mean'] > dropped['mean']:
            better += 1
        line = f'  {label:<20}фильтр {kept["mean"]:+.3f} ({kept["n"]} сделок)'
        if dropped is not None:
            line += f', отброшенное {dropped["mean"]:+.3f}'
        print(line)

    print()
    passed = (seen == len(tb.PERIODS) and all(positive) and strong >= 1
              and not thin and better >= 3)
    if thin or seen < len(tb.PERIODS):
        print('МАЛО СДЕЛОК — замер не состоялся.')
    elif passed:
        print('ПРИНЯТ на отложенных парах.')
        print('Открытый интерес разделяет исход пробоя там, где свечные')
        print('признаки не разделяли, и делает это на инструментах, которых')
        print('отбор не видел. Следующий шаг — вынести фильтр в стратегию.')
    else:
        print('НЕ ПРИНЯТ.')
        print(f'в плюсе на {sum(positive)} из 4, интервал от нуля на {strong}, '
              f'лучше отброшенного на {better} из 4')
        print('Если фильтр не бьёт отброшенное, он не разделяет исход, а лишь')
        print('уменьшает выборку — и тогда пробой закрыт окончательно: ни')
        print('свечные признаки, ни единственный доступный признак иной')
        print('природы края не дают.')


if __name__ == '__main__':
    main()
