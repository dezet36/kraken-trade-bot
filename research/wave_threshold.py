"""
Волновая стратегия: единственный уцелевший вариант — это ещё волна или уже нет.

ЗАЧЕМ ЭТОТ ЗАМЕР. Основной прогон (research/wave_impulse.py) не принял ни
одного варианта, но оставил закономерность, слишком чистую, чтобы её бросить:

    порог зигзага   лаг разметки   бык      медведь
    1.5             0 баров        +0.044   +0.024
    2.5             3 бара         −0.002   −0.027
    3.5             11 баров       −0.037   −0.044

Монотонно на ОБОИХ периодах, и направление противоположно тому, что утверждает
теория: чем надёжнее подтверждена разметка, тем хуже результат. Плюс остался
ровно на том пороге, где волновой структуры фактически нет — колено 2.4 ATR,
разметка известна в тот же бар.

ГИПОТЕЗА, КОТОРУЮ ЭТО ПОРОЖДАЕТ. Если край живёт не в волнах, а в «мелком
откате, купленном быстро», то при дальнейшем снижении порога он должен
продолжать расти по валовой части — и умирать от издержек, потому что стоп
сжимается вместе с коленом. Если же край принадлежит волновой структуре, он
должен иметь максимум где-то в середине, а не на границе диапазона.

Это проверяемая развилка, и она стоит одного прогона: без неё пришлось бы
написать «отвергнуто» рядом с единственной положительной строкой таблицы, не
понимая, что в ней было.

ВТОРАЯ ОСЬ — ПРОСАДКА. Порог 1.5 провалил приёмку в том числе по просадке (31%
на быке). Стратегия набирает позиции в одну сторону без ограничения; предел на
однонаправленные позиции — законный вариант, а не смягчение правила. Приёмка
остаётся прежней и записана до прогона:

    в плюсе на ОБОИХ периодах, интервал не накрывает ноль
    И просадка не больше 25% на обоих.

РЕЗУЛЬТАТ: НИ ОДИН ВАРИАНТ НЕ ПРИНЯТ, И ГИПОТЕЗА ОТВЕРГНУТА ЦЕЛИКОМ — вместе с
той закономерностью, ради которой замер затевался.

    порог           0.75    1.0     1.25    1.5     2.0     2.5     3.5
    валовый бык    0.076   0.053   0.049   0.086   0.140   0.036  −0.004
    валовый медв.  0.047   0.018   0.043   0.067   0.019   0.012  −0.009

Монотонности нет ни на одном периоде, и максимумы у них в разных местах: на
быке 2.0, на медведе 1.5. Значит наблюдение основного прогона было артефактом
трёх точек, а не свойством разметки. Записано и в wave_impulse.py.

ЧТО ЗДЕСЬ РЕШАЕТ ДЕЛО, И ЭТО ВИДНО ЛУЧШЕ ЛЮБОГО ИНТЕРВАЛА. Издержки во всех
шестнадцати клетках равны 0.041-0.046 R, а валовый край гуляет от −0.009 до
0.140 при разбросе между соседними порогами до 0.06 R. Край целиком помещается
внутрь полосы собственных издержек и собственного шума.

И решающее: винрейт во ВСЕХ вариантах на ОБОИХ периодах лежит в 36-40%, а
отношение риска к прибыли — ровно 2.0. Что бы мы ни меняли в волновых
параметрах, на выходе получается один и тот же статистический объект. Так и
выглядит структура, не несущая информации: она не влияет ни на что, кроме
количества сделок.

Единственная клетка с интервалом, отделившимся от нуля, — порог 2.0 на быке
(+0.100 [+0.018; +0.179]). На медведе тот же порог даёт −0.022 при просадке
43%. Это ровно тот случай, ради которого приёмка требует ОБА периода.

ИТОГ ПО ВОЛНОВОЙ ТЕМЕ: 22 варианта в двух замерах, принято ноль. Тема закрыта.

Запуск:
    python research/wave_threshold.py
"""

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import wave_impulse as wi  # noqa: E402
from common import BEAR_CACHE, BEAR_PAIRS, BULL_CACHE, BULL_PAIRS, ci  # noqa: E402

# Порог опускается ниже 1.5 — туда, где волны уже нет совсем. Это и есть смысл
# замера: увидеть, где у края максимум.
wi.THRESHOLDS = (0.75, 1.0, 1.25, 1.5, 2.0)

VARIANTS = []
for thr in wi.THRESHOLDS:
    VARIANTS.append((f'порог {thr}', {'threshold': thr}))
for thr in (1.0, 1.5, 2.0):
    VARIANTS.append((f'порог {thr} · не более 3 в одну сторону',
                     {'threshold': thr, 'max_same_direction': 3}))


def main():
    periods = {}
    for label, cache, pairs in (('бык 2025-26', BULL_CACHE, BULL_PAIRS),
                                ('медведь 2022-23', BEAR_CACHE, BEAR_PAIRS)):
        periods[label] = wi.scan(pairs, cache, label)

    results = {}
    for label, (data, marks) in periods.items():
        print()
        print('=' * 120)
        print(f'{label}   пар: {len(data)}')
        print('=' * 120)
        head = (f'{"вариант":<38}{"заявок":>8}{"сделок":>8}{"налив":>7}'
                f'{"колено ATR":>12}{"RR":>6}{"лаг":>5}{"винрейт":>9}'
                f'{"R вал.":>9}{"издер.":>8}{"R/сделку":>10}{"сумма":>8}'
                f'{"DD%":>7}{"интервал":>22}')
        print(head)
        print('-' * len(head))
        results[label] = {}
        for name, override in VARIANTS:
            cfg = dict(wi.BASE, **override)
            res = wi.run(marks[cfg['threshold']], data, cfg)
            if res is None:
                print(f'{name:<38}{"— мало сделок":>16}')
                continue
            results[label][name] = res
            lo, hi = ci(res['r'])
            print(f'{name:<38}{res["orders"]:>8}{res["n"]:>8}{res["fill"]:>6.0f}%'
                  f'{res["wave1"]:>12.1f}{res["rr"]:>6.1f}{res["lag"]:>5.0f}'
                  f'{res["wr"]:>8.1f}%{res["gross"]:>9.3f}{res["costs"]:>8.3f}'
                  f'{res["mean"]:>10.3f}{res["total"]:>8.1f}{res["dd"]:>7.1f}'
                  f'{f"[{lo:+.3f}; {hi:+.3f}]":>22}')

    print()
    print('=' * 120)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: в плюсе на ОБОИХ периодах,')
    print('интервал не накрывает ноль И просадка не больше 25% на обоих.')
    print('=' * 120)
    for name, _ in VARIANTS:
        cells, ok = '', []
        for label, table in results.items():
            res = table.get(name)
            if not res:
                cells += f'{"—":>36}'
                ok.append(False)
                continue
            lo, hi = ci(res['r'])
            ok.append(res['mean'] > 0 and lo > 0 and res['dd'] <= 25)
            cell = f'{res["mean"]:+.3f} [{lo:+.3f}] DD {res["dd"]:.0f}%'
            cells += f'{cell:>36}'
        print(f'{name:<38}{cells}{"  ПРИНЯТ" if ok and all(ok) else ""}')

    print()
    print('РАЗВИЛКА. Если валовый край растёт по мере снижения порога и гибнет')
    print('от издержек — дело не в волнах, а в мелком откате, и волновая')
    print('надстройка только мешала. Если у края есть максимум внутри')
    print('диапазона — структура что-то значит, и тогда есть что дорабатывать.')


if __name__ == '__main__':
    main()
