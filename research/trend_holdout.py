"""
Пробой канала: проверка на ОТЛОЖЕННЫХ парах.

ЗАЧЕМ. Из девяти вариантов положительным на всех четырёх периодах оказался
ровно один — «пробой глубже 0.30 ATR». Если бы каждая клетка была
подбрасыванием монеты, ожидаемое число таких вариантов равно 9/16 ≈ 0.56. То
есть один — ровно то, что даёт случайность, и одного этого факта достаточно,
чтобы не объявлять находку.

В пользу того, что это не монетка, говорит другое: валовый край положителен во
ВСЕХ клетках всех вариантов (+0.09…+0.28), издержки втрое меньше края, и
картина по горизонтам связная — двое суток не работают, неделя работает,
глубокий пробой лучше мелкого. Но «в пользу» не значит «доказано».

Отложенные пары отвечают на это прямо: пул делится пополам, вариант выбирался
на одной половине, проверяется на другой, которую отбор не видел. Пары берутся
ЧЕРЕЗ ОДНУ, а не первые/вторые: список отсортирован по обороту, и деление
подряд отдало бы одной половине крупные инструменты, а другой мелкие — тогда
провал значил бы «на мелких не работает», а не «подгонка».

ПРИЁМКА ОСТАЁТСЯ ПРЕЖНЕЙ, И РИСК ТОЖЕ 0.5% — как у всех остальных замеров:

    на ОТЛОЖЕННОЙ половине в плюсе на всех четырёх периодах, интервал не
    накрывает ноль хотя бы на одном И не меньше 30 сделок на период.

Требование по интервалу ослаблено с двух периодов до одного СОЗНАТЕЛЬНО и
заранее: половина пула — половина сделок, интервалы расширятся примерно в
полтора раза, и требовать от них того же, что от полного пула, значило бы
поставить условие, невыполнимое по построению. Ровно такую ошибку в проекте
уже допускали.

Просадка здесь не проверяется отдельно: она измерена и известна — при 0.5%
доходит до 36%, при 0.25% укладывается в 20%. Это свойство размера ставки, а
не стратегии, и решать его надо сайзингом, а не приёмкой.

Запуск:
    python research/trend_holdout.py
"""

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import trend_break as tb  # noqa: E402
from common import ci  # noqa: E402

# Вариант, выбранный на полном пуле. Здесь он НЕ пересматривается: проверяется
# ровно он, иначе отложенная половина превратится во второй подбор.
CFG = dict(tb.BASE, **{'break': 0.30})
MIN_TRADES = 30


def main():
    rows = {}
    for label, cache, pairs in tb.PERIODS:
        usable = pairs[:tb.PAIRS_LIMIT]
        halves = {'настройка': usable[0::2], 'проверка': usable[1::2]}
        for part, subset in halves.items():
            data, marks = tb.scan(cache, subset, f'{label} · {part}')
            if not data:
                continue
            rows[(label, part)] = tb.run(marks, data, CFG)

    parts = ('настройка', 'проверка')
    print()
    print('=' * 104)
    print('ПРОБОЙ ГЛУБЖЕ 0.30 ATR НА ДВУХ ПОЛОВИНАХ ПУЛА')
    print('=' * 104)
    head = (f'{"период":<20}' +
            ''.join(f'{p:>40}' for p in parts))
    print(head)
    print('-' * len(head))
    for label, _c, _p in tb.PERIODS:
        cells = ''
        for part in parts:
            res = rows.get((label, part))
            if res is None:
                cells += f'{"— мало сделок":>40}'
                continue
            lo, hi = ci(res['r'])
            cell = (f'{res["mean"]:+.3f} [{lo:+.3f}; {hi:+.3f}] '
                    f'n={res["n"]}')
            cells += f'{cell:>40}'
        print(f'{label:<20}{cells}')

    print()
    print('=' * 104)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: на ОТЛОЖЕННОЙ половине в плюсе на')
    print('всех четырёх периодах, интервал не накрывает ноль хотя бы на одном')
    print(f'И не меньше {MIN_TRADES} сделок на период.')
    print('=' * 104)
    ok, strong, thin, signs = [], 0, False, []
    for label, _c, _p in tb.PERIODS:
        res = rows.get((label, 'проверка'))
        if res is None:
            ok.append(False)
            thin = True
            continue
        lo, _hi = ci(res['r'])
        ok.append(res['mean'] > 0)
        strong += 1 if lo > 0 else 0
        thin = thin or res['n'] < MIN_TRADES
        signs.append(f'{label}: {res["mean"]:+.3f}')
    print('на отложенной половине — ' + '; '.join(signs))
    print()
    if thin:
        print('МАЛО СДЕЛОК — замер не состоялся.')
    elif ok and all(ok) and strong >= 1:
        print('ПРИНЯТ на отложенных парах.')
        print('Это означает, что вариант не был выбором из девяти по счастью:')
        print('он повторился на инструментах, которых отбор не видел.')
    else:
        print('НЕ ПРИНЯТ.')
        print('Если на половине настройки результат хороший, а на отложенной')
        print('нет — вариант был подгонкой, и девять клеток дали своё.')

    print()
    print('ВАЖНОЕ ПРИ ЧТЕНИИ. Половина пула — половина сделок, интервалы шире')
    print('примерно в полтора раза. Поэтому смотреть надо прежде всего на ЗНАК')
    print('и его согласованность между половинами, а не на значимость каждой')
    print('клетки по отдельности.')


if __name__ == '__main__':
    main()
