"""
Параметры стратегии уровней. СОБСТВЕННЫЕ, ни один не взят у SMC или фибо.

Почему отдельным модулем. Стратегия, которая живёт на чужих настройках, не
проверяется, а примеряется: её результат тогда говорит не о ней, а о том,
насколько ей подошли параметры соседа. Порог стопа, число слотов, кулдаун,
лимит на одну сторону — всё это часть стратегии, а не общая инфраструктура.

Каждое число здесь имеет обоснование ИЗ САМОГО МЕТОДА, а не из наших
прошлых замеров. Где обоснования нет — так и написано, и такое число
подлежит проверке в первую очередь.

Работа с уровнями отличается от работы с зонами по существу:

  - уровень живёт долго и тестируется многократно, поэтому заявка на нём
    имеет смысл сутками, а не часами;
  - стоп ставится вплотную за уровень (в этом весь смысл входа от уровня —
    маленький риск при том же движении), поэтому минимум стопа критичен:
    иначе комиссия съест преимущество, как уже случилось на снятии
    ликвидности;
  - одновременных позиций может быть больше: уровни на разных парах —
    независимые события, а не одна ставка.
"""

# ── Построение уровня ────────────────────────────────────────────────────────
# Допуск, в пределах которого два касания считаются касаниями ОДНОЙ цены.
# Классика оперирует «точным касанием»: на акциях это центы. На крипте
# волатильность выше, поэтому берём долю процента, но с запасом в меньшую
# сторону — широкий допуск склеит в один уровень всю область консолидации.
TOLERANCE_PCT = 0.20

# Глубина фрактала для поиска точек касания. 2 — экстремум, вокруг которого
# по две свечи ниже (выше). Меньше — шум, больше — уровень подтверждается
# слишком поздно.
PIVOT_N = 2

# Минимум касаний, чтобы цена считалась уровнем. Два — это уже «дважды
# развернулось на одной цене».
MIN_TOUCHES = 2

# Сколько баров назад ищутся касания одного уровня. 600 часов ~ 25 дней:
# дальше уровень теряет актуальность, рынок его забывает.
MAX_SPAN_BARS = 600

# Уровень перестаёт торговаться, если после его подтверждения прошло больше.
# Обоснования из метода нет — величина назначена и подлежит проверке.
MAX_AGE_BARS = 720

# ── Вход ─────────────────────────────────────────────────────────────────────
# Заявка ставится, когда цена подошла к уровню ближе этого расстояния (в ATR),
# но ещё не коснулась.
TRIGGER_ATR = 1.0

# Ближе этого к уровню заявку ставить поздно — цена уже там.
MIN_GAP_ATR = 0.1

# Сколько живёт заявка. Уровень — объект долгоиграющий, в отличие от пробоя.
EXPIRY_HOURS = 24.0

# ── Риск ─────────────────────────────────────────────────────────────────────
# Стоп за уровнем, в ATR. Вход от уровня тем и ценен, что стоп короткий.
STOP_ATR = 0.5

# Но не короче этого в процентах цены. Круг издержек на бирже — около 0.16%
# цены (тейкер 0.055% x2 + проскальзывание 0.05%). При стопе 0.4% это 0.4 R
# на сделку, то есть заведомый проигрыш при любом сигнале.
MIN_STOP_PCT = 0.8

# Цель в единицах риска.
RR_TARGET = 3.0

# Доля депозита в риске на одну сделку.
RISK_PCT = 0.5

# ── Портфель ─────────────────────────────────────────────────────────────────
# Свои, а не заимствованные у SMC. Уровни на разных парах — независимые
# события, поэтому одновременных позиций допускается больше.
MAX_POSITIONS = 6

# Пауза по паре после выхода.
COOLDOWN_HOURS = 6.0

# Лимит позиций в одну сторону. Ноль — без лимита; проверяется отдельно.
MAX_SAME_DIRECTION = 0

# Максимум времени в позиции.
MAX_HOLD_HOURS = 168.0

# ── Критерии качества уровня ─────────────────────────────────────────────────
# Скорость подхода: сколько ATR цена прошла за SPEED_BARS свечей перед
# заявкой. Быстрый подход по классике даёт отбой, медленное сползание
# продавливает уровень.
SPEED_BARS = 12
SPEED_THRESHOLD = 1.5

# Насколько близко цена уровня должна лежать к круглому числу, в процентах.
ROUND_MAX_PCT = 0.15
