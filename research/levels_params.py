"""
Параметры стратегии уровней. СОБСТВЕННЫЕ, ни один не взят у SMC или фибо.

Почему отдельным модулем. Стратегия, которая живёт на чужих настройках, не
проверяется, а примеряется: её результат тогда говорит не о ней, а о том,
насколько ей подошли параметры соседа. Порог стопа, число слотов, кулдаун,
лимит на одну сторону — часть стратегии, а не общая инфраструктура.

Числа обоснованы из самого метода. Где обоснования нет — так и написано,
и такое число проверяется в первую очередь.
"""

# ── Построение уровня ────────────────────────────────────────────────────────
# Допуск, в пределах которого два касания считаются касаниями ОДНОЙ цены.
# Классика оперирует «точным касанием»: на акциях это центы. На крипте
# волатильность выше, поэтому доля процента — но с запасом в меньшую сторону:
# широкий допуск склеит в один уровень всю область консолидации.
TOLERANCE_PCT = 0.20

# Глубина фрактала для точек касания: экстремум с PIVOT_N барами по бокам.
PIVOT_N = 2

# Минимум касаний. Два — это уже «дважды развернулось на одной цене».
MIN_TOUCHES = 2

# Сколько баров назад ищутся касания одного уровня. 600 часов ~ 25 дней.
MAX_SPAN_BARS = 600

# Уровень перестаёт торговаться, если после подтверждения прошло больше.
MAX_AGE_BARS = 720

# Сколько ближайших к цене уровней рассматривается на каждой свече.
# Живой трейдер держит на графике единицы уровней, а не сотню. Без этого
# ограничения одна пара порождала 4000 заявок — это не торговля от уровней,
# а торговля от всего подряд.
NEAREST_LEVELS = 2

# ── Вход ─────────────────────────────────────────────────────────────────────
# Заявка рассматривается, когда цена ближе этого расстояния (в ATR) к уровню.
TRIGGER_ATR = 1.0
MIN_GAP_ATR = 0.1

# ПОДТВЕРЖДЕНИЕ. Замер показал, что это главный элемент всей конструкции:
# без него -1104 R, с ним +137 R на том же наборе уровней. Цена обязана
# проколоть уровень минимум на PIERCE_ATR и вернуться за него в течение
# RECLAIM_BARS свечей. Пробой без возврата сигнала не даёт вовсе.
PIERCE_ATR = 0.15
RECLAIM_BARS = 4

# Сколько живёт заявка после подтверждения.
EXPIRY_HOURS = 24.0

# ── Риск ─────────────────────────────────────────────────────────────────────
# Стоп ставится за экстремум прокола плюс запас в ATR.
STOP_PAD_ATR = 0.10

# Но не ближе этого в процентах цены. Круг издержек ~0.16% цены (тейкер
# 0.055% x2 + проскальзывание 0.05%). При стопе 0.4% это 0.4 R на сделку —
# заведомый проигрыш при любом сигнале.
MIN_STOP_PCT = 0.8

# Цель в единицах риска.
RR_TARGET = 3.0

# Доля депозита в риске на сделку.
RISK_PCT = 0.5

# ── Портфель ─────────────────────────────────────────────────────────────────
MAX_POSITIONS = 6
COOLDOWN_HOURS = 6.0
MAX_SAME_DIRECTION = 0     # 0 — без лимита; проверяется отдельно
MAX_HOLD_HOURS = 168.0

# ── Критерии качества уровня ─────────────────────────────────────────────────
SPEED_BARS = 12
SPEED_THRESHOLD = 1.5
ROUND_MAX_PCT = 0.15

# Объём на свече возврата относительно среднего за VOLUME_WINDOW свечей.
# Классика: уровень держит крупный участник, и его защита видна объёмом.
# Стакана у нас нет, объём свечи — единственный доступный след.
VOLUME_WINDOW = 48
VOLUME_RATIO = 1.5
