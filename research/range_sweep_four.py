"""
Ложный пробой коридора на ЧЕТЫРЁХ периодах: обещанная перепроверка.

ЗАЧЕМ, ЕСЛИ ТЕМА ЗАКРЫТА. Замер range_sweep закрыл торговлю в коридоре тремя
входами сразу и записал причину: валовый край МЕНЯЕТ ЗНАК между периодами —
на медвежьем около нуля и чуть выше, на бычьем отрицателен. Но оба тех периода
позже оказались ПАДАЮЩИМИ (BTC −34.7% и −39.8%), а «бык» и «медведь» были
ярлыками, а не измерением. Значит формулировка «край меняет знак между
режимами» опиралась на два периода одного режима и в таком виде не держится.

Здесь те же девять вариантов считаются ещё и на двух растущих периодах
(BTC +106.0% и +49.6%), которых у проекта тогда не было.

ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕ ДЕЛАЕТСЯ. Не добавлено ни одного нового варианта.
Соблазн «раз уж считаем, попробуем ещё пару условий» — это и есть тот перебор,
который на четырёх периодах выдал за находку «пробой глубже 0.30 ATR»,
оказавшийся лучшей из девяти монеток. Проверяется ровно то, что проверялось.

ОЖИДАНИЕ НАЗВАНО ДО ПРОГОНА, ЧТОБЫ ПОТОМ НЕ ПОДГОНЯТЬ ТОЛКОВАНИЕ. Подпись
отсутствия края — знак, гуляющий между периодами; подпись нехватки мощности —
знак один, но интервалы накрывают ноль. У range_sweep был первый случай, и
ожидается, что два новых периода его подтвердят. Если вместо этого на растущих
периодах окажется устойчивый плюс, то прежний вывод был неверен, и это будет
сказано прямо.

ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА, — ТА ЖЕ, ЧТО БЫЛА, РАСШИРЕННАЯ НА ЧЕТЫРЕ:

    в плюсе на ВСЕХ ЧЕТЫРЁХ периодах, интервал не накрывает ноль хотя бы на
    двух И просадка не больше 25% на каждом.

Пул здесь не делится пополам: у коридорных вариантов сделок и так немного, и
половина пула увела бы замер в «мало сделок», где не различить ничего.

ИТОГ: ЗАКРЫТИЕ ПОДТВЕРЖДЕНО, НО ПРЕЖНЕЕ ОБЪЯСНЕНИЕ ОКАЗАЛОСЬ НЕВЕРНЫМ. Восемь
вариантов из девяти отрицательны по чистому R на ВСЕХ ЧЕТЫРЁХ периодах, девятый
не набрал сделок. Валовый R тоже не спасает: у большинства вариантов он
отрицателен или гуляет вокруг нуля.

Поправка к range_sweep. Там было записано, что валовый край МЕНЯЕТ ЗНАК между
периодами, и это толковалось как режимная зависимость: мол, в одном режиме
работает, в другом нет. На четырёх периодах видно, что режим ни при чём — оба
растущих периода дают ровно такую же картину, что и падающие. Никакой
зависимости от режима нет; есть отрицательный край, а «смена знака» была тем,
как выглядит шум, когда его смотрят в двух точках.

Ровно та же ошибка чтения, что уже случалась с «монотонностью по порогу» у
волн: три точки приняли за закономерность, более частая сетка её растворила.

Единственные клетки с заметным плюсом — вариант Вайкоффа (+0.463 на 2025 при
−0.450 на 2024) и «наш объём возврата» (+0.273 валовыми на 2024 при −0.112 на
2022). Размах в целый R между периодами при десятках сделок — это не край, а
малая выборка.

Тема торговли в коридоре закрыта окончательно, четырьмя входами и четырьмя
периодами. Что это НЕ отменяет: стратегия уровней, работающая тем же приёмом
прокола с возвратом, край имеет. Разница в том, какой уровень считать значимым —
найденный по касаниям за месяц или граница коридора за двое суток.

Запуск:
    python research/range_sweep_four.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import range_sweep as rs  # noqa: E402
from common import (BEAR_CACHE, BEAR_PAIRS, BULL_CACHE, BULL_PAIRS,  # noqa: E402
                    RISING_CACHES, RISING_PAIRS, ci)

MAX_DD = 25.0

PERIODS = [
    ('2022-01 падение', BEAR_CACHE, BEAR_PAIRS),
    ('2023-07 РОСТ',    RISING_CACHES[0], RISING_PAIRS),
    ('2024-07 РОСТ',    RISING_CACHES[1], RISING_PAIRS),
    ('2025-05 падение', BULL_CACHE, BULL_PAIRS),
]


def main():
    results = {}
    for label, cache, pairs in PERIODS:
        data, setups = rs.load(cache, pairs, label)
        if not data:
            print(f'   {label}: данных нет')
            continue
        results[label] = {}
        for name, pierce, reclaim, frac, max_pv, min_rv, kind in rs.VARIANTS:
            results[label][name] = rs.run(setups[(pierce, reclaim)], data,
                                          frac, max_pv, min_rv, kind)

    labels = [lab for lab, _c, _p in PERIODS if lab in results]

    print()
    print('=' * 112)
    print('ЧИСТЫЙ R НА СДЕЛКУ ПО ПЕРИОДАМ')
    print('=' * 112)
    head = f'{"вариант":<40}' + ''.join(f'{lab:>18}' for lab in labels)
    print(head)
    print('-' * len(head))
    for name, *_rest in rs.VARIANTS:
        cells = ''
        for label in labels:
            res = results[label].get(name)
            cells += f'{"— мало":>18}' if res is None else f'{res["mean"]:>+18.3f}'
        print(f'{name:<40}{cells}')

    print()
    print('=' * 112)
    print('ВАЛОВЫЙ R — до издержек. Здесь видно, есть ли что защищать вообще.')
    print('=' * 112)
    print(head)
    print('-' * len(head))
    for name, *_rest in rs.VARIANTS:
        cells = ''
        for label in labels:
            res = results[label].get(name)
            cells += f'{"— мало":>18}' if res is None else f'{res["gross"]:>+18.3f}'
        print(f'{name:<40}{cells}')

    print()
    print('=' * 112)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: в плюсе на ВСЕХ ЧЕТЫРЁХ, интервал')
    print(f'от нуля хотя бы на двух И просадка не больше {MAX_DD:.0f}% на каждом.')
    print('=' * 112)
    for name, *_rest in rs.VARIANTS:
        signs, strong, deep, thin = [], 0, False, False
        for label in labels:
            res = results[label].get(name)
            if res is None:
                thin = True
                continue
            lo, _hi = ci(res['r'])
            signs.append(1 if res['mean'] > 0 else -1)
            strong += 1 if lo > 0 else 0
            deep = deep or res['dd'] > MAX_DD
        if thin or len(signs) < len(labels):
            verdict = 'мало сделок'
        elif all(s > 0 for s in signs) and strong >= 2 and not deep:
            verdict = 'ПРИНЯТ'
        elif all(s > 0 for s in signs):
            verdict = 'знак один, но приёмку не проходит'
        else:
            plus = sum(1 for s in signs if s > 0)
            verdict = f'знак гуляет — плюс на {plus} из {len(signs)}'
        print(f'  {name:<42}{verdict}')

    print()
    print('КАК ЧИТАТЬ. «Знак гуляет» на валовом R означает отсутствие края:')
    print('издержки тут ни при чём, потому что до них дело не доходит. Если же')
    print('валовый знак один и положителен, а чистый нет — край есть, но его')
    print('съедают издержки, и это совсем другой разговор.')


if __name__ == '__main__':
    main()
