"""
Общая оснастка замеров: статистика, периоды, глушение журнала.

ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Двадцать один замер брал бутстрап, списки пар и пути
к кэшу из `fibo_audit` — файла, названного именем ОДНОЙ из стратегий. Работало
это исправно, но означало вот что: правка, сделанная ради Фибоначчи, молча
меняла замеры волн, уровней, сетки и Боллинджера. Достаточно было тронуть в нём
число повторов бутстрапа или список пар, чтобы поехали результаты у всех.

Стратегии в этом проекте намеренно независимы: у каждой свой пакет, свои
параметры, свой префикс переменных окружения. Анализ должен быть независим
ровно так же — иначе «проверка на двух периодах» проверяет заодно и то, что
кто-то не подкрутил чужой файл.

ЧТО ЗДЕСЬ ЛЕЖИТ И ПОЧЕМУ ИМЕННО ЭТО. Только то, что не принадлежит ни одной
стратегии: доверительные интервалы, определения периодов и глушилка журнала.
Пороги, геометрия и настройки портфеля сюда не попадают НИКОГДА — они у каждой
стратегии свои, и общее место для них немедленно превратилось бы в то, от чего
уходим.

ПОПУТНО ИСПРАВЛЕНА НАСТОЯЩАЯ ОШИБКА. Прежняя `hush()` глушила журнал модуля
`strategy`, то есть Фибоначчи, — независимо от того, чей замер её вызвал.
Замеры уровней и Боллинджера звали её и продолжали писать по строке на каждую
просмотренную свечу, а прогон упирался в журнал, а не в счёт. Теперь глушатся
те стратегии, что реально загружены.
"""

