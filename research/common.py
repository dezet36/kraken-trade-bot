# ИМЕНА BULL/BEAR ВВОДЯТ В ЗАБЛУЖДЕНИЕ, И ЭТО ИЗМЕРЕНО: у «бычьего» периода
# BTC −39.8%, у «медвежьего» −34.7%. Оба падающие. Подробности и цифры — в
# smc_market_regime, где эти имена определены.
#
# Практический вывод для нового замера: двух этих периодов НЕДОСТАТОЧНО.
# Независимость там только по времени, не по режиму, и вывод «работает на двух
# независимых периодах» ничего не говорит о растущем рынке. Для полноты нужны
# RISING_CACHES — BTC +106.0% и +49.6%.

# ── Статистика ───────────────────────────────────────────────────────────────
BOOTSTRAP = 10_000
# Зерно закреплено: интервалы должны воспроизводиться от прогона к прогону,
# иначе «пограничный» вариант будет то проходить приёмку, то нет, и спорить
# придётся с генератором случайных чисел.
RNG = np.random.default_rng(20260806)

# Одна выборка бутстрапа занимает BOOTSTRAP × len(values) чисел. При десяти
# тысячах повторов и семнадцати тысячах сделок это 1.3 ГБ одним куском, и
# скальперский замер на пятиминутках честно упал на этом. Считаем частями:
# результат тот же, память ограничена сверху.
CHUNK_CELLS = 20_000_000


def _boot_means(values, size=None):
    """Средние бутстраповых выборок. Считается частями — иначе не влезает."""
    size = len(values) if size is None else size
    per_chunk = max(1, CHUNK_CELLS // max(size, 1))
    out = []
    left = BOOTSTRAP
    while left > 0:
        take = min(per_chunk, left)
        out.append(RNG.choice(values, size=(take, size),
                              replace=True).mean(axis=1))
        left -= take
    return np.concatenate(out)


def ci(values, alpha=0.05):
    """Доверительный интервал среднего бутстрапом."""
    v = np.asarray(values, dtype=float)
    if len(v) < 3:
        return (np.nan, np.nan)
    draws = _boot_means(v)
    return tuple(np.percentile(draws, [alpha / 2 * 100, (1 - alpha / 2) * 100]))


def diff_ci(a, b, alpha=0.05):
    """Интервал РАЗНИЦЫ средних двух независимых выборок."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    if len(a) < 3 or len(b) < 3:
        return (np.nan, np.nan)
    d = _boot_means(a) - _boot_means(b)
    return tuple(np.percentile(d, [alpha / 2 * 100, (1 - alpha / 2) * 100]))


# ── Журнал ───────────────────────────────────────────────────────────────────
# Боевой код пишет строку на КАЖДУЮ просмотренную свечу — «нет сигнала, цена
# вне окна входа». В работе это полезно, в замере это двести тысяч записей на
# пару, и прогон упирается именно в них, а не в счёт.
STRATEGY_MODULES = ('strategy', 'strategy_smc', 'strategy_levels',
                    'strategy_rsibb')


def hush(*names):
    """
    Глушит журнал стратегий на время поиска. Возвращает снимок для возврата.

    Без аргументов глушит ВСЕ загруженные модули стратегий, а не один
    конкретный. Прежняя версия жила в файле аудита Фибоначчи и глушила только
    его модуль: замеры уровней и Боллинджера звали её и продолжали писать в
    журнал по строке на свечу.

    Модули не импортируются, а берутся из уже загруженных: замер импортирует ту
    стратегию, которую меряет, и тянуть сюда остальные значило бы поднимать
    биржевые клиенты ради глушения журнала.
    """
    saved = {}
    for name in (names or STRATEGY_MODULES):
        module = sys.modules.get(name)
        if module is not None and hasattr(module, 'log'):
            saved[name] = module.log
            module.log = lambda *a, **k: None
    return saved


def unhush(saved):
    """Возвращает журнал на место."""
    for name, original in (saved or {}).items():
        module = sys.modules.get(name)
        if module is not None:
            module.log = original
