"""
Пробой БЕЗ СТОПА, с выходом по времени. Последняя непроверенная конструкция.

ОТКУДА ВЗЯЛСЯ ВОПРОС. Диагностика пробоя (break_diagnosis.py) намерила вещь,
которая не согласуется с четырьмя отказами подряд: средний ход цены через 72
часа после глубокого пробоя недельного канала положителен на ВСЕХ четырёх
периодах — +0.71, +0.80, +0.40, +0.62 процента, значимо на трёх. Направление
после пробоя есть, и оно устойчивее всего, что удалось намерить фильтрами.

Гибло каждый раз не направление, а ГЕОМЕТРИЯ. Разброс ходов около 8.7%, средний
ход 0.6% — край составляет 0.07 своего шума. Стоп в три ATR (около 3.6% цены)
при таком отношении срабатывает раньше, чем дрейф успевает проявиться: он
превращает симметричный шум в отрезанный слева хвост и съедает ровно те сделки,
ради которых всё затевалось.

Отсюда конструкция, которая ни разу не проверялась в этом проекте: НИКАКОГО
СТОПА, выход строго по времени, размер позиции маленький и одинаковый. Так
работают управляющие временным моментумом, и так же устроен сам замер хода
вперёд — то есть проверяется ровно то, что было намерено, без наложенной сверху
геометрии.

ЧЕМ ЗА ЭТО ПЛАТИТСЯ, СКАЗАНО ЗАРАНЕЕ. Убыток на сделке ничем не ограничен;
защита только в размере позиции и в их числе. Это НЕ замена стопу и не
улучшение — это другой способ распоряжаться риском, и решать, приемлем ли он,
пользователю, а не замеру. Здесь считается, есть ли вообще что распределять.

СЧИТАЕТСЯ В ПРОЦЕНТАХ ХОДА, А НЕ В R. Единица R определена через расстояние до
стопа, а стопа тут нет — делить не на что. Поэтому и приёмка записана в
процентах, и сравнивать эти числа с R прежних замеров НЕЛЬЗЯ.

ИЗДЕРЖКИ ВЫЧИТАЮТСЯ ТЕЙКЕРСКИЕ, ПОЛНЫМ КРУГОМ. Вход по закрытию пробойной
свечи и выход по времени — оба по рынку, 0.105% в одну сторону. Никаких
мейкерских допущений: они здесь были бы выдачей желаемого за действительное.

ОТЛОЖЕННАЯ ПОЛОВИНА ВСТРОЕНА СРАЗУ, а не пристроена после. Пары делятся через
одну — список отсортирован по обороту, и деление подряд отдало бы одной
половине крупные инструменты.

ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА. На ОТЛОЖЕННОЙ половине, ПОСЛЕ издержек:

    в плюсе на всех четырёх периодах, интервал не накрывает ноль хотя бы на
    двух И не меньше 50 сделок на период.

Порог по числу сделок поднят с обычных тридцати: край здесь ожидается около
0.4% при разбросе около 9%, то есть меньше одной двадцатой шума. На тридцати
сделках такой замер не различил бы вообще ничего, и приёмка была бы
самообманом.

ИТОГ: НЕ ПРИНЯТ, И ЭТИМ ПРОБОЙ ЗАКРЫТ. На отложенной половине после издержек
плюс на всех четырёх периодах — +0.41, +0.39, +0.35, +1.06 процента, — но
интервал уходит от нуля лишь на одном из четырёх при требовавшихся двух. Даже
на пятистах сделках край в четыре десятых процента неотличим от нуля: он и
составляет около одной двадцатой разброса, о чём было сказано до прогона.

МЕДИАНЫ ВАЖНЕЕ СРЕДНИХ, И ОНИ ОТРИЦАТЕЛЬНЫ ВЕЗДЕ: -0.06, -0.34, -0.12, -0.28.
Больше половины сделок убыточны, а весь плюс несут редкие крупные ходы. Именно
для этого медиана и печаталась рядом.

Половина настройки добавляет последнее: +0.60, +0.94, -0.03, -0.42. Знак не
держится и там, причём проваливается на тех периодах, где отложенная половина
дала плюс. Две половины одного пула расходятся по знаку — это шум, а не край,
съеденный издержками.

Итого против пробоя пять независимых замеров. Направление после ухода за
уровень измеримо и устойчиво на чистом ходе цены, но оно слишком мало
относительно собственного разброса: любая надстройка — стоп, цель, фильтр,
выход по времени — его теряет. Из непроверенного остаётся дельта агрессора,
истории которой не существует ни на одной из двух бирж; её сбор идёт живьём.

Запуск:
    python research/break_hold.py
"""

import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'Live_Bot'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import break_diagnosis as bd  # noqa: E402
import trend_break as tb  # noqa: E402
from common import ci  # noqa: E402

ROUND_TRIP = 0.21      # тейкер туда и обратно, в процентах
MIN_TRADES = 50


def main():
    rows = {}
    for label, cache, pairs in bd.PERIODS:
        usable = pairs[:tb.PAIRS_LIMIT]
        for part, subset in (('настройка', usable[0::2]),
                             ('проверка', usable[1::2])):
            collected = bd.collect(cache, subset, f'{label} · {part}')
            if not collected:
                continue
            gross = np.array([r['forward'] for r in collected], dtype=float)
            rows[(label, part)] = gross - ROUND_TRIP

    for part in ('настройка', 'проверка'):
        print()
        print('=' * 96)
        print('ОТЛОЖЕННАЯ ПОЛОВИНА — по ней и только по ней идёт приёмка'
              if part == 'проверка' else
              'ПОЛОВИНА НАСТРОЙКИ — для сравнения, в приёмке не участвует')
        print('=' * 96)
        print(f'{"период":<20}{"сделок":>9}{"валовый %":>12}{"чистый %":>11}'
              f'{"интервал чистого":>26}{"медиана %":>12}')
        print('-' * 96)
        for label, _c, _p in bd.PERIODS:
            net = rows.get((label, part))
            if net is None:
                print(f'{label:<20}{"— нет данных":>9}')
                continue
            lo, hi = ci(net)
            span = f'[{lo:+.2f}; {hi:+.2f}]'
            print(f'{label:<20}{len(net):>9}{net.mean() + ROUND_TRIP:>+12.2f}'
                  f'{net.mean():>+11.2f}{span:>26}'
                  f'{np.median(net):>+12.2f}')

    print()
    print('=' * 96)
    print('ПРИЁМКА, ЗАПИСАННАЯ ДО ПРОГОНА: на ОТЛОЖЕННОЙ половине после')
    print('издержек в плюсе на всех четырёх, интервал от нуля хотя бы на двух')
    print(f'И не меньше {MIN_TRADES} сделок на период.')
    print('=' * 96)

    positive, strong, thin, seen = [], 0, False, 0
    for label, _c, _p in bd.PERIODS:
        net = rows.get((label, 'проверка'))
        if net is None:
            thin = True
            continue
        seen += 1
        lo, _hi = ci(net)
        positive.append(net.mean() > 0)
        strong += 1 if lo > 0 else 0
        thin = thin or len(net) < MIN_TRADES
        print(f'  {label:<20}{net.mean():+.2f}% ({len(net)} сделок)')

    print()
    if thin or seen < len(bd.PERIODS):
        print('МАЛО СДЕЛОК — замер не состоялся.')
    elif all(positive) and strong >= 2:
        print('ПРИНЯТ на отложенных парах.')
        print('Направление после пробоя есть и переживает издержки, если его')
        print('не резать стопом. Дальше — вопрос размера позиции и числа')
        print('одновременных, а не наличия края.')
    else:
        print('НЕ ПРИНЯТ.')
        print(f'в плюсе на {sum(positive)} из 4, интервал от нуля на {strong}')
        print('Пробой закрыт окончательно: направление после него измеримо,')
        print('но издержек не переживает даже без стопа.')

    print()
    print('ВАЖНОЕ ПРИ ЧТЕНИИ. Медиана печатается рядом со средним не для')
    print('красоты: если среднее держится плюсом, а медиана заметно ниже,')
    print('значит весь результат несут редкие крупные ходы. Такая стратегия')
    print('может быть верной, но переживать её тяжело, и знать это надо до')
    print('запуска, а не после первой полосы убытков.')


if __name__ == '__main__':
    main()
