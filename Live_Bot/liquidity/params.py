"""
Вынос ликвидности с целью ЗА противоположным забором: параметры. Свои.

ЧТО ЭТО ЗА СЕТАП. Стопы стоят не на уровне, а чуть ЗА ним, и там, где уровень
проверялся дважды-трижды, их скапливается особенно много: равные максимумы и
равные минимумы — это видимая всем черта, за которую все и прячут стоп. Цена
заходит за неё, собирает стопы, разворачивается. Вход на возврате.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ УЖЕ ЗАКРЫТОГО. Ложный пробой границы коридора мерился и
отвергнут: знак края менялся между периодами. Отличие здесь одно, но
существенное — ЦЕЛЬ. Там она стояла на противоположном крае коридора. Здесь —
за противоположным скоплением стопов, то есть дальше:

    коридор:   вход у одного края, цель у другого
    здесь:     вход после выноса, цель ЗА противоположным скоплением

Логика в том, что цена, собрав стопы с одной стороны, идёт к следующему их
скоплению — а оно лежит не на уровне, а за ним. Отношение риска к прибыли от
этого заметно выше, и именно короткая цель губила и сетку (RR 0.38 требовал 72%
попаданий), и торговлю в коридоре.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Дельты продавца — разницы агрессивных покупок и
продаж. Она была в исходном замысле, и её отсутствие честно измерено: в свече
шесть полей, поля объёма покупателя среди них нет, лента отдаёт девять минут и
запрос в прошлое игнорирует, а заменитель из свечи даёт связь со следующим
баром −0.008. Проверить дельту на истории НЕЛЬЗЯ. Сбор запущен (positioning.py),
и через два-три месяца она станет проверяемой — тогда её добавление будет
отдельным замером с честной приёмкой, а не догадкой.

ФАНДИНГ ВХОДИТ НЕ УРОВНЕМ, А ЧАСОМ. История ставок достаёт лишь на 400 дней и
не покрывает проверочные периоды. Но источники утверждают, что выносы учащаются
около СБРОСА фандинга — 00:00, 08:00 и 16:00 UTC, — а для этого нужны только
часы. Утверждение проверяемо бесплатно и потому проверяется.
"""

import os


def _f(name, default):
    return float(os.getenv(f'LIQ_{name}', default))


def _i(name, default):
    return int(os.getenv(f'LIQ_{name}', default))


def _s(name, default):
    return os.getenv(f'LIQ_{name}', default)


# ── Скопление ликвидности ────────────────────────────────────────────────────
ATR_PERIOD = _i('ATR_PERIOD', 14)
# Пивот считается таковым, если он крайний в окне ±PIVOT_BARS.
PIVOT_BARS = _i('PIVOT_BARS', 3)
# Сколько пивотов должны совпасть по цене, чтобы это считалось скоплением.
# Двух достаточно: «равные максимумы» — это ровно про два касания, а требование
# трёх отсекает большинство настоящих скоплений.
MIN_POOL_TOUCHES = _i('MIN_POOL_TOUCHES', 2)
# Насколько близко должны стоять пивоты, чтобы считаться одним скоплением, в
# ATR. Слишком узко — скоплений не будет вовсе, слишком широко — любые два
# максимума сойдут за равные.
POOL_TOLERANCE_ATR = _f('POOL_TOLERANCE_ATR', 0.35)
# Глубже какого возраста скопление не рассматриваем, в барах: стопы за
# полугодовым максимумом давно сняты или отменены.
POOL_MAX_AGE = _i('POOL_MAX_AGE', 300)

# ── Вынос ────────────────────────────────────────────────────────────────────
# Насколько глубоко цена должна уйти ЗА скопление, в ATR. Мелкое касание — это
# подход, а не сбор стопов.
PIERCE_ATR = _f('PIERCE_ATR', 0.20)
# За сколько баров цена должна ЗАКРЫТЬСЯ обратно. Тень за уровнем ничего не
# сообщает: значение имеет то, где бар закрылся.
RECLAIM_BARS = _i('RECLAIM_BARS', 4)

# ── Выход ────────────────────────────────────────────────────────────────────
# Насколько ЗА противоположное скопление ставится цель, в ATR. Ноль означает
# «ровно на скоплении» — тогда сетап вырождается в обычный отбой к уровню.
TARGET_BEYOND_ATR = _f('TARGET_BEYOND_ATR', 0.30)
# Запас за экстремум выноса до стопа, в ATR.
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.25)
# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.6)
MIN_RR = _f('MIN_RR', 1.5)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 72)
EXPIRY_BARS = _i('EXPIRY_BARS', 2)

# ── Фандинг как ЧАС, а не как уровень ────────────────────────────────────────
# Сброс фандинга на бессрочных контрактах происходит трижды в сутки. Источники
# утверждают, что выносы к нему учащаются. Ноль отключает проверку.
FUNDING_HOURS = (0, 8, 16)
# Сколько часов до и после сброса считать «окном сброса».
FUNDING_WINDOW = _i('FUNDING_WINDOW', 0)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 6)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 6.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
