"""
Скальпинг по RSI и полосам Боллинджера: параметры. Свои, ничего не заимствовано.

ЧТО ЭТО ЗА СЕТАП. Классика возврата к среднему: цена уходит за нижнюю полосу
Боллинджера, RSI подтверждает перепроданность — покупаем в расчёте на возврат
к средней линии. Симметрично для шорта.

ГЛАВНАЯ БОЛЕЗНЬ ЭТОГО СЕТАПА НАЗВАНА В ИСТОЧНИКАХ ПРЯМО, и она же убивала
наши прошлые попытки возврата к среднему:

    «Цена может идти вдоль полосы много свечей подряд, не разворачиваясь. Это
    называется ходьбой по полосе, и она уничтожает сделки на возврат.»

То есть сетап работает в боковике и разоряет в тренде. Вся его судьба в том,
можно ли отличить одно от другого ЗАРАНЕЕ.

ПОЭТОМУ ГЛАВНОЕ ЗДЕСЬ — НЕ ПОЛОСЫ И НЕ RSI, А ФИЛЬТР СОСТОЯНИЯ. Источники дают
проверяемое утверждение с числами:

    с фильтрами (ADX, подтверждение отбоя, предел удержания) реалистичен
    винрейт 58-65%; без фильтров ближе к 45%, потому что трендовые дни дают
    катастрофические серии убытков.

Это не «мнение о стратегии», а гипотеза с величиной эффекта: фильтр обязан
двигать долю попаданий примерно на 15 процентных пунктов. Ровно так и будет
проверяться — отдельным вариантом, а не на глаз.

ОСТОРОЖНО С ЭТИМ ЖАНРОМ УТВЕРЖДЕНИЙ. В замере пробоя внешний источник обещал
65% против 48% за счёт пересыхания объёма; на наших данных это сдвинуло
результат на +0.005 и −0.008 R, то есть не воспроизвелось вовсе. Внешнее число
здесь — повод для проверки, а не основание доверять.

НАСТРОЙКИ RSI ВЗЯТЫ ИЗ ИСТОЧНИКОВ, А НЕ ИЗ ГОЛОВЫ. Для скальпинга на крипте
пороги 70/30 названы слишком узкими — рекомендуются 75/25 или 80/20, и период
короче 14, чтобы сигнал приходил быстрее. Оба варианта в замере.

АРИФМЕТИКА ИЗДЕРЖЕК РЕШАЕТ ЗДЕСЬ БОЛЬШЕ, ЧЕМ ГДЕ БЫ ТО НИ БЫЛО. Вход на полосе
и цель на средней линии — обе заявки лимитные по построению, цена приходит к
ним сама. Круг мейкер-мейкер стоит 0.040% против 0.210% у тейкера с обеих
сторон. Но сетап скальперский, стопы короткие: при стопе 0.3% даже 0.040%
съедают 0.13 R. Поэтому пол по расстоянию до стопа здесь не защита от шума, а
прямая арифметика.
"""

import os


def _f(name, default):
    return float(os.getenv(f'RSIBB_{name}', default))


def _i(name, default):
    return int(os.getenv(f'RSIBB_{name}', default))


def _s(name, default):
    return os.getenv(f'RSIBB_{name}', default)


# ── Полосы Боллинджера ───────────────────────────────────────────────────────
BB_PERIOD = _i('BB_PERIOD', 20)
BB_MULT = _f('BB_MULT', 2.0)

# ── RSI ──────────────────────────────────────────────────────────────────────
RSI_PERIOD = _i('RSI_PERIOD', 14)
RSI_LOW = _f('RSI_LOW', 30.0)
RSI_HIGH = _f('RSI_HIGH', 70.0)
# Как читать RSI на полосе:
#   'extreme'    — канон: лонг только при перепроданности;
#   'divergence' — наоборот: лонг только если импульс НЕ слаб (расхождение);
#   'neutral'    — только середина диапазона;
#   'off'        — не смотреть вовсе.
# Пробник на бычьем периоде даёт канону 16% возвратов к средней против 26% без
# всякого фильтра, а расхождению — 76%. Это ровно наоборот учебнику, и потому
# требует не радости, а проверки вторым периодом: скорее всего расхождение
# отбирает не истощение продавца, а прокол вниз внутри восходящего тренда.
RSI_MODE = _s('RSI_MODE', 'extreme')

# ── Фильтр состояния рынка ───────────────────────────────────────────────────
ADX_PERIOD = _i('ADX_PERIOD', 14)
# Выше этого значения рынок считается трендовым, и возврат к среднему не
# торгуется. Ноль отключает фильтр — так меряется его вклад.
ADX_MAX = _f('ADX_MAX', 0.0)
# Полосы не должны расширяться: расширение означает начало движения, а не
# затухание. Отношение нынешней ширины к средней за окно. Ноль отключает.
WIDTH_WINDOW = _i('WIDTH_WINDOW', 50)
MAX_WIDTH_RATIO = _f('MAX_WIDTH_RATIO', 0.0)

# ── Вход ─────────────────────────────────────────────────────────────────────
# 'touch'   — лимит на полосе, как только RSI подтвердил крайность;
# 'reclaim' — вход по рынку, когда свеча ЗАКРЫЛАСЬ обратно внутрь полосы.
# Первое даёт лучшую цену, второе — подтверждение отбоя. Урок ложного пробоя:
# заявка НА краю систематически покупает у того, кто сметает стопы.
ENTRY_MODE = _s('ENTRY_MODE', 'touch')
# Сколько баров ждём закрытия обратно внутрь в режиме reclaim.
RECLAIM_BARS = _i('RECLAIM_BARS', 3)

# ── Выход ────────────────────────────────────────────────────────────────────
# Куда целимся, в долях расстояния от полосы до средней линии.
# 1.0 — средняя линия, 2.0 — противоположная полоса.
TARGET_FRAC = _f('TARGET_FRAC', 1.0)
# Стоп за полосой, в долях полуширины канала.
STOP_FRAC = _f('STOP_FRAC', 0.5)
# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.4)
# Что делать, когда естественный стоп ниже пола. 'widen' — расширить стоп,
# 'skip' — не брать сетап. Здесь это не мелочь: канал узкий, пол упирается
# почти всегда, и расширение роняет отношение риска к прибыли с 2.0 до 1.15.
THIN_STOP = _s('THIN_STOP', 'widen')
MIN_RR = _f('MIN_RR', 1.0)
# Предел удержания. Источники называют его среди обязательных фильтров: сделка
# на возврат, не сработавшая быстро, — это и есть начавшийся тренд.
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 48)
EXPIRY_BARS = _i('EXPIRY_BARS', 6)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 6)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 2.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
