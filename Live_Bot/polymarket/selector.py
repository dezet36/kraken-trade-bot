"""
Отбор рынков: где стоять двусторонней котировкой и зарабатывать на спреде.

ЗАДАЧА ИМЕННО ТАКАЯ, а не «собрать награды». Разобранный кошелёк @planktonxd
делает 1 495 сделок в сутки по $1.79, входит мейкером (комиссии 0.13% против
4.7% у тейкера) и берёт 1.5 цента на контракте — это 16% от цены покупки. Он
работает в мелких событиях, где есть стакан, и живёт разницей цен, а не наградой.
Награда, если рынок под неё подходит, идёт сверх и в отборе не главная.

ТРИ РАЗА ЗА РАЗБОР ОДНА И ТА ЖЕ ЛОВУШКА, поэтому она здесь описана подробно.
Всякий раз, когда рынок отбирался по одному числу — награде, отношению награды
к ликвидности, относительному спреду, — наверх всплывали ПУСТЫЕ книги:

    награда к ликвидности      бидов на $2,  асков на $15,  спред 0.889
    относительный спред        бидов на $0,  асков на $11 849, спред 200%

Второй случай особенно поучителен. Дешёвый лонгшот НИКТО не хочет покупать по
два цента, зато многие хотят продать. Наш бид оказался бы единственным: нас
исполнят немедленно, и мы получим ровно тот хвост дешёвых позиций, на котором
разобранный кошелёк держит переоценку -$8 564 при 22% позиций в плюсе.

Отсюда правило: рынок отбирается по СТАКАНУ, а не по полю ликвидности, и обе
стороны должны быть живыми. Поле `liquidity` считает всё вместе и односторонний
стакан от двустороннего не отличает.

ЧТО ОСТАЁТСЯ ПОСЛЕ ОТСЕВА. Из 1 282 кандидатов книга есть у 600, глубина не
меньше $100 по обеим сторонам — у 410, без сильного перекоса — у 82. Медианный
спред у этих 82 составляет 6% от ставки за круг. Высокие проценты, которые
манили раньше, жили ровно в односторонних книгах.

РАЗМЕР ЗАЯВКИ — МИНИМАЛЬНЫЙ ДОПУСТИМЫЙ, ПЯТЬ КОНТРАКТОВ. Порог 20-200 относится
только к награде, а для заработка на спреде он не нужен. Двусторонняя котировка
в пять контрактов стоит РОВНО $5 при любой цене: покупка берёт 5p, продажа
5(1-p), в сумме пятёрка. Значит сотня долларов — это двадцать рынков, а не пять.
"""

import json
import math
import time
from datetime import datetime, timezone

from . import book as book_mod
from . import client, params


def rewards_daily(market):
    return sum(float(r.get('rewardsDailyRate') or 0)
               for r in (market.get('clobRewards') or []))


def quote_cost(size, price, one_sided=None):
    """
    Во что обходится котировка. Зависит от того, стоим ли обеими сторонами.

    ДВУСТОРОННЯЯ стоит РОВНО размер при любой цене: покупка берёт p за
    контракт, продажа — (1-p), потому что продавать надо то, чего у нас нет.
    Считать одну сторону значило бы вдвое занизить потребность и обнаружить это
    на первом отказе биржи.

    ВХОД ОДНОЙ СТОРОНОЙ стоит size × min(p, 1-p) — мы занимаем деньги только
    под дешёвую сторону, а выходим продажей того, что уже держим, и это не
    стоит ничего. Замерено: медиана падает с $5.00 до $0.62 на рынок, то есть
    те же деньги покрывают 64 рынка вместо восьми.
    """
    price = float(price)
    light = params.MM_CAPITAL_LIGHT if one_sided is None else one_sided
    if light:
        return float(size) * min(price, 1.0 - price)
    return float(size) * price + float(size) * (1 - price)


def _hours_left(end):
    """Часов до разрешения. Без даты возвращает бесконечность, а не ноль."""
    if not end:
        return float('inf')
    try:
        stamp = str(end).replace('Z', '+00:00')
        left = (datetime.fromisoformat(stamp)
                - datetime.now(timezone.utc)).total_seconds() / 3600.0
    except Exception:                                      # noqa: BLE001
        return float('inf')
    return left


def _candidates(pages, min_volume, price_lo, price_hi):
    """Первичный отсев по метаданным. Стакан здесь ещё не смотрим."""
    rows = []
    for page in range(pages):
        chunk = client._get(f'{params.GAMMA}/markets?limit=100'
                            f'&offset={page * 100}&closed=false')
        if not isinstance(chunk, list) or not chunk:
            break
        for m in chunk:
            try:
                tokens = json.loads(m.get('clobTokenIds') or '[]')
                price = float(json.loads(m.get('outcomePrices') or '[]')[0])
            except Exception:                              # noqa: BLE001
                continue
            spread = float(m.get('spread') or 0)
            if not tokens or spread <= 0:
                continue
            if not price_lo < price < price_hi:
                continue
            if float(m.get('volume') or 0) < min_volume:
                continue
            # РЫНОК ПЕРЕД РАЗРЕШЕНИЕМ НЕ КОТИРУЕМ, и это самый крупный риск во
            # всей затее. Мейкер зарабатывает полтора цента на контракте; при
            # разрешении контракт становится нулём или единицей ЦЕЛИКОМ. Один
            # запас в пять контрактов по 0.20, застигнутый разрешением не в ту
            # сторону, стоит доллар — то есть тринадцать удачных кругов.
            #
            # Наклон против запаса разгружает нас за часы, а не за минуты, и
            # перед самым разрешением разгружать уже некому: ликвидность
            # уходит первой. Поэтому порог по времени, а не надежда на выход.
            if _hours_left(m.get('endDate')) < params.MM_MIN_HOURS_LEFT:
                continue
            rows.append({
                'id': m.get('id'), 'question': m.get('question'),
                'condition_id': m.get('conditionId'), 'token_id': tokens[0],
                'token_no': tokens[1] if len(tokens) > 1 else None,
                'tick': float(m.get('orderPriceMinTickSize') or 0.001),
                'order_min': float(m.get('orderMinSize') or 5),
                'rewards_daily': rewards_daily(m),
                'rewardsMinSize': m.get('rewardsMinSize'),
                'rewardsMaxSpread': m.get('rewardsMaxSpread'),
                'liquidity': float(m.get('liquidity') or 0),
                'volume': float(m.get('volume') or 0),
                'meta_price': price, 'meta_spread': spread,
                'end': m.get('endDate'), 'fee_type': m.get('feeType'),
                'event_id': ((m.get('events') or [{}])[0] or {}).get('id'),
            })
        time.sleep(params.PAUSE)
    return rows


def scan(budget=None, limit=None, pages=30, min_volume=None,
         min_depth=None, min_balance=None, remember=None):
    """
    Рынки, где двусторонняя котировка имеет смысл. Лучшие первыми.

    Отсев идёт в два шага, и второй обязателен: сначала метаданные, потом
    НАСТОЯЩИЙ стакан. Пропустив второй, мы отобрали бы односторонние книги, где
    наша заявка окажется единственной со своей стороны и её снимут немедленно.
    """
    budget = float(budget if budget is not None else params.bankroll_for('MM'))
    limit = int(limit or params.MM_MARKETS)
    min_volume = float(min_volume if min_volume is not None
                       else params.MM_MIN_VOLUME)
    min_depth = float(min_depth if min_depth is not None
                      else params.MM_MIN_SIDE_DEPTH)
    min_balance = float(min_balance if min_balance is not None
                        else params.MM_MIN_BALANCE)

    rows = _candidates(pages, min_volume, params.MM_MIN_PRICE,
                       params.MM_MAX_PRICE)
    # СПРАВОЧНИК ПОПОЛНЯЕТСЯ ВСЕМИ КАНДИДАТАМИ, А НЕ ТОЛЬКО ОТОБРАННЫМИ.
    #
    # Отбор оставляет горстку лучших, а позиция может пережить его и остаться
    # на рынке, который больше никуда не проходит. Панель тогда показывает
    # открытую позицию прочерком: названия взять неоткуда. Замерено в работе —
    # семь позиций из тринадцати оказались без имени.
    #
    # Здесь же, до всякой фильтрации, названия есть у всех тысячи с лишним.
    if remember:
        try:
            remember(rows)
        except Exception:                                  # noqa: BLE001
            pass                                           # справочник — удобство
    if not rows:
        return []

    books = book_mod.fetch_many([r['token_id'] for r in rows])
    # СКОЛЬКО ОБЕЩАННОГО СПРЕДА МЫ ЗАБИРАЕМ НА ДЕЛЕ — спрашивается один раз за
    # отбор: замер читает журнал исполнений с диска.
    capture = _capture_factor()
    good = []
    for row in rows:
        live = books.get(str(row['token_id']))
        if not live or not live['bids'] or not live['asks']:
            continue
        top = book_mod.top(live)
        if not top or top['mid'] is None or top['spread'] is None:
            continue
        # ГЛУБИНА СЧИТАЕТСЯ В ДЕНЬГАХ, А НЕ В КОНТРАКТАХ. Тысяча контрактов по
        # цене 0.002 — это два доллара, и называть такую сторону живой нельзя.
        bid_usd = sum(size * price for price, size in live['bids'])
        ask_usd = sum(size * (1 - price) for price, size in live['asks'])

        # У НАГРАДЫ СВОИ ПОРОГИ, И ЭТО НЕ ПОСЛАБЛЕНИЕ, А РАЗНЫЕ ЗАДАЧИ.
        #
        # Глубина, перекос и ширина спреда писались под ЗАХВАТ СПРЕДА: там нам
        # нужен встречный поток, место в очереди и что-то, что останется после
        # шага внутрь. Награда же платится за СТОЯНИЕ близко к середине, и ей
        # безразлично, торгует рынок или молчит.
        #
        # Цена этой путаницы измерена: из 644 наградных рынков, живущих дольше
        # двух суток, наш отбор пропускал ВОСЕМЬ. Пулы там по три-тридцать
        # долларов в день, и делить их почти не с кем.
        #
        # ЛОВУШКА ПУСТОЙ КНИГИ ОСТАЁТСЯ ЗАКРЫТОЙ, и стережёт её не глубина, а
        # прямой вопрос: сколько чужих очков стоит внутри допуска. Глубина
        # обманывает — книга бывает толстой, но вся далеко от середины. Доля
        # спрашивает то, что нужно: если она под сотню процентов, мы не берём
        # долю, а становимся всем рынком, и любая сделка пойдёт против нас.
        reward_ok = _reward_worth_standing(live, top, row)
        if (bid_usd < min_depth or ask_usd < min_depth) and not reward_ok:
            continue
        # ПЕРЕКОС МЕРЯЕТСЯ В КОНТРАКТАХ, А НЕ В ДЕНЬГАХ. В деньгах он врёт по
        # построению: при РАВНОЙ глубине в контрактах бид на цене 0.90 стоит
        # $900, а аск — $100, и книга выглядит перекошенной девятикратно, хотя
        # она идеально симметрична. Так отбраковывался КАЖДЫЙ рынок дороже 0.80
        # и дешевле 0.20 — независимо от того, что в нём на самом деле.
        #
        # Глубина по-прежнему считается в деньгах: там вопрос «сколько стоит
        # эта сторона», и ответ на него денежный. Перекос спрашивает другое —
        # «одинаково ли готовы покупать и продавать», и это про контракты.
        bid_lots = sum(size for _, size in live['bids'])
        ask_lots = sum(size for _, size in live['asks'])
        balance = min(bid_lots, ask_lots) / max(bid_lots, ask_lots, 1e-9)
        if balance < min_balance and not reward_ok:
            continue

        # СПРЕД ДОЛЖЕН ВМЕЩАТЬ ШАГ ВНУТРЬ. Условие здесь ТО ЖЕ, что в стратегии,
        # и это не дублирование, а согласование: без него отбор обещал 90
        # рынков и $450 вложений, а котировалось 22 — на остальных стратегия
        # отказывалась вставать в конец очереди, и план расходился с делом.
        #
        # Узкий спред не изъян рынка, а отсутствие места для нас: при спреде в
        # один тик заработать нечего, а встать можно только за очередь из 152
        # контрактов по медиане.
        # ОДНОТИКОВЫЕ РЫНКИ БОЛЬШЕ НЕ ОТБРАСЫВАЮТСЯ ЗДЕСЬ. Прежде отсев шёл по
        # ширине спреда, и это была ошибка: замер по 53 рынкам показал, что у
        # шести ожидание меньше часа, медиана 23 минуты, и почти все они как
        # раз однотиковые. Спред узок там потому, что торгуют. Решение теперь
        # принимает время ожидания — ниже, после замера потока.
        ticks = int(round(top['spread'] / row['tick'])) if row['tick'] > 0 else 0

        size = max(row['order_min'], params.MM_MIN_ORDER_SIZE)
        cost = quote_cost(size, top['mid'])
        if cost <= 0 or cost > budget:
            continue

        row.update({
            'price': top['mid'], 'spread': top['spread'],
            'bid_usd': round(bid_usd, 2), 'ask_usd': round(ask_usd, 2),
            'balance': round(balance, 3), 'size': size, 'cost': round(cost, 2),
            # Спред в долях цены. Это НЕ ожидаемый доход, и называть его так
            # было бы обманом: полный спред достаётся лишь тому, у кого
            # исполнились ОБЕ стороны, а широкий спред как раз и означает, что
            # никто не хочет котировать теснее. Обе наши заявки в таком рынке
            # исполнятся только тогда, когда кому-то станет ясно, куда идёт
            # цена, — то есть против нас.
            'spread_share': round(top['spread'] / max(top['mid'], 1e-9), 4),
            # ОЧКИ НАГРАДЫ СЧИТАЮТСЯ ЗДЕСЬ, ПОТОМУ ЧТО ЗДЕСЬ ЕСТЬ КНИГА.
            # Ниже по течению остаются только числа, а доля в награде зависит
            # от КАЖДОГО уровня чужих заявок с его весом. Считать её по общей
            # глубине — то, что делалось раньше, — значит не считать вовсе.
            'reward_rivals': round(_rival_score(live, top['mid'], row), 3),
            'reward_unit': round(_own_unit(top['mid'], row), 5),
            # Взят ли рынок РАДИ НАГРАДЫ, а не ради спреда. Захват спреда на
            # нём может быть невозможен вовсе, и требовать от него круга нельзя.
            'reward_path': bool(reward_ok),
            # ЧАСОВ ДО РАЗРЕШЕНИЯ — от него зависит, можно ли стоять обеими
            # сторонами: пара запирает деньги ровно до этого срока.
            'hours_left': _hours_left(row.get('end')),
            # ДОЛЯ ЗАБИРАЕМОГО СПРЕДА, замеренная по нашим же кругам. Кладётся
            # в каждую строку, чтобы расчёт дохода не лазил на диск.
            'capture': capture,
        })
        good.append(row)

    # НИЖНЕГО ПОРОГА ПО ДОЛЕ СПРЕДА БОЛЬШЕ НЕТ. Он отбраковывал дорогие рынки:
    # спред в восемь тиков при цене 0.80 составляет всего 1% от неё, и рынок с
    # ожиданием в СЕМЬ МИНУТ и доходом $0.25 в час отсеивался как «узкий».
    # Достаточно требовать, чтобы после нашего шага что-то оставалось, — это
    # проверяет our_gain ниже.
    #
    # Верхний порог остаётся: слишком широкий спред означает, что рынок не
    # знает цены, и исполнят нас там ровно тогда, когда узнает.
    good = [r for r in good if r['spread_share'] <= params.MM_MAX_SPREAD_SHARE]
    good = measure_wait(good, books)
    # ОТСЕВ ПО ВРЕМЕНИ, А НЕ ПО ШИРИНЕ СПРЕДА. Рынок, где круг занимает сутки,
    # бесполезен при любом спреде: деньги стоят, а разрешение приближается.
    # НАГРАДНЫЕ РЫНКИ НЕ ВЫБРАСЫВАЮТСЯ ПО ВРЕМЕНИ КРУГА, и это исправление
    # крупной потери.
    #
    # Награда платится за ТО, ЧТО МЫ СТОИМ, а не за то, что круг закрылся.
    # Отсев по времени написан для захвата спреда: там медленный рынок и правда
    # бесполезен. Но наградному рынку скорость безразлична — деньги идут, пока
    # заявка висит внутри допуска от середины.
    #
    # Замерено: захват спреда насыщается на 14 рынках и $14.70 капитала, дальше
    # деньги девать некуда. Награда же принимает капитал до тысячи долларов:
    #
    #     $40  → 13 рынков, $2.85/сут  = 215% в месяц
    #     $200 → 27 рынков, $8.57/сут  = 129%
    #     $1000→129 рынков, $15.50/сут =  47%
    #
    # И со входом дешёвой стороной наградная заявка стоит $1-3, а не $20.
    for row in good:
        row['pays_reward'] = float(row.get('rewards_daily') or 0) > 0 and             float(row.get('rewardsMinSize') or 0) > 0
    good = [r for r in good
            if (r['wait_hours'] <= params.MM_MAX_WAIT_HOURS or r['pays_reward'])
            and r['our_gain'] > 0]

    # ПОРЯДОК ПО ДЕНЬГАМ В ЧАС, а не по обороту и не по ширине спреда.
    #
    # Оборот обманывает: он накоплен за всю жизнь рынка. Отобранные по нему
    # рынки имели по $152 000 оборота и торговали 0.3 раза в час — семь сделок
    # в сутки на рынок. При таком темпе безразлично, насколько хорошо мы
    # котируем: круг просто не с кем совершить.
    #
    # Ширина спреда обманывает иначе: самые быстрые рынки биржи (20+ сделок в
    # час) имеют спред в ОДИН тик. Там нечего брать, и это не жадность рынка, а
    # его правильная работа — где многим нужна немедленность, конкуренция
    # сжимает спред. Широкий спред означает ровно обратное: немедленность
    # никому не нужна.
    #
    # Заработок — произведение того и другого. Меряем частоту по ЛЕНТЕ, а не
    # по обороту, и ставим наверх рынки с наибольшим ожидаемым доходом в час.
    # ИЗМЕРЕННАЯ ПОПРАВКА ПРИМЕНЯЕТСЯ ДО СОРТИРОВКИ. Расчёт ожидания считает
    # стороны независимыми; на деле они связаны против нас — цена ушла вниз,
    # покупку исполнили, продажу нет. Насколько именно расчёт оптимистичен,
    # видно только по нашим же исполнениям, и вот их-то сюда и подставляем.
    # Пока замеров мало, поправка равна единице и ничего не меняет.
    # ПОПРАВКА РАБОТАЕТ В ОБЕ СТОРОНЫ, и до сих пор это было не так.
    #
    # Применялась она только когда модель ОПТИМИСТИЧНА. А замер показал
    # обратное: обещано 48 минут, вышло 1.1 — модель пессимистична, и рынки
    # отбраковывались по расчёту, который занижает скорость в разы. Фильтр
    # «круг быстрее восьми часов» снимал 315 рынков из 324 именно так.
    #
    # Замерено, сколько рынков проходит при разной поправке: ×1.0 — четырнадцать,
    # ×0.5 — двадцать, ×0.25 — двадцать семь. Предел поправки не даёт нескольким
    # мгновенным исполнениям открыть список целиком.
    factor = _measured_factor()
    if factor != 1.0:
        for row in good:
            row['wait_hours'] = round(row['wait_hours'] * factor, 3)
            row['usd_per_hour'] = round(row['usd_per_hour'] / factor, 5)
            row['wait_factor'] = factor

    good.sort(key=lambda r: -r['usd_per_hour'])
    good = _cap_per_event(good)[:limit]
    # РАЗМЕР ЗДЕСЬ МИНИМАЛЬНЫЙ, А РЕШАЕТ РАСКЛАДКА. Прежде размер назначался
    # прямо тут — доля потока с потолком в 34% счёта, — и рынки приходили в
    # раскладку уже раздутыми: сорок долларов заканчивались на третьем.
    #
    # Сравнивать рынки надо при ОДИНАКОВОМ размере, иначе порядок по доходу в
    # час сравнивает не рынки, а назначенные им размеры. Добавку раздаёт
    # allocate — она одна видит весь бюджет и знает, кому добавка что даст.
    for row in good:
        row['size'] = _floor_size(row)
        row['cost'] = round(quote_cost(row['size'], row['price']), 2)
        # ВРЕМЯ ПЕРЕСЧИТЫВАЕТСЯ ПОД РАЗМЕР. Пойманная на себе ошибка: размер
        # поднимался с 5 до 34 контрактов, а ожидание оставалось от пятёрки — и
        # доход выходил завышенным ровно во столько же раз.
        _recompute_wait(row)
    return good


def _measured_factor():
    """Поправка на оптимизм модели, измеренная по нашим исполнениям."""
    try:
        from . import wait_factor
        return float(wait_factor())
    except Exception:                                      # noqa: BLE001
        return 1.0


# Множитель площадки за одностороннюю ликвидность. Стоя одной стороной, мы
# получаем треть очков — и только в полосе цен 0.10..0.90. Вне полосы одна
# сторона не приносит НИЧЕГО.
REWARD_ONE_SIDED_PENALTY = 3.0


def _spread_score(allowance, distance):
    """
    Очки за одну заявку: ((допуск − расстояние) / допуск)².

    Формула площадки, а не наша выдумка. Квадрат означает, что расстояние до
    середины важнее размера: заявка на полпути к границе допуска приносит
    четверть того, что заявка вплотную к середине.
    """
    if allowance <= 0 or distance < 0 or distance >= allowance:
        return 0.0
    return ((allowance - distance) / allowance) ** 2


def _reward_worth_standing(live, top, row):
    """
    Годится ли рынок под НАГРАДУ, даже если под захват спреда не годится.

    Три условия, и каждое закрывает ошибку, найденную замером:

      * пул есть — иначе платить нечего;
      * внутри допуска стоит КТО-ТО ЕЩЁ. Пустая книга у середины означает, что
        цену там назначаем мы одни, и согласится с ней только тот, кому она
        выгодна. Замерено: рынки с нулём чужих очков обещали по формуле пять
        тысяч процентов в сутки — это не доход, а приглашение стать рынком;
      * наша доля не больше трети. То же самое, но в числах и мягче: доля под
        сотню процентов — верный признак, что делить не с кем.

    ПОЧЕМУ НЕ ГЛУБИНА. Глубина обманывает по построению: книга бывает толстой,
    но вся стоять далеко от середины — за пределами допуска, где очков не дают
    никому. Доля спрашивает ровно то, что решает деньги.
    """
    if not top or top.get('mid') is None:
        return False
    if float(row.get('rewards_daily') or 0) <= 0:
        return False
    unit = _own_unit(top['mid'], row)
    if unit <= 0:
        return False
    rivals = _rival_score(live, top['mid'], row)
    if rivals <= 0:
        return False                # у середины никого — не встаём

    # ПЕРЕКОС НАГРАДЕ БЕЗРАЗЛИЧЕН, А НАШЕМУ ЗАПАСУ НЕТ.
    #
    # Книга с двадцатью контрактами по одной стороне и двадцатью тысячами по
    # другой — это рынок, уходящий в ноль. Награду там платят, но исполнят нас
    # тонкой стороной, и останется запас, который никому не нужен. Порог здесь
    # свой и много мягче основного: захвату спреда нужна соразмерность сторон,
    # награде — лишь бы вторая сторона существовала.
    bid_lots = sum(size for _, size in (live.get('bids') or []))
    ask_lots = sum(size for _, size in (live.get('asks') or []))
    if min(bid_lots, ask_lots) / max(bid_lots, ask_lots, 1e-9) < \
            params.MM_REWARD_MIN_BALANCE:
        return False
    size = max(float(row.get('order_min') or 0), params.MM_MIN_ORDER_SIZE)
    ours = _qualifying(unit * size, 0.0, top['mid'])
    if ours <= 0:
        return False
    return ours / (ours + rivals) <= params.MM_REWARD_MAX_SHARE


def _rival_score(live, mid, row):
    """Очки ЧУЖИХ заявок — то, с чем мы делим пул."""
    allowance = float(row.get('rewardsMaxSpread') or 0) / 100.0
    if allowance <= 0 or not live:
        return 0.0
    bids = sum(_spread_score(allowance, mid - price) * size
               for price, size in (live.get('bids') or []))
    asks = sum(_spread_score(allowance, price - mid) * size
               for price, size in (live.get('asks') or []))
    return _qualifying(bids, asks, mid)


def _own_unit(mid, row):
    """Очки за ОДИН контракт, если встать в тике от середины."""
    allowance = float(row.get('rewardsMaxSpread') or 0) / 100.0
    return _spread_score(allowance, float(row.get('tick') or 0.01))


def _qualifying(one, two, mid):
    """
    Зачётные очки из двух сторон — правило площадки целиком.

    В полосе 0.10..0.90 односторонняя ликвидность засчитывается с делением на
    три. Вне полосы — только двусторонняя: там min(одна, ноль) = ноль.
    """
    if 0.10 <= mid <= 0.90:
        return max(min(one, two), max(one, two) / REWARD_ONE_SIDED_PENALTY)
    return min(one, two)


def reward_per_hour(row, size, one_sided=False):
    """
    Сколько награда даст в час, если поставить столько-то контрактов.

    ФОРМУЛА ВЗЯТА У ПЛОЩАДКИ И СВЕРЕНА С ВЫПЛАТОЙ. Прежний расчёт делил пул
    пропорционально нашим долларам против всей глубины книги, и врал в обе
    стороны разом: на рынке «Democratic House retirements» он обещал $0.0011 в
    сутки там, где биржа заплатила $0.0767 — в семьдесят раз меньше factum, — а
    по счёту в целом сулил $2.85 в сутки при настоящих восьми центах.

    Настоящий счёт устроен иначе:

        S(v, s) = ((v − s) / v)²      v — допуск рынка, s — до середины
        Q       = сумма S × размер по каждой стороне
        зачёт   = max(min(Q₁, Q₂), max(Q₁, Q₂)/3)   при цене 0.10..0.90
                = min(Q₁, Q₂)                       вне этой полосы
        доля    = наш зачёт / (наш + чужой) × дневной пул

    ПРОВЕРЕНО НА ВЫПЛАТЕ: для нашей заявки в пять контрактов одной стороной
    формула даёт $0.0731 в сутки, биржа заплатила $0.0767. Расхождение 5%.

    ДВА СЛЕДСТВИЯ, КОТОРЫХ НЕ БЫЛО В ПРЕЖНЕЙ МОДЕЛИ. Первое: расстояние до
    середины входит В КВАДРАТЕ, поэтому стоять близко важнее, чем стоять
    крупно. Второе: вне полосы 0.10..0.90 односторонняя котировка не приносит
    ничего — а именно дешёвые рынки мы и выбирали, и именно на них стояли
    одной стороной.

    ПОРОГ РАЗМЕРА НЕ ОБНУЛЯЕТ. Здесь было записано обратное со ссылкой на
    ответ биржи о скоринге, и это оказалось неверно: заплатили как раз за
    пять контрактов при «пороге» двадцать. Порог решает, попадёт ли заявка в
    отдельный список поощряемых, но очки начисляются и без него.

    ЛОВУШКА, КОТОРАЯ НИКУДА НЕ ДЕЛАСЬ И СТОИЛА УЖЕ ТРЁХ РАЗБОРОВ. Доля тем
    больше, чем меньше чужих очков, — и наверх всплывают ПУСТЫЕ книги: пул $3
    при книге в $2 даёт «2744% в месяц», что означает не доход, а приглашение
    стать всем рынком сразу. Формула считает честно и потому в эту ловушку
    заводит сама; держит вход закрытым отсев по глубине книги ВЫШЕ, и снимать
    его можно только своим параметром.
    """
    pool = float(row.get('rewards_daily') or 0)
    if pool <= 0 or size <= 0:
        return 0.0
    unit = float(row.get('reward_unit') or 0)
    if unit <= 0:
        # Книги под рукой нет — считать нечем. Молчаливая единица здесь была бы
        # хуже нуля: она вернула бы прежнее враньё под новым именем.
        return 0.0
    mid = float(row.get('price') or 0.5)
    ours = unit * float(size)
    mine = _qualifying(ours, 0.0, mid) if one_sided else ours
    if mine <= 0:
        return 0.0
    rivals = float(row.get('reward_rivals') or 0)
    return pool * mine / (mine + rivals) / 24.0


def reward_size(row):
    """Размер, с которого рынок начинает платить награду. 0 — не платит."""
    if float(row.get('rewards_daily') or 0) <= 0:
        return 0.0
    floor = float(row.get('rewardsMinSize') or 0)
    return max(floor, _floor_size(row)) if floor else 0.0


def _step_options(ticks):
    """
    Возможные шаги внутрь спреда, в тиках. Ноль означает встать на лучшую цену.

    Шаг должен оставлять хотя бы тик: при спреде в шесть тиков глубже двух не
    уйти, иначе цены сойдутся и заявка станет тейкерской.
    """
    room = (ticks - 1) // 2
    return [0] + [d for d in (1, 2, 3, 5, 8, 12) if d <= room]


def _both_wait(queue_in, queue_out, size, flow_in, flow_out):
    """
    Часы до того, как исполнятся ОБЕ стороны. Бесконечность, если одной нет.

    Для независимых ожиданий со средними a и b среднее время, когда случатся
    оба, равно a + b − ab/(a+b): всегда меньше суммы и всегда больше большего
    из двух.
    """
    if flow_in <= 0 or flow_out <= 0:
        return float('inf')
    wait_in = (queue_in + size) / flow_in
    wait_out = (queue_out + size) / flow_out
    total = wait_in + wait_out
    return total - (wait_in * wait_out / total) if total > 0 else 0.0


def _recompute_wait(row):
    """
    Ожидание и доход под окончательный размер заявки.

    ОБЕ ЗАЯВКИ СТОЯТ ОДНОВРЕМЕННО, и это меняет арифметику. Прежде ожидания
    складывались, как будто мы сперва покупаем, потом выставляем продажу, —
    но бид и аск живут в стакане вместе, и часы у них идут параллельно.

    Для независимых ожиданий со средними a и b среднее время, когда случатся
    ОБА, равно a + b - ab/(a+b). Это всегда меньше суммы и всегда больше
    большего из двух: сложение завышало ожидание в полтора раза при равных
    сторонах, то есть занижало доход настолько же.
    """
    size = float(row['size'])
    both = _both_wait(row.get('queue_in', 0), row.get('queue_out', 0), size,
                      float(row.get('flow_in') or 0),
                      float(row.get('flow_out') or 0))
    row['wait_hours'] = round(both, 3) if both != float('inf') else both
    # ДОХОД ОТ СПРЕДА УМНОЖАЕТСЯ НА ТО, ЧТО МЫ ЗАБИРАЕМ НА САМОМ ДЕЛЕ.
    #
    # Модель считает, что обе стороны исполнятся по нашим ценам при неподвижной
    # середине. Замер по закрытым кругам говорит другое:
    #
    #     купили 0.554 → продали 0.527   −0.027   обещано +0.014
    #     купили 0.235 → продали 0.208   −0.027   обещано +0.019
    #     взято −$0.37 против обещанных +$0.97 — доля −41.6%
    #
    # В каждом убыточном круге мы продали ДЕШЕВЛЕ, чем купили: между двумя
    # исполнениями проходит время, и мейкера подбирают по одной стороне ровно
    # тогда, когда вторая уже невыгодна.
    #
    # Ноль вместо отрицательного — намеренно. Отрицательная доля означает «на
    # спред рассчитывать нельзя», а не «спред отнимает деньги пропорционально
    # ставке»: второе было бы додумыванием сверх замера.
    # Доля берётся ИЗ СТРОКИ, а не считается здесь: замер читает журнал с
    # диска, а эта функция вызывается на каждый рынок и каждый размер. Отбор
    # спрашивает один раз и кладёт ответ в строку.
    capture = float(row.get('capture', 1.0))
    row['usd_per_hour'] = round(
        size * row['our_gain'] * capture / row['wait_hours'], 5) \
        if row['wait_hours'] not in (0, float('inf')) else 0.0
    return row


def _capture_factor():
    """
    Какую долю обещанного спреда мы забираем. Единица, пока замерять нечего.

    Ограничена сверху единицей: забрать больше, чем оставляет спред, нельзя, и
    если замер это показал — значит нам просто везло, а не модель занижает.

    Ограничена снизу нулём НАМЕРЕННО. Отрицательная доля означает «на спред
    рассчитывать нельзя»; переносить минус в план значило бы утверждать, что
    спред отнимает деньги пропорционально ставке, — а этого замер не говорит.
    """
    try:
        from . import stats
        got = stats.capture_factor()
    except Exception:                                       # noqa: BLE001
        return 1.0
    if got is None:
        return 1.0                  # кругов мало — идём по модели, как раньше
    return max(0.0, min(1.0, float(got)))


def size_for(row, budget):
    """
    Размер заявки от ПОТОКА рынка, с тремя потолками.

    Пятёрка на всё подряд оставляла деньги без дела: после отсева по времени
    остаётся горстка рынков, и на них уходило $30 из ста. Поток при этом
    измерен и известен — по нему и считаем.

    ТРИ ПОТОЛКА, КАЖДЫЙ ОТ СВОЕЙ БЕДЫ. Доля потока: больше, чем рынок
    пропускает, взять нельзя — остаток заявки простоит и исказит наш же замер
    ожидания. Доля счёта: один рынок не должен решать судьбу счёта. Доля
    стакана: быть большей частью книги значит двигать цену собой.
    """
    flow = min(float(row.get('flow_in') or 0), float(row.get('flow_out') or 0))
    by_flow = flow * params.MM_FLOW_HOURS
    by_money = budget * params.MM_MAX_MARKET_SHARE
    by_book = min(float(row.get('bid_usd') or 0),
                  float(row.get('ask_usd') or 0)) * params.MM_MAX_BOOK_SHARE
    size = min(by_flow, by_money, by_book)
    floor = max(float(row.get('order_min') or 0), params.MM_MIN_ORDER_SIZE)
    return floor if size < floor else float(int(size))


def as_yes(trades, token_yes, token_no):
    """
    Сделки ОБОИХ токенов, приведённые к нашей стороне.

    ЗДЕСЬ ПРЯТАЛАСЬ САМАЯ КРУПНАЯ ОШИБКА ЗАМЕРА. У бинарного рынка два токена,
    и покупка «нет» по цене q экономически есть продажа «да» по цене (1-q).
    Считая сделки только своего токена, мы видели меньшую часть потока:

        «Will Nigel Farage win at least 80%» — 25 продаж «да» в нашем счёте
        против 363 настоящих, потому что 338 покупок «нет» мы не считали вовсе.

    Из-за этого 276 рынков из 327 объявлялись «без потока с одной стороны» и
    выбрасывались. Отбор считал мёртвыми ровно те рынки, где торговля шла
    через встречный токен.

    Цена зеркалится, сторона переворачивается. Размер остаётся: контракт «нет»
    и контракт «да» — одна и та же единица.
    """
    out = []
    for trade in trades or []:
        asset = trade.get('asset')
        if asset == token_yes:
            out.append(trade)
        elif token_no and asset == token_no:
            out.append({**trade,
                        'price': round(1.0 - float(trade['price']), 10),
                        'side': 'SELL' if trade['side'] == 'BUY' else 'BUY'})
    return out


def depth_at(book, side, price):
    """Контрактов на этой самой цене — очередь, если встать рядом."""
    levels = book['bids'] if side == 'bid' else book['asks']
    return sum(size for lvl, size in levels if abs(lvl - price) < 1e-9)


def measure_wait(rows, books, limit=None):
    """
    Сколько ЖДАТЬ исполнения — вот что решает, а не ширина спреда.

    СОБСТВЕННАЯ ОШИБКА, ИСПРАВЛЕННАЯ ЗАМЕРОМ. Рынки со спредом в один тик
    отбрасывались на том основании, что впереди стоит 152 контракта по медиане.
    Длина очереди мерилась на МЕДЛЕННЫХ рынках и была перенесена на все.

    Очередь важна не длиной, а временем. Замер по 53 рынкам: у шести ожидание
    меньше часа, медиана 23 минуты, и почти все они — как раз однотиковые.
    «Will Alexandria Ocasio-Cortez win...»: очередь 9 контрактов при потоке 530
    в час, то есть ОДНА МИНУТА. Такой рынок мы выбрасывали.

    Спред узок там именно потому, что торгуют, — и там же очередь рассасывается.

        время до исполнения = (очередь + наш размер) / поток

    Формула одна на оба случая. Шагнув внутрь, мы создаём новый уровень, где
    очередь равна нулю, и ждём только собственный размер. Встав на лучшую цену,
    ждём ещё и всех, кто пришёл раньше.
    """
    day = 24 * 3600
    now = time.time()
    # ЛЕНТЫ БЕРУТСЯ РАЗОМ, И ЭТО ВОПРОС ОХВАТА, А НЕ СКОРОСТИ. Поодиночке
    # девятьсот рынков занимали семь минут, поэтому мерились первые сто
    # восемьдесят — а какие в них попадут, решал порядок выдачи биржи.
    # Ликвидные, но непопулярные рынки лежат в хвосте любой выдачи: мы их не
    # отвергали, мы до них не доходили. Теперь доходим до всех.
    subset = rows[:int(limit)] if limit else rows
    tapes = book_mod.tape_many([r['condition_id'] for r in subset])
    for row in subset:
        live = books.get(str(row['token_id']))
        trades = tapes.get(row['condition_id']) or []
        mine = [t for t in as_yes(trades, row['token_id'], row.get('token_no'))
                if now - t['ts'] < day]
        # СКОРОСТЬ СЧИТАЕТСЯ ПО СВЕЖЕСТИ, А НЕ СРЕДНИМ ЗА СУТКИ.
        #
        # ЗДЕСЬ БЫЛА ГЛАВНАЯ ПРИЧИНА, ПО КОТОРОЙ НИЧЕГО НЕ ИСПОЛНЯЛОСЬ.
        # Знаменателем служил промежуток от первой сделки до последней — и
        # сгусток превращался в мнимую скорость. Первая правка перенесла
        # знаменатель на «до сейчас», но этого мало: усреднение за сутки всё
        # равно выдаёт вчерашнюю толчею за сегодняшний поток.
        #
        #     «Arc launch a token»   обещанный круг 46 минут
        #                            тишина на деле восемь часов
        #     «Base FDV above $10B»  обещанный круг 43 минуты
        #                            тишина на деле семь часов
        #
        # Заявка стоит СЕЙЧАС, и значение имеет то, что происходит сейчас.
        # Вес сделки падает как exp(−возраст/срок), знаменатель — тот же
        # интеграл по окну. Для рынка с ровным потоком оценка не меняется: за
        # сутки при сроке в три часа интеграл равен трём часам, и десять
        # контрактов в час так и остаются десятью. Сгусток же двадцатичасовой
        # давности сжимается в семьсот раз и перестаёт звать нас на мёртвый
        # рынок.
        #
        # Проверка вселенной, 400 рынков наугад: за час торгует лишь 11%.
        # Мёртвый рынок — это НОРМА, и отбор обязан отличать его на глаз.
        decay = max(params.MM_FLOW_DECAY_HOURS, 1e-6)
        for t in mine:
            t['weight'] = math.exp(-((now - t['ts']) / 3600) / decay)
        span = decay * (1 - math.exp(-(day / 3600) / decay))
        top = row.get('top') or (book_mod.top(live) if live else None)
        if not top or not live:
            row['wait_hours'] = float('inf')
            continue
        sells = [t for t in mine
                 if t['side'] == 'SELL' and t['price'] <= top['bid'] + 1e-9]
        buys = [t for t in mine
                if t['side'] == 'BUY' and t['price'] >= top['ask'] - 1e-9]
        flow_in = sum(t['size'] * t['weight'] for t in sells) / span
        flow_out = sum(t['size'] * t['weight'] for t in buys) / span
        size = row.get('size') or params.MM_MIN_ORDER_SIZE
        ticks = int(round(top['spread'] / row['tick'])) if row['tick'] > 0 else 0

        # ГЛУБИНА ШАГА ПОДБИРАЕТСЯ, А НЕ БЕРЁТСЯ В ОДИН ТИК.
        #
        # Шаг в один тик был произволом, и замер показал, насколько дорогим.
        # На широком спреде заявка в тик от лучшей цены стоит ДАЛЕКО от
        # середины, и до неё почти никто не доходит:
        #
        #     «Khvicha Kvaratskhelia», спред 21 тик
        #         шаг 1 тик:  остаётся 0.0190, поток   13.1 контр/ч
        #         шаг 5 тик:  остаётся 0.0110, поток  225.6 контр/ч
        #
        # Поток вырос в семнадцать раз, спред упал вдвое — произведение
        # выросло вдесятеро. По четырём рынкам подбор дал вдевятеро больше
        # жёсткого тика.
        #
        # ШАГ ВЫБИРАЕТСЯ ПО ДОХОДУ В ЧАС, А НЕ ПО ПРОИЗВЕДЕНИЮ «СПРЕД НА ПОТОК».
        #
        # Прежняя мера не смотрела на ОЧЕРЕДЬ и потому раз за разом выбирала
        # худшее. Разобрано на проверке, которая это и поймала:
        #
        #     спред три тика, поток 158 контрактов в час, впереди 2000
        #         шаг 0:  берём 0.03, но стоим за очередью → круг 18.8 часа
        #         шаг 1:  берём 0.01 при пустой очереди    → круг 0.05 часа
        #
        # Старая мера предпочитала первый: тройной спред перевешивал. А он в
        # четыреста раз медленнее, и рынок отсеивался как безнадёжный — при том
        # что круг там три минуты.
        #
        # Доход в час — это «что остаётся», делённое на время круга, и очередь
        # входит в него там, где ей место.
        best = None
        for depth in _step_options(ticks):
            if depth == 0:
                price_bid, price_ask = top['bid'], top['ask']
                q_in = depth_at(live, 'bid', top['bid'])
                q_out = depth_at(live, 'ask', top['ask'])
            else:
                price_bid = top['bid'] + depth * row['tick']
                price_ask = top['ask'] - depth * row['tick']
                q_in = q_out = 0.0
            take = price_ask - price_bid
            if take <= 0:
                continue
            f_in = sum(t['size'] * t['weight'] for t in mine
                       if t['side'] == 'SELL'
                       and t['price'] <= price_bid + 1e-9) / span
            f_out = sum(t['size'] * t['weight'] for t in mine
                        if t['side'] == 'BUY'
                        and t['price'] >= price_ask - 1e-9) / span
            score = take / _both_wait(q_in, q_out, size, f_in, f_out)
            if best is None or score > best['score']:
                best = {'score': score, 'depth': depth, 'gain': take,
                        'flow_in': f_in, 'flow_out': f_out,
                        'queue_in': q_in, 'queue_out': q_out}
        if best is None:
            row['wait_hours'] = float('inf')
            continue

        row['step_ticks'] = best['depth']
        row['step_inside'] = best['depth'] > 0
        row['flow_in'] = round(best['flow_in'], 1)
        row['flow_out'] = round(best['flow_out'], 1)
        # Очереди сохраняются, потому что время придётся пересчитать: размер
        # заявки выбирается ПОЗЖЕ, а ждать большую заявку дольше.
        row['queue_in'] = round(best['queue_in'], 1)
        row['queue_out'] = round(best['queue_out'], 1)
        row['our_gain'] = round(max(best['gain'], 0.0), 6)
        _recompute_wait(row)
    for row in rows:
        row.setdefault('wait_hours', float('inf'))
        row.setdefault('usd_per_hour', 0.0)
        row.setdefault('our_gain', 0.0)
        row.setdefault('step_inside', False)
    return rows


def _cap_per_event(rows):
    """
    Не больше нескольких рынков одного события.

    «США ударят по 8 странам» и «США ударят по 9 странам» — один и тот же
    вопрос, заданный дважды: запас по ним набирается ОДИНАКОВЫЙ и одинаково
    же обесценивается. Двадцать рынков одного события — это одна ставка с
    двадцатикратным размером, притом выглядящая как разнообразие.
    """
    seen, out = {}, []
    for row in rows:
        key = row.get('event_id') or row['condition_id']
        if seen.get(key, 0) >= params.MM_MAX_PER_EVENT:
            continue
        seen[key] = seen.get(key, 0) + 1
        out.append(row)
    return out


def _floor_size(market):
    """Наименьший размер, который примет биржа на этом рынке."""
    return max(float(market.get('order_min') or 0), params.MM_MIN_ORDER_SIZE)


def allocate(markets, budget=None):
    """
    Раскладывает бюджет по рынкам: СНАЧАЛА ОХВАТ, ПОТОМ ДОБАВКА.

    ПОЧЕМУ ИМЕННО В ТАКОМ ПОРЯДКЕ — это исправление, а не вкусовщина. Раньше
    размер заявки считался как доля счёта (34%), и деньги кончались на третьем
    рынке: сорок долларов уходили в три рынка по тринадцать. Человек спрашивал
    «почему у меня только три направления, я просил максимум» — и был прав.

    Добавка сверх минимума почти ничего не даёт там, где перед нами нет
    очереди. Время ожидания растёт вместе с размером — (очередь + размер) /
    поток, — поэтому при пустой очереди доход в час от размера НЕ ЗАВИСИТ
    вовсе: вдвое больший размер ждёт вдвое дольше. Добавка окупается только
    там, где впереди стоит очередь: её мы ждём в любом случае, и чем больше
    заявка, тем больше приходится на то же ожидание.

    Замерено на 1 243 рынках при $40:

        как было (34% на рынок)     5 рынков, вложено $35, $0.90/час
        охват по минимуму           8 рынков, вложено $40, $1.00/час

    То есть больше рынков, больше задействованных денег и на одиннадцать
    процентов больше расчётного дохода — одним изменением порядка раскладки.

    ПРЕДЕЛ НА ОДИН РЫНОК остаётся: одно исполнение не должно сажать в позицию
    половину счёта. Он теперь ограничивает добавку, а не выедает бюджет сразу.
    """
    budget = float(budget if budget is not None else params.bankroll_for('MM'))

    # ПРЕДЕЛ НА РЫНОК НЕ МОЖЕТ БЫТЬ НИЖЕ МИНИМУМА БИРЖИ. При $10 доля в 34%
    # даёт $3.40, а дешевле $5 котировку не выставить вовсе — и раскладка
    # отвергала ВСЕ рынки до единого, молча возвращая пустой план. Снаружи это
    # «бот запущен и никуда не встал», без единого слова о причине.
    #
    # Смысл предела — чтобы один рынок не решал судьбу счёта. При десяти
    # долларах и минимуме в пять любой рынок это половина счёта, и поделать с
    # этим нечего: так устроена биржа, а не наш выбор. Честный ответ —
    # встать на двух рынках и сказать об этом, а не стоять нигде.
    cap = max(budget * params.MM_MAX_MARKET_SHARE, params.MM_MIN_ORDER_SIZE)

    # ── Проход первый: охват. Каждому рынку по минимуму, лучшие первыми.
    chosen, used = [], 0.0
    for market in markets:
        # СЛАБЫЕ РЫНКИ НЕ БЕРЁМ ДАЖЕ ПРИ СВОБОДНЫХ ДЕНЬГАХ. «Ещё один рынок»
        # звучит как разнообразие, но рынок с доходом в цент за час — это
        # деньги, вынутые из работающих. Замерено: при $100 добавление
        # четырнадцати рынков вместо восьми снижало расчётный доход с $1.30 до
        # $1.09 в час.
        if float(market.get('usd_per_hour') or 0) < params.MM_MIN_USD_PER_HOUR:
            continue
        size = _floor_size(market)
        cost = quote_cost(size, market['price'])
        if cost > cap or used + cost > budget:
            continue
        market['size'] = size
        market['cost'] = round(cost, 2)
        _recompute_wait(market)
        chosen.append(market)
        used += cost

    # ── Проход второй: добавка тем, кому она что-то даёт.
    #
    # Порядок прежний — лучшие первыми, — но растём только пока растёт доход в
    # час. На рынке без очереди он не растёт вовсе, и добавка там означала бы
    # деньги, лежащие без дела под видом работы.
    for market in chosen:
        room = min(budget - used, cap - market['cost'])
        if room < 1:
            continue

        # РОСТ РАДИ НАГРАДЫ СЧИТАЕТСЯ ОТДЕЛЬНО ОТ РОСТА РАДИ СПРЕДА.
        #
        # Награда включается СТУПЕНЬКОЙ: до порога она равна нулю, после —
        # сразу заметна. Обычный поиск «растём, пока растёт доход в час» такую
        # ступеньку не находит, потому что первый же шаг ничего не даёт.
        #
        # Замерено на 256 рынках с живой книгой: лучшие дают сто-двести
        # процентов в месяц на вложенное, тогда как захват спреда за ночь
        # принёс полцента. Порог везде двадцать контрактов, и наши пять под
        # награду не попадали ни разу — спрошено у биржи про пятнадцать
        # стоящих заявок, скоринг ноль из пятнадцати.
        wanted = reward_size(market)
        if wanted and market['size'] < wanted:
            cost = quote_cost(wanted, market['price'])
            gain = reward_per_hour(market, wanted)
            # НАГРАДА ПРЕДПОЧИТАЕТСЯ РАСЧЁТНОМУ СПРЕДУ, и это решение принято
            # по делу, а не по вкусу. Доход от спреда — ОЦЕНКА модели, и она
            # пока не сбылась: за сутки четыре круга и минус тридцать центов
            # при обещанных сотнях в месяц. Награда же проверена отправкой:
            # биржа ответила scoring=True и платит её независимо от того,
            # закроется круг или нет.
            #
            # Поэтому сравниваем не с полной оценкой спреда, а с её долей.
            # Единица здесь означала бы «верим модели как факту» — а мы уже
            # знаем, что верить нельзя.
            worth = market['usd_per_hour'] * params.MM_REWARD_PREFER
            if (cost <= cap and used - market['cost'] + cost <= budget
                    and gain > worth):
                used += cost - market['cost']
                market['size'] = wanted
                market['cost'] = round(cost, 2)
                market['reward_per_hour'] = round(gain, 5)
                _recompute_wait(market)
                market['usd_per_hour'] = round(
                    market['usd_per_hour'] + gain, 5)
                room = min(budget - used, cap - market['cost'])

        ceiling = size_for(market, budget)
        while room >= 1 and market['size'] < ceiling:
            probe = dict(market)
            probe['size'] = min(float(int(market['size'] + max(1, market['size'] * 0.5))),
                                ceiling)
            _recompute_wait(probe)
            gain = probe['usd_per_hour'] - market['usd_per_hour']
            spent = quote_cost(probe['size'], market['price']) - market['cost']
            if gain <= 1e-9 or spent > room:
                break
            market['size'] = probe['size']
            market['cost'] = round(quote_cost(probe['size'], market['price']), 2)
            market['wait_hours'] = probe['wait_hours']
            market['usd_per_hour'] = probe['usd_per_hour']
            used += spent
            room = min(budget - used, cap - market['cost'])

    # ── Проход третий: остаток денег в награду.
    #
    # Захват спреда насыщается: годных рынков четырнадцать, и стоят они $14.70.
    # Остальное лежало без дела. Награда принимает капитал дальше и платится за
    # стояние, а не за закрытый круг, — значит именно ей и место в остатке.
    #
    # Отбираются по доходу НА ВЛОЖЕННЫЙ ДОЛЛАР: пул делится по объёму, поэтому
    # тонкая книга при щедром пуле даёт больше, чем толстая при таком же.
    # Пороги качества книги при этом те же, что и везде, — иначе наверх всплыли
    # бы пустые книги, и эта ловушка в проекте описана трижды.
    taken = {id(m) for m in chosen}
    pool = [m for m in markets
            if id(m) not in taken and m.get('pays_reward')]
    # СТОРОННОСТЬ ВЫБИРАЕТСЯ СЧЁТОМ, А НЕ УМОЛЧАНИЕМ.
    #
    # Одна сторона даёт треть очков, но и стоит она min(p, 1−p) вместо целого
    # доллара за контракт. На рынке по 0.26 это втрое меньше очков за впятеро
    # меньшие деньги — то есть выгоднее. А на рынке по 0.05 одна сторона даёт
    # РОВНО НОЛЬ: вне полосы 0.10..0.90 зачёт равен min(Q₁, Q₂).
    #
    # Поэтому считаем оба способа и берём тот, что даёт больше на вложенный
    # доллар. Замер по всей выдаче: при $40 лучшая раскладка — двадцать рынков,
    # пять из них двусторонних, $1.85 награды в сутки. Наш прежний счёт при том
    # же бюджете принёс восемь центов.
    for market in pool:
        market['reward_stake'] = reward_size(market)
    pool = [m for m in pool if m['reward_stake']]
    for market in pool:
        best = None
        for one_sided in (True, False):
            size = market['reward_stake']
            cost = quote_cost(size, market['price'], one_sided=one_sided)
            gain = reward_per_hour(market, size, one_sided=one_sided)
            if gain <= 0 or cost <= 0:
                continue
            rate = gain / cost
            if best is None or rate > best['rate']:
                best = {'rate': rate, 'one_sided': one_sided, 'cost': cost,
                        'gain': gain}
        market['reward_rate'] = best['rate'] if best else 0.0
        market['reward_plan'] = best
    pool = [m for m in pool if m.get('reward_plan')]
    pool.sort(key=lambda m: -m['reward_rate'])
    for market in pool:
        size = market['reward_stake']
        cost = market['reward_plan']['cost']
        if cost > cap or used + cost > budget:
            continue
        gain = market['reward_plan']['gain']
        market['reward_one_sided'] = market['reward_plan']['one_sided']
        if gain <= 0:
            continue
        market['size'] = size
        market['cost'] = round(cost, 2)
        market['reward_per_hour'] = round(gain, 5)
        market['reward_only'] = True
        _recompute_wait(market)
        market['usd_per_hour'] = round(market['usd_per_hour'] + gain, 5)
        chosen.append(market)
        used += cost

    edge = sum(m['spread_share'] * m['cost'] / 2 for m in chosen)
    # СВОДКА ПО НАГРАДЕ СЧИТАЕТСЯ ТОЙ ЖЕ ФОРМУЛОЙ, ЧТО И ОТБОР. Здесь стояла
    # своя — доля от глубины книги, — и панель показывала сотни процентов в
    # месяц там, где биржа платила центы. Две разные формулы на одно число
    # означают, что неверна хотя бы одна.
    rewards = sum(
        reward_per_hour(m, m['size'],
                        one_sided=bool(m.get('reward_one_sided'))) * 24
        for m in chosen)
    return {
        'markets': chosen, 'used': round(used, 2),
        'free': round(budget - used, 2), 'cap_per_market': round(cap, 2),
        # ПОТОЛОК дохода за один оборот всех рынков, а не ожидание. Считается
        # как половина спреда на вложенное — то есть при условии, что обе
        # стороны исполнились по нашим ценам и ни разу не против нас. Ни того,
        # ни другого мы пока не наблюдали: бумажный прогон не дал исполнений.
        'ceiling_per_round_usd': round(edge, 3),
        'rewards_daily': round(rewards, 3),
        'rewards_monthly': round(rewards * 30, 2),
    }
