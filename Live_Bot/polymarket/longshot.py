"""
Продажа дешёвых лонгшотов. ВАЛИДАЦИЯ ПРОВАЛЕНА — модуль только для бумаги.

СПЕЦИФИКАЦИЯ САМА ТРЕБУЕТ ЭТУ ПРОВЕРКУ ПЕРВЫМ ШАГОМ и говорит прямо: если
реальная частота срабатывания не ниже подразумеваемой ценой — стратегию в
текущем виде не разворачивать. Проверка проведена на 1706 разрешённых рынках и
751 независимом событии, и вот её итог по целевому диапазону:

    цена YES        рынков  событий   YES сбылся   чистый «No»
    0.001-0.005         33       26        0.00%       +0.0022
    0.005-0.010         22       20        0.00%       +0.0063
    0.010-0.020         32       28        3.12%       -0.0180
    0.020-0.050         44       41        2.27%       +0.0074
    0.050-0.100         71       66        9.86%       -0.0316

В ДИАПАЗОНЕ $0.01-0.02, КОТОРЫЙ СПЕЦИФИКАЦИЯ РЕКОМЕНДУЕТ ПРЯМО, СМЕЩЕНИЕ ИДЁТ В
ОБРАТНУЮ СТОРОНУ: лонгшоты сбывались вдвое чаще, чем заложено в цену, и продажа
их теряет. То же в диапазоне 0.05-0.10.

ДВЕ ВЕРХНИЕ СТРОКИ — НЕ ПОДТВЕРЖДЕНИЕ, А ЛОВУШКА. Там ноль сбывшихся исходов, и
узкий доверительный интервал получается по построению: бутстрап пересэмплирует
наблюдённые исходы, а раз проигрышей не наблюдалось, ни в одной выборке их не
будет. По правилу трёх при 26 событиях без единого срабатывания верхняя граница
вероятности равна 11.5%, тогда как безубыток при цене 0.0023 требует значения
НИЖЕ 0.23%. Мы в пятьдесят раз не дотягиваем до нужной точности.

Асимметрия при этом предельная: выигрыш +0.23%, проигрыш -99.77%. Одно
срабатывание съедает 430 удачных ставок.

ДОВЕСТИ ВАЛИДАЦИЮ НЕЧЕМ. Спецификация требует «тысячи» наблюдений; в диапазоне
дешевле двух центов доступно 87 рынков и 74 события. Больше не собрать: история
цен у площадки живёт 30-40 суток, это измерено отдельно. Чтобы набрать тысячи,
нужны годы, которых площадка не отдаёт.

ПОЭТОМУ МОДУЛЬ РАБОТАЕТ ТОЛЬКО В БУМАГЕ. Живое исполнение он не предлагает
никогда, независимо от настроек: `Decision.action` не бывает 'EXECUTE'. Это
поведение закреплено тестом, а не соглашением.
"""

import json

from . import client, params

VALIDATION_PASSED = False
VALIDATION_NOTE = (
    'смещение «фаворит-лонгшот» на 1706 рынках и 751 событии не подтверждено: '
    'в диапазоне 0.01-0.02 оно обратное (3.12% против 1.42% в цене), а в более '
    'дешёвых корзинах выборки хватает лишь на верхнюю границу 11.5% при '
    'требуемых 0.23%'
)

# Диапазон из спецификации. Оставлен как есть, чтобы бумажный прогон повторял
# именно её замысел, а не исправленную версию.
SPEC_MIN = 0.002
SPEC_MAX = 0.02


def candidates(markets, low=SPEC_MIN, high=SPEC_MAX):
    """
    Рынки, где сторона «No» стоит дорого, а «Yes» дёшево.

    Возвращает ставку на «No»: цена входа 1 - p, выигрыш 1. Издержки считаются
    от цены ВХОДА, то есть от 1 - p, а не от p — на дорогой стороне они малы, и
    это единственное, что в этой стратегии выглядит благополучно.
    """
    out = []
    for m in markets:
        try:
            price_yes = float(json.loads(m.get('outcomePrices') or '[]')[0])
        except Exception:                                  # noqa: BLE001
            continue
        if not low <= price_yes < high:
            continue
        entry = 1 - price_yes
        rate = client.fee_rate(m)
        out.append({
            'market': m,
            'side': 'NO',
            'price': entry,
            # Наша «модель» здесь — это и есть заявленное смещение: мы
            # утверждаем, что YES сбывается РЕЖЕ цены. Множитель взят из
            # спецификации как гипотеза, а не как измеренная величина, и
            # именно он замером не подтвердился.
            'model': 1 - price_yes * 0.5,
            'cost': client.entry_cost(entry, rate),
            'liquidity': float(m.get('liquidity') or 0),
            'category': m.get('feeType'),
            'event': ((m.get('events') or [{}])[0]).get('id'),
        })
    return out


def evaluate(signal, manager, open_positions=None):
    """
    Решение по ставке. Живое исполнение НЕ ПРЕДЛАГАЕТСЯ никогда.

    Слой риска возвращает 'PROPOSE' для годных ставок; здесь это сохраняется,
    но помечается как бумажное. Отдельная проверка нужна потому, что общий
    слой риска ничего не знает о провале валидации, а знать он и не должен:
    его дело — размеры и лимиты.
    """
    decision = manager.evaluate(signal, open_positions)
    if decision.action == 'PROPOSE':
        decision.details['paper_only'] = True
        decision.details['validation'] = VALIDATION_NOTE
        decision.reason = f'ТОЛЬКО БУМАГА: {decision.reason}'
    return decision


def live_trading_allowed():
    """Всегда False, пока валидация не пройдена. Читается исполнителем."""
    return bool(VALIDATION_PASSED) and not params.PAPER
