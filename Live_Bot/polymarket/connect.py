"""
Подключение кошелька из панели: проверка ключа и запись настройки.

ПОЧЕМУ ЭТО ВСЁ-ТАКИ РАЗРЕШЕНО. Долгое время ключ Polymarket принимался только
из окружения, а панель считалась негодной: она слушает без пароля, и секрет,
прошедший через неё, надо считать раскрытым. Довод верный, но применялся он
непоследовательно — ключи БИРЖИ в этом же приложении давно задаются из панели,
проверяются и пишутся в .env. Особый случай для Polymarket ничем не
обосновывался, кроме привычки, и оставлял человека с сервером без способа
подключить кошелёк вообще: консоли там нет.

ЧЕМ ЭТОТ КЛЮЧ ОТЛИЧАЕТСЯ ОТ БИРЖЕВОГО, И ЭТО РАЗЛИЧИЕ НАСТОЯЩЕЕ. Ключ биржи
можно урезать в правах — запретить вывод, оставить только торговлю. Приватный
ключ Polygon урезать нельзя: он распоряжается ВСЕМ, что лежит на адресе, и
подписывает любую операцию, включая перевод всего остатка. Поэтому:

    кошелёк для бота заводится ОТДЕЛЬНЫЙ, и на нём лежит только та сумма,
    которой не жаль в эксперименте.

Это сказано в панели прямым текстом, а не спрятано в документации.

ТРИ ПРАВИЛА, КОТОРЫЕ ЗДЕСЬ СОБЛЮДАЮТСЯ ВСЕГДА:

    1. Ключ НИКОГДА не отдаётся обратно. Наружу уходит только адрес и признак
       «настроен» — по адресу всё видно и ничего нельзя подписать.
    2. Ключ проверяется ДО записи. Записать непроверенный значит узнать о
       негодности в момент первой сделки, а не в момент настройки.
    3. Подключение кошелька НЕ включает живую торговлю. Для неё нужен
       отдельный, явный переключатель — иначе одно действие делало бы два.
"""

import os
import re

from . import params, wallet

KEY_RE = re.compile(r'^(0x)?[0-9a-fA-F]{64}$')
ADDRESS_RE = re.compile(r'^0x[0-9a-fA-F]{40}$')


def mask(value):
    """
    Ключ в виде, годном для показа: начало, конец и длина.

    Полностью скрывать нельзя — человек должен видеть, что записалось именно
    то, что он вводил. Показывать целиком нельзя тем более.
    """
    text = str(value or '')
    if len(text) < 12:
        return '—'
    return f'{text[:6]}…{text[-4:]} ({len(text)} знаков)'


# ТИПЫ ПОДПИСИ У ПЛОЩАДКИ, И ПОЧЕМУ ИХ ПРИХОДИТСЯ ПОДБИРАТЬ.
#
#     0  EOA           ключ сам владеет деньгами; счёт равен адресу ключа
#     1  POLY_PROXY    вход по почте: деньги на прокси, ключ только подписывает
#     2  GNOSIS_SAFE   вход кошельком-расширением: деньги на сейфе Gnosis
#
# Угадать со стороны нельзя. Тип зависит от того, КАК человек когда-то завёл
# счёт на площадке, а не от того, какой у него кошелёк сейчас: один и тот же
# Phantom даёт тип 0, если торговать прямо с адреса, и тип 2, если площадка
# завела для него сейф. Документация площадки на этот счёт противоречит сама
# себе — в одном месте для расширений назван тип 0, в другом тип 2.
#
# Поэтому мы не спрашиваем и не гадаем, а ПРОБУЕМ: верный тот, с которым биржа
# выдаёт учётные данные. Ошибиться здесь молча дороже всего — заявки уходили бы
# от имени счёта, на котором нет денег, и отвергались бы без внятной причины.
# ТИП 3 СТОИТ ПЕРВЫМ, И ЭТО ЕДИНСТВЕННЫЙ РАБОЧИЙ. Проверено отправкой настоящей
# заявки: типы 0, 1 и 2 проходят вход, но на отправке отвечают «maker address
# not allowed, please use the deposit wallet flow» — все три, при любом счёте.
# Площадка перешла на CTF Exchange v2, где подпись даёт смарт-контракт.
#
# Остальные оставлены в переборе: у старых счетов, заведённых до перехода,
# может работать иное, и отнимать эту возможность из уверенности вредно.
SIGNATURE_TYPES = (3, 0, 1, 2)
SIGNATURE_NAMES = {0: 'ключ владеет деньгами напрямую',
                   1: 'счёт-прокси (вход по почте)',
                   2: 'сейф Gnosis (вход кошельком-расширением)',
                   3: 'подпись смарт-контрактом (новая биржа)'}


def check(private_key, funder=None):
    """
    Проверяет ключ, НЕ записывая его. Возвращает (годен, адрес, причина).

    Проверка идёт тем же способом, каким потом пойдёт бот: ключ подставляется
    в окружение временно, поднимается настоящий торговый клиент, спрашивается
    адрес. Иначе «проверено» означало бы «похоже на ключ», а это не проверка.

    Тип подписи ПОДБИРАЕТСЯ перебором, если не задан явно: см. выше, почему
    угадать его со стороны нельзя.
    """
    key = str(private_key or '').strip()
    if not KEY_RE.match(key):
        # ОТКАЗ ОБЪЯСНЯЕТ, ЧТО ИМЕННО НЕ ТО. «Ключ должен быть 64 знака»
        # верно, но бесполезно: человек не знает, что у него в руках другое.
        # Чаще всего вставляют секретную ФРАЗУ — она порождает множество
        # ключей и потому опаснее любого из них; принимать её мы не станем.
        if len(key.split()) >= 6:
            return False, None, (
                'это секретная фраза, а нужен приватный КЛЮЧ одного адреса. '
                'Фраза распоряжается всеми кошельками сразу, и хранить её боту '
                'нельзя. В Phantom: Настройки → Управление аккаунтами → нужный '
                'аккаунт → Показать приватный ключ. Берите ключ EVM-аккаунта, '
                'не Solana')
        if ADDRESS_RE.match(key):
            return False, None, ('это АДРЕС, а не ключ: адрес короче вдвое и '
                                 'подписывать им нельзя')
        return False, None, ('ключ должен быть 64 знака из цифр и букв a-f. '
                             f'Введено {len(key)} знаков')
    if funder and not ADDRESS_RE.match(str(funder).strip()):
        return False, None, 'адрес счёта должен быть вида 0x и 40 знаков'

    saved = {name: os.environ.get(name) for name in
             ('PM_PRIVATE_KEY', 'PM_FUNDER', 'PM_SIGNATURE_TYPE')}
    try:
        os.environ['PM_PRIVATE_KEY'] = key
        address = wallet.address()
        if not address:
            return False, None, 'ключ не удалось прочитать как приватный'

        # ПОДБИРАЕМ СВЯЗКУ ЦЕЛИКОМ, А НЕ ТОЛЬКО ТИП ПОДПИСИ.
        #
        # Человеку неоткуда знать, какой у него случай: деньги могут лежать на
        # самом кошельке, а могут — на счёте, который площадка завела при
        # первом входе. Спрашивать об этом значит спрашивать о внутреннем
        # устройстве чужого сервиса.
        #
        # Поэтому перебираем сочетания и выбираем то, где ЕСТЬ ДЕНЬГИ: это
        # единственный признак, который нельзя истолковать двояко. Учётные
        # данные площадка выдаёт почти на любую связку — по ним верную не
        # отличить, а по остатку отличить можно.
        candidates = []
        for money_at in ([str(funder).strip()] if funder else []) + [address]:
            for sig in SIGNATURE_TYPES:
                candidates.append((money_at, sig))

        # СОХРАНЁННЫЙ ТИП ПОДПИСИ НЕ ЗАПИРАЕТ ПОДБОР, а только идёт первым.
        #
        # ЭТО И БЫЛО ПРИЧИНОЙ «ОСТАТОК $0.00» У ЧЕЛОВЕКА, У КОТОРОГО ВСЁ
        # ОСТАЛЬНОЕ РАБОТАЛО. Прежняя версия подбирала тип из 0, 1, 2 — тогда
        # ещё не было известно, что нужен третий, — и записывала найденный в
        # настройки. Следующая версия читала записанное и слепо ему следовала,
        # хотя знала верный ответ по умолчанию. Замер прямо на живом счёте:
        #
        #     тип 0: $0.00     тип 1: $0.00
        #     тип 2: $0.00     тип 3: $42.42
        #
        # Настройка, однажды записанная, не должна отменять то, что мы узнали
        # позже. Порядок она задаёт, приговор — нет.
        chosen = os.environ.get('PM_SIGNATURE_TYPE')
        if chosen:
            try:
                first = int(chosen)
                candidates.sort(key=lambda c: 0 if c[1] == first else 1)
            except (TypeError, ValueError):
                pass

        works = None
        for money_at, sig in candidates:
            os.environ['PM_FUNDER'] = money_at
            os.environ['PM_SIGNATURE_TYPE'] = str(sig)
            if wallet.client(force=True) is None:
                continue
            balance = wallet.balance()
            if balance and balance > 0:
                _remember(money_at, sig)
                return True, address, (
                    f'счёт {money_at[:8]}…{money_at[-4:]}, '
                    f'на нём ${balance:,.2f} · {SIGNATURE_NAMES[sig]}')
            if works is None:
                works = (money_at, sig)

        if works:
            # Связка принята, но денег на ней не видно. Это НЕ отказ: класть
            # средства могут после подключения. Но и молчать нельзя — иначе
            # человек узнает о пустом счёте на первой заявке.
            _remember(*works)
            same = works[0].lower() == (address or '').lower()
            hint = ('деньги искались на адресе КЛЮЧА. У кошелька, заведённого '
                    'через сайт Polymarket, счёт ОТДЕЛЬНЫЙ — возьмите его на '
                    'polymarket.com/settings и впишите в поле «Адрес счёта»'
                    if same else
                    'пополните счёт: USDC в сети Polygon через кнопку Deposit '
                    'на polymarket.com')
            return True, address, (
                f'подключено ({SIGNATURE_NAMES[works[1]]}), но остатка не '
                f'видно. {hint}')
        # ПРИЧИНА НАЗЫВАЕТСЯ, А НЕ УГАДЫВАЕТСЯ. Прежде тут стоял совет про
        # адрес счёта — верный лишь в одном случае из нескольких. Нехватка
        # библиотеки, закрытая сеть и ограничение по стране выглядели так же,
        # и человек проверял адрес там, где дело было в сети.
        why = wallet.explain_failure()
        return False, address, (
            f'подключиться не удалось: {why}' if why else
            'ключ прочитан, но площадка не приняла ни одну связку. Проверьте '
            'адрес счёта на polymarket.com/settings — он может отличаться от '
            'адреса кошелька')
    except Exception as exc:                                # noqa: BLE001
        # СООБЩЕНИЕ БИБЛИОТЕКИ НАРУЖУ НЕ ИДЁТ. Оно способно содержать сам ключ:
        # у некоторых версий он попадает в текст ошибки целиком.
        return False, None, f'ключ не принят ({type(exc).__name__})'
    finally:
        # Окружение возвращается в прежний вид независимо от исхода: проверка
        # не должна незаметно включить кошелёк, который человек ещё не сохранил.
        for name, value in saved.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
        wallet.client(force=True)


_FOUND = {}


def _remember(funder_address, sig):
    """Запоминает подобранную связку, чтобы записать её вместе с ключом."""
    _FOUND['funder'] = str(funder_address)
    _FOUND['type'] = int(sig)


def save(private_key, funder=None):
    """
    Проверяет и записывает. Возвращает (успех, адрес, сообщение).

    ЖИВАЯ ТОРГОВЛЯ НЕ ВКЛЮЧАЕТСЯ. Подключить кошелёк и разрешить тратить с него
    деньги — два разных решения, и человек принимает их по отдельности.
    """
    ok, address, why = check(private_key, funder)
    if not ok:
        return False, address, why

    import first_run
    values = {'PM_PRIVATE_KEY': str(private_key).strip()}
    # СЧЁТ ЗАПИСЫВАЕТСЯ ВСЕГДА, даже когда человек его не ввёл: тогда это адрес
    # самого ключа. Оставить поле пустым значило бы, что configured() вернёт
    # ложь и кошелёк будет считаться неподключённым сразу после успешной
    # проверки.
    # ПИШЕТСЯ ПОДОБРАННОЕ, А НЕ ВВЕДЁННОЕ. Человек мог указать адрес кошелька
    # там, где деньги лежат на счёте площадки, — подбор это выяснил, и
    # записывать надо то, что работает, а не то, что было напечатано.
    values['PM_FUNDER'] = _FOUND.get('funder') or (
        str(funder).strip() if funder else (address or ''))
    if _FOUND.get('type') is not None:
        values['PM_SIGNATURE_TYPE'] = str(_FOUND['type'])
    first_run._write_env(values)

    # Окружение текущего процесса тоже обновляется: иначе настройка
    # подействовала бы только после перезапуска, а человек в панели видел бы
    # «не настроен» сразу после успешного сохранения.
    for name, value in values.items():
        os.environ[name] = value
    wallet.client(force=True)
    return True, address, 'кошелёк подключён; живая торговля пока выключена'


def forget():
    """
    Убирает ключ из настроек и из окружения.

    Нужен ровно затем же, зачем аварийная остановка: способ прекратить всё
    одним действием, не разбираясь, где что записано.
    """
    import first_run
    first_run._write_env({'PM_PRIVATE_KEY': '', 'PM_FUNDER': '',
                          'PM_SIGNATURE_TYPE': '', 'PM_LIVE': '0'})
    for name in ('PM_PRIVATE_KEY', 'PM_FUNDER', 'PM_SIGNATURE_TYPE'):
        os.environ.pop(name, None)
    os.environ['PM_LIVE'] = '0'
    wallet.client(force=True)
    return True, 'кошелёк отключён, живая торговля выключена'


def set_live(enabled):
    """
    Включает или выключает живую торговлю. Отдельно от подключения кошелька.

    БЕЗ КОШЕЛЬКА НЕ ВКЛЮЧАЕТСЯ. Разрешение тратить деньги там, где тратить
    нечем, — это не безобидная настройка, а забытый включённым рубильник:
    он сработает в тот момент, когда кошелёк появится.
    """
    import first_run
    if enabled and not wallet.configured():
        return False, 'сначала подключите кошелёк'
    first_run._write_env({'PM_LIVE': '1' if enabled else '0'})
    os.environ['PM_LIVE'] = '1' if enabled else '0'
    return True, ('ЖИВАЯ ТОРГОВЛЯ ВКЛЮЧЕНА — заявки уйдут на биржу'
                  if enabled else 'живая торговля выключена')


def state():
    """
    Что показать в панели. Ключа здесь нет и быть не может.

    Отдаётся адрес, признак настройки, остаток и бюджет — всё, по чему человек
    судит о готовности, и ничего, чем можно подписать сделку.
    """
    status = wallet.status()
    money, why = params.budget_plan('MM')
    out = {
        'configured': status['configured'],
        'address': status['address'],
        'live_enabled': status['live_enabled'],
        'can_trade_live': status['can_trade_live'],
        'budget_usd': round(money, 2),
        'budget_note': why,
        'signature_type': status.get('signature_type'),
        'signature_note': SIGNATURE_NAMES.get(status.get('signature_type'), ''),
        'balance_usd': None,
        'balance_known': False,
    }
    if status['configured']:
        balance = wallet.balance()
        # НЕИЗВЕСТНО И НОЛЬ — РАЗНЫЕ ВЕЩИ, и панель обязана их различать: на
        # нуле торговать нельзя осознанно, при неизвестном нельзя вообще.
        out['balance_known'] = balance is not None
        out['balance_usd'] = round(balance, 2) if balance is not None else None
    return out
