# сделкам и потому приблизителен.
OS_MIN_EXIT_SHARE = _f('OS_MIN_EXIT_SHARE', 0.5)

# РАЗМЕР ЗАЯВКИ СЧИТАЕТСЯ ОТ ПОТОКА РЫНКА. Жёсткая пятёрка оставляла 97% счёта
# без дела: после порога на двусторонний поток остаётся горстка рынков, и на
# них уходило $2.39 из ста. При этом поток продаж по нашим ценам — 299
# контрактов в час, а чужая сделка бывает и в 357 контрактов.
#
# Берём полчаса потока: больше рынок за это время не пропустит, и остаток
# заявки простоял бы впустую.
