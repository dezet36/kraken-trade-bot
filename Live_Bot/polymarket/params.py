# движение против нас необратимо; выше 0.95 то же самое с другой стороны.
MM_MIN_PRICE = _f('MM_MIN_PRICE', 0.02)
MM_MAX_PRICE = _f('MM_MAX_PRICE', 0.95)

# Границы спреда в долях цены. Снизу — чтобы круг покрывал хотя бы себя; сверху
# — чтобы не лезть в рынки, где спред широк из-за неопределённости, а не из-за
# отсутствия конкурентов. Спред 0.56 при цене 0.42 означает бид 0.14 против
# аска 0.70: обе наши заявки исполнятся там только тогда, когда кому-то станет
# ясно, куда идёт цена, то есть против нас.
MM_MIN_SPREAD_SHARE = _f('MM_MIN_SPREAD_SHARE', 0.02)
MM_MAX_SPREAD_SHARE = _f('MM_MAX_SPREAD_SHARE', 0.35)
