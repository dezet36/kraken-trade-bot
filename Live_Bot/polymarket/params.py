# «при полном запасе сдвинуть котировку ровно на половину спреда». Меньше —
# запас будет уходить медленнее; больше — котировка уедет за пределы рынка.
MM_SKEW = _f('MM_SKEW', 1.0)

# ПРИ КАКОМ ЗАПАСЕ НАКЛОН ПОЛНЫЙ — в наших же размерах заявки.
#
# Двойка означает: одна набранная котировка — это половина наклона, две —
# полный. Половины хватает, чтобы закрывающая сторона стала лучшей ценой в
# стакане и при этом оставила тик прибыли; полный наклон ставит её на грань
# безубытка и разгружает любой ценой. Единица была бы слишком резкой: первое
# же исполнение отдавало бы весь спред обратно.
#
# Прежде полнота делилась на MM_MAX_POSITION (триста контрактов), и при размере
# в пять наклон был меньше тика — то есть его не было вовсе.
MM_SKEW_FULL_AT = _f('MM_SKEW_FULL_AT', 2.0)
# Потолок запаса на ОДИН рынок, в контрактах. Именно здесь ломается разобранный
# кейс: 2 236 позиций, 22% в плюсе, переоценка -$8 564. Потолок делает такое
# накопление невозможным по построению.
MM_MAX_POSITION = _f('MM_MAX_POSITION', 300)
# Потолок запаса по всем рынкам сразу, в долларах вложенного.
MM_MAX_EXPOSURE_USD = _f('MM_MAX_EXPOSURE_USD', 500)
# Сколько держим позицию, если встречная сторона так и не исполнилась. Доход
# здесь — спред, а не предсказание, и позиция, застрявшая до разрешения, это
# уже ставка на исход.
MM_MAX_HOLD_HOURS = _f('MM_MAX_HOLD_HOURS', 24)


# Наибольшая доля капитала в ОДНОМ рынке. Без неё сотня долларов уходила
# целиком в один рынок — самый доходный по оценке и единственный: одно
# исполнение, и весь счёт в позиции, которую нечем нести. Треть выбрана так,
# чтобы даже при малом счёте рынков было не меньше трёх.
MM_MAX_MARKET_SHARE = _f('MM_MAX_MARKET_SHARE', 0.34)


# ── Отбор рынков под котирование ─────────────────────────────────────────────
# Размер заявки в КОНТРАКТАХ. Пять — минимум, который принимает биржа
# (orderMinSize у всех рынков равен 5). Порог 20-200 относится только к
# награде, а для заработка на спреде он не нужен: двусторонняя котировка в пять
# контрактов стоит ровно $5 при любой цене, и сотня долларов расходится на
# двадцать рынков вместо пяти.
MM_MIN_ORDER_SIZE = _f('MM_MIN_ORDER_SIZE', 5)

# СКОЛЬКО ТИКОВ СПРЕДА НУЖНО, ЧТОБЫ ШАГНУТЬ ВНУТРЬ. Шаг внутрь съедает по тику
# с каждой стороны, поэтому при трёх тиках остаётся один — минимум, ради
# которого стоит стоять. При спреде в один-два тика шага нет, и мы встаём на
# лучшую цену, зная, что исполнение там маловероятно: 96% наблюдений имеют
# впереди больше пяти контрактов.
MM_MIN_TICKS_TO_STEP_IN = _f('MM_MIN_TICKS_TO_STEP_IN', 3)

# ЗА СКОЛЬКО ЧАСОВ ДО РАЗРЕШЕНИЯ ПЕРЕСТАЁМ КОТИРОВАТЬ. Мейкер зарабатывает
# полтора цента на контракте, а разрешение превращает контракт в ноль или
# единицу целиком: один застигнутый запас стоит десятка удачных кругов.
# Разгружаться перед самым разрешением не у кого — ликвидность уходит первой.
MM_MIN_HOURS_LEFT = _f('MM_MIN_HOURS_LEFT', 48)

# ЧЕРЕЗ СКОЛЬКО МИНУТ ПОСЛЕ ИСПОЛНЕНИЯ СМОТРИМ, КУДА УШЛА ЦЕНА. Полчаса — это
# компромисс: за минуту снос ещё не проявится, за сутки его смоет посторонним
# движением рынка, и замер перестанет отвечать на свой вопрос.
MM_DRIFT_MINUTES = _f('MM_DRIFT_MINUTES', 30)

# СКОЛЬКО РЫНКОВ ОДНОГО СОБЫТИЯ БРАТЬ. «США ударят по 8 странам» и «по 9
# странам» — один вопрос, заданный дважды: запас по ним набирается одинаковый и
# обесценивается одинаково. Двадцать рынков одного события это одна ставка
# двадцатикратного размера, притом выглядящая как разнообразие.
MM_MAX_PER_EVENT = _f('MM_MAX_PER_EVENT', 2)

# КАК ЧАСТО ПЕРЕСМАТРИВАТЬ СПИСОК РЫНКОВ. Прежде он замораживался при запуске и
# не менялся никогда: бот не видел ни новых событий, ни того, что рынок затих.
# Деньги, стоящие в затихшем рынке, не работают — а их всего сотня.
MM_RESCAN_MINUTES = _f('MM_RESCAN_MINUTES', 30)

# СКОЛЬКО ЧАСОВ ЖДАТЬ ИСПОЛНЕНИЯ, ПРЕЖДЕ ЧЕМ УЙТИ С РЫНКА. Рынок без единого
# исполнения держит $5 впустую; при сотне долларов это двадцатая часть счёта.
# Рынки с открытым запасом не бросаются НИКОГДА — уйти, оставив позицию,
# значит перестать ею управлять.
MM_IDLE_HOURS = _f('MM_IDLE_HOURS', 6)

# ВО СКОЛЬКО РАЗ ДОЛЬШЕ ОБЕЩАННОГО ЖДЁМ, ПРЕЖДЕ ЧЕМ УЙТИ.
#
# Общий потолок в шесть часов был один на все рынки, и это давало ровно ту
# картину, с которой пришёл человек: «бот висит часами на одном рынке». Рынку,
# которому отбор обещал круг за двадцать минут, к шестому часу мы дали
# восемнадцать сроков — при том что место в списке стоит денег.
#
# Тройка выбрана не за красоту: одинарного срока мало (очередь плавает, и мы
# дёргались бы на шуме), а к тройному ошибка модели перестаёт быть
# случайностью. Общий потолок остаётся верхней границей.
MM_IDLE_TRIES = _f('MM_IDLE_TRIES', 3)

# ПРЕДЕЛ ОЖИДАНИЯ ПОЛНОГО КРУГА. Решает время, а не ширина спреда: рынок, где
# круг занимает сутки, бесполезен при любом спреде — деньги стоят, а разрешение
# приближается. Замер по 53 рынкам: у шести ожидание меньше часа при медиане 23
# минуты, и почти все они однотиковые — то есть ровно те, что прежде
# отбрасывались за узость спреда.
MM_MAX_WAIT_HOURS = _f('MM_MAX_WAIT_HOURS', 8)

# НИЖНИЙ ПОРОГ ДОХОДА, ниже которого рынок не стоит места в списке.
#
# «Ещё один рынок» звучит как разнообразие, но рынок с доходом в цент за час —
# это деньги, вынутые из работающих. Замерено на 1 243 рынках: при $100
# четырнадцать рынков вместо восьми снижали расчётный доход с $1.30 до $1.09 в
# час. Цент в час — это примерно семь долларов в месяц с рынка; всё, что ниже,
# в сумме не покрывает даже риска запаса.
MM_MIN_USD_PER_HOUR = _f('MM_MIN_USD_PER_HOUR', 0.01)

# Доля часового потока, которую просим заявкой. Больше рынок не пропустит:
# остаток простоит и исказит собственный замер ожидания.
MM_FLOW_HOURS = _f('MM_FLOW_HOURS', 0.5)

# Быть большей частью книги значит двигать цену собой.
MM_MAX_BOOK_SHARE = _f('MM_MAX_BOOK_SHARE', 0.10)

# СКОЛЬКО ЛЕНТ ТЯНУТЬ РАЗОМ. Здесь решается охват: последовательно девятьсот
# рынков занимают семь минут, и отбор мерил только первые сто восемьдесят —
# причём какие именно, решал порядок выдачи биржи. Ликвидные, но непопулярные
# рынки лежат в хвосте любой выдачи, и мы до них просто не доходили.
#
# Шестнадцать потоков дают полминуты вместо семи. Больше не берём: площадка
# начнёт отвечать отказом, и вместо охвата выйдет его видимость с пустыми
# лентами — то есть рынки, признанные мёртвыми по нашей же ошибке.
TAPE_WORKERS = _f('TAPE_WORKERS', 16)

# ── Односторонний мейкер на дешёвых рынках ──────────────────────────────────
#
# ОТДЕЛЬНЫЕ ПАРАМЕТРЫ, А НЕ ОБЩИЕ С ДВУСТОРОННЕЙ СХЕМОЙ. Стратегии разные по
# существу: та не набирает направленной позиции, эта набирает всегда. Общие
# настройки означали бы, что правка одной молча меняет другую.
#
# ПОЛОСА ЦЕН ВЗЯТА ИЗ ЗАМЕРА, а не из удобства. На 3 001 разрешённом рынке и
# 375 событиях недобор в 0.02-0.15 составил +0.0191 на контракт при интервале
# [-0.0034, +0.0446]. Вне этой полосы замера нет, и котировать там значило бы
# опираться на ничто.
OS_MIN_PRICE = _f('OS_MIN_PRICE', 0.02)
OS_MAX_PRICE = _f('OS_MAX_PRICE', 0.15)

# Два тика — минимум: один на вход внутрь, один на выход выше.
OS_MIN_TICKS = _f('OS_MIN_TICKS', 2)

# Глубина требуется только по биду: мы не продаём того, чего нет, значит до
# первой покупки сторона аска нас не касается. Но пустой бид отсекается —
# там наша заявка единственная, и исполнят нас, когда это выгодно другому.
OS_MIN_BID_DEPTH = _f('OS_MIN_BID_DEPTH', 50)
OS_MIN_VOLUME = _f('OS_MIN_VOLUME', 500)
OS_MARKETS = _f('OS_MARKETS', 200)

# КАКАЯ ДОЛЯ ВЫХОДОВ НУЖНА, ЧТОБЫ БРАТЬ РЫНОК. Порог добавлен ПОСЛЕ замера, и
# без него стратегия была бы убыточной: по ленте медианная доля выходов на
# дешёвых рынках равна НУЛЮ. Продавцы по нашей цене входа есть, покупателей по
# цене выхода нет вовсе — поток односторонний. Дешёвый лонгшот тем и дёшев,
# что все хотят из него выйти.
#
# Порог 0.5 означает: на каждые две продажи нам должна приходиться хотя бы
# одна покупка обратно. Арифметика требует 25% (0.01·f > 0.0034·(1-f)), запас
