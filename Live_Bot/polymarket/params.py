# ── Банкролл по стратегиям ───────────────────────────────────────────────────
# РАЗДЕЛЬНЫЕ БАНКРОЛЛЫ — требование раздела 17 спецификации, и оно по существу.
# Смешав капитал, мы не смогли бы сказать, какая стратегия заработала, а какая
# проела: у них разная частота, разный профиль просадки и разный статус
# валидации. Общий счёт превратил бы сравнение в гадание.
#
# Доли выбраны по статусу проверки, а не поровну. Погода — единственная, где
# замер хоть что-то нашёл. Крипта не проверялась вовсе. Лонгшоты валидацию
# провалили, и им оставлена символическая доля исключительно ради бумажного
# наблюдения: реальных денег они не получат ни при каких настройках.
BANKROLL_SPLIT = {
    'WEATHER': _f('BANKROLL_WEATHER', 0.30),
    'CRYPTO': _f('BANKROLL_CRYPTO', 0.20),
    'LONGSHOT': _f('BANKROLL_LONGSHOT', 0.05),
    # Маркет-мейкинг получает половину, и это не предпочтение, а различие в
    # природе. Три остальные стратегии УГАДЫВАЮТ исход и проверяются на
    # истории; ни одна проверку не прошла. Здесь источник дохода другой —
    # разница между комиссией мейкера (ноль) и тейкера (до 4.75% ставки на
    # дешёвых контрактах) плюс награда за ликвидность ($5 976 в день по всей
    # площадке). Это механика биржи, а не гипотеза о будущем.
    'MM': _f('BANKROLL_MM', 0.45),
}


def bankroll_for(strategy, total=None):
    """Капитал стратегии. Незнакомое имя получает ноль, а не весь счёт."""
    total = float(total if total is not None else BANKROLL)
    return total * float(BANKROLL_SPLIT.get(strategy, 0.0))


