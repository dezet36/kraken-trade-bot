"""
Параметры работы с Polymarket. Все значения — через переменные окружения.

ПРЕФИКС PM_ СВОЙ, И ЭТО НЕ УКРАШЕНИЕ. У каждой стратегии в проекте свой набор
переменных, чтобы правка ради одной не задевала остальные. Здесь площадка
вообще другая, и смешение было бы особенно вредным.

ЧИСЛА ВЗЯТЫ ИЗ ЗАМЕРОВ, А НЕ ИЗ ГОЛОВЫ. Где значение получено измерением, рядом
стоит откуда. Где выбрано осторожно — сказано, что осторожно.
"""

import os


def _f(name, default):
    try:
        return float(os.getenv(f'PM_{name}', default))
    except (TypeError, ValueError):
        return float(default)


def _i(name, default):
    try:
        return int(os.getenv(f'PM_{name}', default))
    except (TypeError, ValueError):
        return int(default)


def _s(name, default):
    return os.getenv(f'PM_{name}', default) or default


def _b(name, default):
    return _s(name, '1' if default else '0').strip().lower() in ('1', 'true', 'да')


