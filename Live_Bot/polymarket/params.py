MM_MIN_BALANCE = _f('MM_MIN_BALANCE', 0.25)
# Оборот рынка: без него стакан может быть нарисован и не торговаться вовсе.
MM_MIN_VOLUME = _f('MM_MIN_VOLUME', 500)
# Границы цены. Ниже двух центов один тик уже равен половине ставки, и любое
