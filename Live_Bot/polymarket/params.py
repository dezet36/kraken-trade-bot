# Один рынок не должен забирать заметную часть денег, иначе его разрешение
# становится событием для всего счёта.
OS_MAX_MARKET_SHARE = _f('OS_MAX_MARKET_SHARE', 0.15)

# Быть большей частью бида значит двигать цену собой и остаться единственным
# покупателем, когда придёт продавец, который знает больше.
OS_MAX_BOOK_SHARE = _f('OS_MAX_BOOK_SHARE', 0.10)
# Глубина стакана В ДЕНЬГАХ, которая должна быть с КАЖДОЙ стороны. Тысяча
# контрактов по 0.002 — это два доллара, и живой такую сторону называть нельзя.
MM_MIN_SIDE_DEPTH = _f('MM_MIN_SIDE_DEPTH', 100)
# Перекос сторон: слабая должна составлять хотя бы эту долю сильной. Без этого
# условия наверх всплывают книги вида «бидов на $0, асков на $11 849»: дешёвый
# лонгшот, который никто не покупает. Наш бид оказался бы там единственным, и
