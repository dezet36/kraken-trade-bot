"""
Логика котирования: где встать и какого размера, с оглядкой на запас.

ЗДЕСЬ ЖИВЁТ ЕДИНСТВЕННОЕ СУЩЕСТВЕННОЕ ОТЛИЧИЕ ОТ РАЗОБРАННОГО КЕЙСА. У кошелька
@planktonxd захват спреда прекрасный: +1.50 цента, +16.2% от цены покупки,
плюс на 89% активов. И почти всё это съедено запасом: 2 236 позиций, 22% в
плюсе, переоценка -$8 564 против зафиксированных +$11 000. Он покупает дёшево и
копит то, что идёт к нулю.

Лечится это не хитростью, а арифметикой: котировать ОБЕ стороны и наклонять
котировку против собственного запаса. Набрал длинную позицию — обе цены
опускаются, покупать становится невыгодно, а продавать выгодно. Запас сам
стремится к нулю, без отдельного «закрывающего» кода.

СПРАВЕДЛИВАЯ ЦЕНА БЕРЁТСЯ НЕ СЕРЕДИНОЙ. Середина не учитывает, что объёмы по
сторонам разные: если на биде стоит в десять раз больше, чем на аске, цена
скорее пойдёт вверх, и середина систематически занижает. Взвешивание по
ПРОТИВОПОЛОЖНЫМ объёмам (микроцена) это исправляет — приём стандартный и
проверяемый: при равных объёмах он в точности даёт середину.

ПОЧЕМУ ВСЁ ЭТО В ОТДЕЛЬНОМ МОДУЛЕ И БЕЗ СЕТИ. Логика котирования обязана быть
проверяемой без биржи: функции берут стакан и запас, возвращают числа. Иначе
единственным способом её проверить остаётся живая торговля, а это самый дорогой
из возможных отладчиков.
"""

from . import params


def fair_value(top):
    """
    Микроцена: середина, поправленная на перекос объёмов.

    Вес берётся ПРОТИВОПОЛОЖНЫЙ: цена бида умножается на размер аска. Это не
    описка. Большой бид и маленький аск означают, что покупателей больше и цена
    тянется вверх — значит вес должен смещать оценку к аску.

    При равных объёмах возвращает ровно середину, и это удобное свойство для
    проверки.
    """
    if not top or top.get('bid') is None or top.get('ask') is None:
        return None
    bid_size = float(top.get('bid_size') or 0)
    ask_size = float(top.get('ask_size') or 0)
    total = bid_size + ask_size
    if total <= 0:
        return top['mid']
    return (top['bid'] * ask_size + top['ask'] * bid_size) / total


def inventory_skew(position, full_at, spread):
    """
    Сдвиг котировки против накопленного запаса, в единицах цены.

    Знак отрицательный при длинной позиции: обе цены опускаются, покупка
    становится менее вероятной, продажа более. Величина растёт линейно с долей
    запаса и ограничена половиной спреда — больший сдвиг увёл бы котировку за
    пределы рынка и превратил бы мейкера в тейкера.

    ПОЛНОТА СЧИТАЕТСЯ ОТ НАШЕГО РАЗМЕРА, А НЕ ОТ АБСТРАКТНОГО ПОТОЛКА, и это
    исправление, без которого весь наклон был украшением.

    Раньше делили на MM_MAX_POSITION — триста контрактов, число из расчёта на
    большой счёт. При нашем размере в пять контрактов доля выходила 5/300, то
    есть полтора процента, а сдвиг — треть десятой доли тика:

        позиция  0 контрактов: сдвиг -0.00000  →  бид 0.21  аск 0.23
        позиция 50 контрактов: сдвиг -0.00333  →  бид 0.20  аск 0.23

    Аск не двигался ВООБЩЕ, сколько бы мы ни набрали. Поэтому исполнялась одна
    сторона, а закрывающая оставалась там же, где стояла, — и из двенадцати
    исполнений за ночь закрылось ОДНО, а деньги замерли в десяти позициях.

    Правильная мерка — наш собственный размер: набрав одну свою котировку, мы
    на этом рынке заполнены целиком, и закрывающую сторону надо делать
    привлекательной немедленно, а не когда-нибудь при трёхстах контрактах.
    """
    if not full_at or spread is None:
        return 0.0
    share = max(-1.0, min(1.0, float(position) / float(full_at)))
    return -share * (spread / 2.0) * params.MM_SKEW


def _round_to_tick(price, tick, mode='near'):
    """Цена, приведённая к сетке биржи. Заявка вне сетки будет отвергнута."""
    steps = price / tick
    if mode == 'down':
        steps = int(steps)
    elif mode == 'up':
        steps = int(steps) + (1 if steps > int(steps) else 0)
    else:
        steps = round(steps)
    return round(steps * tick, 10)


def desired_quote(top, market, position=0.0, max_position=None, book=None,
                  avg_cost=0.0):
    """
    Куда встать двусторонней котировкой с учётом запаса.

    Возвращает {'bid','ask','size','fair','skew','reason'} либо None, если
    котировать нельзя. Причина отказа всегда называется: молчаливый пропуск
    рынка невозможно отличить от поломки.

    ПОРЯДОК ОГРАНИЧЕНИЙ ВАЖЕН. Сначала считается желаемая цена, потом она
    прижимается к сетке, потом проверяется, что мы не пересекли рынок, и лишь
    в конце — что котировка попадает под награду. Проверив награду раньше
    округления, мы бы отсеивали заявки, которые после округления как раз
    проходят.
    """
    if not top or top.get('bid') is None or top.get('ask') is None:
        return None
    tick = float(market.get('tick') or 0.001)
    spread = top['ask'] - top['bid']
    fair = fair_value(top)
    if fair is None:
        return None

    cap = float(max_position if max_position is not None else params.MM_MAX_POSITION)

    # РАЗМЕР СЧИТАЕТСЯ ДО НАКЛОНА, потому что полнота меряется именно им.
    # Порядок был обратный, и наклон делился на потолок в триста контрактов —
    # число, к нашей пятёрке отношения не имеющее.
    size = max(float(market.get('size') or 0),
               float(market.get('order_min') or 0),
               float(params.MM_MIN_ORDER_SIZE))
    skew = inventory_skew(position, size * params.MM_SKEW_FULL_AT, spread)

    # ВСТАЁМ ВНУТРЬ СПРЕДА, А НЕ В ХВОСТ ОЧЕРЕДИ. Это исправление стоило нам
    # всех исполнений разом, поэтому причина записана целиком.
    #
    # Прежняя версия просила половину спреда от справедливой цены. Поскольку
    # справедливая цена почти равна середине, получалось ровно top['bid'] и
    # ровно top['ask']: мы КАЖДЫЙ раз вставали на лучшую цену — то есть в
    # КОНЕЦ чужой очереди. На 4 852 наблюдениях впереди нас стояло 152
    # контракта по медиане, 2 197 в девяностой доле, и больше пяти контрактов
    # в 96% случаев. Заявка на пять контрактов за такой очередью не исполнится
    # никогда: за девять часов бумажного прогона на 90 рынках исполнений было
    # ровно ноль.
    #
    # Шаг внутрь на один тик создаёт НОВЫЙ ценовой уровень, где мы одни, и
    # очередь становится нулевой. Это не хитрость, а сама работа мейкера:
    # заработать спред может только тот, кто стоит первым.
    #
    # Платим за это двумя тиками спреда, поэтому шагаем лишь когда после шага
    # что-то остаётся. Порог в три тика проверяем на данных: 36% наблюдений
    # проходят, и остаточный спред у них 7.7% от ставки по медиане.
    ticks = int(round(spread / tick)) if tick > 0 else 0

    # МЕСТА НЕТ — НЕ КОТИРУЕМ ВОВСЕ, а не встаём в конец очереди. При спреде в
    # один-два тика шагнуть внутрь нельзя: цены сойдутся, и заявка станет
    # тейкерской. Остаётся встать на лучшую цену, то есть за очередь из 152
    # контрактов по медиане, — и держать там деньги, ничего не зарабатывая.
    #
    # При бюджете в сотню долларов это не мелочь: каждые занятые $5 — это
    # двадцатая часть счёта, простаивающая в рынке, где мы заведомо не первые.
    # Те же деньги на рынке с тремя тиками работают с нулевой очередью.
    # УЗКИЙ СПРЕД БОЛЬШЕ НЕ ОТКАЗ, А ДРУГОЙ СПОСОБ ВСТАТЬ. Прежде такие рынки
    # пропускались: «встали бы в конец очереди». Это была ошибка, и стоила она
    # лучших рынков биржи.
    #
    # Очередь важна не длиной, а ВРЕМЕНЕМ. Замер по 53 рынкам: у шести
    # ожидание меньше часа при медиане 23 минуты, и почти все они однотиковые.
    # «Will Alexandria Ocasio-Cortez win...» — очередь 9 контрактов при потоке
    # 530 в час, то есть одна минута. Спред там узок именно потому, что торгуют,
    # и там же очередь рассасывается.
    #
    # Отбор считает время заранее и сюда доводит только те рынки, где круг
    # укладывается в предел. Здесь остаётся выбрать, КАК встать: есть место —
    # шагаем внутрь и берём спред минус два тика; места нет — встаём на лучшую
    # цену и берём спред целиком, расплачиваясь ожиданием.
    # ГЛУБИНА ШАГА ПРИХОДИТ ИЗ ОТБОРА, где она подобрана по замеру потока.
    # Жёсткий тик был произволом: на широком спреде заявка в тик от лучшей
    # цены стоит далеко от середины, и до неё почти никто не доходит. По
    # рынку «Khvicha Kvaratskhelia» шаг в пять тиков вместо одного поднимал
    # доходящий поток с 13 до 226 контрактов в час при вдвое меньшем спреде.
    #
    # Запасной вариант на случай, когда отбор ничего не сказал: прежний тик.
    depth = market.get('step_ticks')
    if depth is None:
        depth = 1 if ticks >= params.MM_MIN_TICKS_TO_STEP_IN else 0
    # Глубже половины спреда уходить нельзя — цены сойдутся.
    depth = max(0, min(int(depth), (ticks - 1) // 2))
    step = depth * tick

    want_bid = _round_to_tick(top['bid'] + step + skew, tick, 'down')
    want_ask = _round_to_tick(top['ask'] - step + skew, tick, 'up')

    # НИЖЕ СВОЕЙ ЦЕНЫ НЕ ПРОДАЁМ, ВЫШЕ СВОЕЙ НЕ ПОКУПАЕМ.
    #
    # САМАЯ ДОРОГАЯ ОШИБКА, НАЙДЕННАЯ НА ЖИВЫХ КРУГАХ. Из четырёх закрытых
    # кругов три оказались убыточными, и каждый — продажей ДЕШЕВЛЕ покупки:
    #
    #     купили 0.554 → продали 0.527    -$0.135
    #     купили 0.235 → продали 0.208    -$0.135
    #     купили 0.203 → продали 0.193    -$0.050
    #
    # Причина в том, что цены считались от ТЕКУЩЕГО рынка и ничего не знали о
    # том, по чём мы вошли. Рынок ушёл вниз — наш аск поехал за ним и оказался
    # ниже собственной покупки. Так стратегия спреда превращается в «купить
    # дорого, продать дёшево», причём с виду всё правильно: обе заявки стоят
    # внутри спреда, обе исполняются, а круг в минусе.
    #
    # Мейкер зарабатывает разницу цен, а не угадывание. Рынок ушёл — значит
    # круг сегодня не закроется, и это нормально: ждём, а наклон против запаса
    # тем временем делает покупку невыгодной, чтобы не набирать ещё.
    #
    # ВЫХОД ПО РИСКУ — ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ. Просроченная позиция и позиция
    # за пределом убытка закрываются по любой цене: там мы уже признали, что
    # ошиблись, и платим за выход сознательно.
    risky = bool(market.get('stale'))
    if position and avg_cost and not risky:
        edge = params.MM_MIN_CLOSE_TICKS * tick
        if position > 0:
            want_ask = max(want_ask, _round_to_tick(avg_cost + edge, tick, 'up'))
        else:
            want_bid = min(want_bid, _round_to_tick(avg_cost - edge, tick, 'down'))

    # НЕ ПЕРЕСЕКАЕМ РЫНОК. Наклон против запаса двигает обе цены, и при большом
    # запасе он способен занести заявку на чужую сторону. Такая заявка
    # исполнится немедленно и по ТЕЙКЕРСКОЙ комиссии — 4.7% против 0.13%, то
    # есть дороже всего спреда, ради которого мы здесь стоим.
    want_bid = min(want_bid, top['ask'] - tick)
    want_ask = max(want_ask, top['bid'] + tick)

    if want_bid <= 0 or want_ask >= 1 or want_bid >= want_ask:
        return {'reason': 'цены вне допустимого диапазона'}

    # РАЗМЕР — МИНИМАЛЬНЫЙ ДОПУСТИМЫЙ БИРЖЕЙ, а не наградный порог. Прежняя
    # версия брала max(100, rewardsMinSize) и выставляла по 100-200 контрактов
    # на каждом из 90 рынков: около $9 000 обязательств при $450 денег. В
    # бумаге это не жгло, потому что не исполнялось ни разу; на бирже часть
    # заявок прошла бы, а остальные были бы отвергнуты — и мы узнали бы размер
    # своего плеча по факту, а не заранее.

    # Запас упёрся в потолок — котируем ТОЛЬКО сокращающую сторону. Это
    # единственное место, где котировка становится односторонней, и делается
    # это сознательно: держать запас выше потолка опаснее, чем потерять награду.
    only = None
    if position >= cap:
        only = 'ask'
    elif position <= -cap:
        only = 'bid'

    # ВХОДИМ ДЕШЁВОЙ СТОРОНОЙ, ВЫХОДИМ ПРОДАЖЕЙ ТОГО, ЧТО ДЕРЖИМ.
    #
    # Двусторонняя котировка связывает РОВНО размер в долларах при любой цене:
    # покупка берёт p, встречная сторона — (1-p). На дешёвом рынке это значит
    # занять 94 цента ради семи десятых заработка. Разобранный кошелёк так не
    # делает — он покупает дёшево и продаёт то, что уже держит, а продажа
    # своего не стоит ничего. Отсюда его 16% на вложенное против наших 1.2%.
    #
    # Замерено по 327 рынкам: $5.00 на рынок против $0.62, то есть 8 рынков на
    # сорок долларов против 64.
    #
    # Пока позиции нет — стоим той стороной, которая дешевле. Появилась
    # позиция — закрывающая сторона становится бесплатной, и котируем её.
    # ДЕШЁВАЯ СТОРОНА РАБОТАЕТ ТОЛЬКО В ПОЛОСЕ 0.10..0.90, И ЭТО ПРАВИЛО
    # ПЛОЩАДКИ, А НЕ НАША ОСТОРОЖНОСТЬ.
    #
    # Награда считает зачётные очки как max(min(Q₁,Q₂), max(Q₁,Q₂)/3) — но
    # деление на три действует лишь при середине от 0.10 до 0.90. Вне полосы
    # зачёт равен min(Q₁,Q₂), и односторонняя котировка даёт РОВНО НОЛЬ.
    #
    # Именно туда нас и приводил дешёвый вход: замерено на живом счёте — из
    # двадцати стоящих котировок ни одной двусторонней, цены 0.036, 0.041,
    # 0.05, 0.074, и за сутки восемь центов награды на весь счёт. Дешёвая
    # сторона дешёвого рынка — это сторона, за которую не платят.
    cheap_side_pays = 0.10 <= fair <= 0.90

    # ДВУСТОРОННЯЯ КОТИРОВКА ЗАПИРАЕТ ДЕНЬГИ ДО РАЗРЕШЕНИЯ РЫНКА, И ВЫНУТЬ ИХ МЫ
    # НЕ МОЖЕМ. Это выяснено разбором самой площадки, а не рассуждением.
    #
    # Когда исполняются ОБЕ стороны, у нас на руках пара «ДА+НЕТ». По ставке это
    # ноль, по деньгам — ровно доллар за штуку, но лежащий мёртво: обратно в
    # залог пара гасится вызовом mergePositions, а наш счёт — депозитный
    # кошелёк Polymarket. Он принимает вызовы только от своей фабрики (ошибка
    # OnlyFactory), а фабрика — только от операторов площадки (OnlyOperator).
    # Проверено симуляцией: сам вызов проходит, но подать его нам некуда.
    #
    # Значит успешный круг ЗАБИРАЕТ капитал до разрешения рынка. Замерено на
    # живом счёте:
    #
    #     «Democratic House»  пара по 0.9700 → +3.09% за две недели
    #     «Dplus LCK»         пара по 0.9970 → +0.30% за четыре с половиной
    #                          месяца, то есть меньше процента годовых
    #
    # Односторонний вход этим не страдает: он покупает, а выходит ПРОДАЖЕЙ
    # того, что держит, и деньги возвращаются сразу.
    #
    # Отсюда правило: обе стороны ставим только там, где разрешение близко.
    # ВНЕ ПОЛОСЫ ЦЕН ВЫБОРА НЕТ: одна сторона там не приносит НИЧЕГО, значит
    # остаётся двусторонняя — а она запирает деньги до разрешения. Если оно
    # далеко, такой рынок брать нельзя вовсе: мы отдадим капитал на месяцы за
    # круг, который в лучшем случае вернёт полпроцента.
    #
    # Внутри полосы этой беды нет: односторонний вход выходит ПРОДАЖЕЙ того, что
    # держим, и деньги возвращаются сразу.
    hours_left = market.get('hours_left')
    if (not position and not cheap_side_pays and hours_left is not None
            and hours_left > params.MM_TWO_SIDED_MAX_HOURS):
        return {'bid': None, 'ask': None, 'size': size, 'only': None,
                'fair': fair, 'skew': 0.0, 'spread': None, 'mid': top['mid'],
                'expected_seconds': None,
                'reason': (f'до разрешения {hours_left / 24:.0f} дней, а здесь '
                           f'нужна двусторонняя — деньги запрутся в паре')}

    if params.MM_CAPITAL_LIGHT and not only:
        full = size * params.MM_SKEW_FULL_AT
        if not position:
            # Позиции нет — занимаем деньги только под дешёвую сторону, и
            # только там, где за одну сторону вообще платят. Вне полосы
            # дешёвый вход означает стоять бесплатно.
            if cheap_side_pays:
                only = 'bid' if fair <= 0.5 else 'ask'
        elif abs(position) >= full:
            # Набрали полный запас — дальше только разгружаемся.
            only = 'ask' if position > 0 else 'bid'
        # ИНАЧЕ КОТИРУЕМ ОБЕ СТОРОНЫ, и это возврат к тому, ради чего наклон и
        # писался.
        #
        # ПОЧЕМУ ЭТО ГЛАВНЫЙ РЫЧАГ ЧИСЛА СДЕЛОК. Разобранный кошелёк делает
        # 1 495 сделок в сутки и держит 2 236 позиций одновременно — то есть
        # НЕ ждёт закрытия круга, а продолжает входить. Мы же после первого
        # исполнения переходили в «только закрывать», и рынок замолкал до
        # конца круга: одна-две сделки в сутки вместо десятков.
        #
        # Держать обе стороны безопасно ровно потому, что есть наклон: каждая
        # следующая покупка идёт по цене хуже предыдущей, а продажа — лучше.
        # Запас растёт со всё большим сопротивлением и упирается в полный
        # наклон, где вход закрывается сам. Закрывающая сторона при этом
        # бесплатна: продаём то, что держим.

    # ПРОСРОЧЕННАЯ ПОЗИЦИЯ ЗАКРЫВАЕТСЯ, А НЕ ЖДЁТ ЛУЧШЕЙ ЦЕНЫ.
    #
    # Доход мейкера — спред, а не исход. Позиция, висящая сутки, превращает нас
    # в предсказателя и держит деньги, которые должны работать на других
    # рынках. Срок удержания записан в ограничениях риска с самого начала, и
    # всё это время его никто не проверял: stale_positions существовала и не
    # вызывалась ни разу.
    #
    # Закрываем НЕ переходя в тейкеры: встаём закрывающей стороной на лучшую
    # цену вместо шага внутрь. Это отдаёт шаг спреда, но выводит из позиции за
    # время очереди, а не за сутки. Комиссия тейкера на цене 0.05 съела бы
    # 4.75% ставки — весь спред, ради которого мы здесь стоим.
    if market.get('stale') and position:
        only = 'ask' if position > 0 else 'bid'
        if only == 'ask':
            want_ask = _round_to_tick(top['ask'], tick, 'down')
        else:
            want_bid = _round_to_tick(top['bid'], tick, 'up')

    # ЗАСТРЯВШАЯ ПОЗИЦИЯ ВЫХОДИТ ЧЕРЕЗ РЫНОК, А НЕ ЖДЁТ ЕЩЁ СУТКИ.
    #
    # Встать лучшей ценой на мёртвом рынке значит не выйти НИКОГДА: замер по
    # нашим же заявкам — три из четырнадцати без встречного потока вовсе,
    # очереди по четыре и девять тысяч контрактов, тишина до тридцати трёх
    # часов. Ожидание там не «долго», а бесконечно.
    #
    # Цена этому — пересечение спреда и комиссия тейкера, 4-7% от p×(1−p).
    # Цена бездействию — весь капитал позиции, стоящий без работы. Замерено на
    # живом счёте: $38.77 в запасе при $1.45 свободных, шестнадцать рынков и
    # три сделки за девять часов. Бот не сломался, ему стало не на что торговать.
    #
    # Поэтому после ВТОРОГО срока удержания встаём НА ВСТРЕЧНУЮ цену: продаём
    # по биду, покупаем по аску. Это немедленное исполнение, и оно нам нужно.
    if market.get('desperate') and position:
        only = 'ask' if position > 0 else 'bid'
        if only == 'ask':
            want_ask = _round_to_tick(top['bid'], tick, 'down')
        else:
            want_bid = _round_to_tick(top['ask'], tick, 'up')

    # ЗАКРЫВАЮЩАЯ СТОРОНА НЕ ПРОСИТ БОЛЬШЕ, ЧЕМ У НАС ЕСТЬ.
    #
    # ТИХАЯ И ДОРОГАЯ ОШИБКА, НАЙДЕННАЯ ПОСТОЯННЫМ КОНТРОЛЕМ ПОЗИЦИЙ. Частичное
    # исполнение оставляет остаток вроде 4.9926 контракта. Продажа же просилась
    # ровно на пять — а продать больше, чем держишь, биржа не даёт, и отправка
    # честно превращала продажу в ПОКУПКУ встречного токена по 0.927:
    #
    #     держим 4.9926 по 0.078, хотим продать 5
    #     уходит покупка «НЕТ» на $4.64 — денег нет, отказ каждый такт
    #
    # Снаружи это выглядело как «позиция без заявки»: выход не выставлен, и
    # почему — не сказано. Просим ровно то, что держим.
    #
    # ОСТАТОК НИЖЕ МИНИМУМА БИРЖИ НЕ ПРОДАТЬ ВОВСЕ, и притворяться иначе
    # незачем: заявка на 4.99 при минимуме 5 будет отвергнута. Такой остаток
    # называется прямо, чтобы его было видно, а не искать причину в отказах.
    floor = max(float(market.get('order_min') or 0),
                float(params.MM_MIN_ORDER_SIZE))
    if only and position and only == ('ask' if position > 0 else 'bid'):
        have = abs(float(position))
        if have < floor:
            return {'bid': None, 'ask': None, 'size': have, 'only': only,
                    'fair': fair, 'skew': skew, 'spread': None,
                    'mid': top['mid'], 'expected_seconds': None,
                    'reason': f'остаток {have:.4f} меньше минимума биржи {floor:.0f}'}
        size = min(size, have)

    # Обещанное время круга едет вместе с котировкой — чтобы в момент
    # исполнения было с чем сравнить вышедшее.
    promised = market.get('wait_hours')
    expected = (float(promised) * 3600
                if promised not in (None, float('inf')) else None)

    return {'bid': want_bid, 'ask': want_ask, 'size': size,
            'fair': fair, 'skew': skew, 'spread': round(want_ask - want_bid, 10),
            'mid': top['mid'], 'only': only, 'expected_seconds': expected,
            'reason': ''}
