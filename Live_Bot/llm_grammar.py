"""
Грамматика ответа: то, что делает выдуманную цену невозможной.

КАК ЭТО РАБОТАЕТ. llama.cpp умеет ограничивать выбор токенов на каждом шаге
формальной грамматикой (GBNF). Токены, не подходящие под неё, вычёркиваются ДО
выбора — не штрафуются, а именно исключаются. Значит ответ, не укладывающийся
в грамматику, не «маловероятен», а невозможен.

ПОЧЕМУ ЭТО ЗДЕСЬ ГЛАВНОЕ. Просьба в промпте «не выдумывай цены» — это просьба,
и модель её нарушит, причём незаметно: выдуманный уровень выглядит ровно так
же, как настоящий, и объяснение к нему будет таким же складным. Грамматика
переводит запрет из разряда пожеланий в разряд свойств: поле входа может быть
только одним из идентификаторов, собранных llm_context для ЭТОГО сетапа.

РАЗБОР ИДЁТ ПЕРВЫМ ПОЛЕМ, И ЭТО ЗАМЕНА РЕЖИМУ РАЗМЫШЛЕНИЯ. У Qwen3 есть режим
размышления: модель пишет <think>…</think> и только потом отвечает. С жёсткой
грамматикой он несовместим — она требует JSON с первого токена и размышление
попросту запрещает.

Выход оказался лучше исходного замысла. Поля JSON порождаются по порядку,
поэтому «режим рынка» и «разбор» поставлены ПЕРЕД решением: модель сначала
описывает, что видит, и только потом выбирает направление и уровни. Это то же
рассуждение вслух, но с двумя отличиями — оно не выбрасывается после ответа, а
попадает в журнал, и его читает человек.

КЛЮЧИ КОРОТКИЕ И ЛАТИНСКИЕ, И ЭТО НЕ НЕБРЕЖНОСТЬ. Кириллическое имя поля —
это три-четыре токена вместо одного. Важнее другое: JSON с кириллическими
ключами модель почти не встречала при обучении, и принуждение к нему
грамматикой ухудшает всё остальное в ответе. Человеческий текст в полях
остаётся русским — его читают люди.

ПРЕДЕЛЫ ДЛИНЫ ЩЕДРЫЕ, А НЕ ЭКОНОМНЫЕ. Первая версия резала объяснение на 300
символах, и живой ответ оборвался на полуслове: «…отношение хода к риску не
соответствует требованиям. Нужно ожид». Грамматика режет ровно на пределе, без
оглядки на границу предложения, и обрубок уходит в журнал именно так.

Управлять объёмом ограничением — значит получать обрезки. Пределы здесь стоят
настолько выше обычного ответа, что упереться в них нельзя; краткости, где она
нужна, требует промт.
"""

# Сколько целей разрешено назвать. Одна обязательна, больше трёх — это уже не
# план выхода, а пожелание: плечо дальних целей всё равно не отрабатывается.
MAX_TARGETS = 3

# Пределы длины полей в символах. Не средство экономии, а страховка от
# зацикливания: модель на медленном процессоре способна писать одно и то же
# предложение до конца окна контекста.
#
# ЗАМЕРЕНО 19 СЕНТЯБРЯ 2026, И ЭТО НЕ ДОГАДКА. Первый же полный ответ показал,
# во что обходится широкий предел: поле why на 800 знаков выродилось в
# «Нет подтверждения от расстояния до стопа. Нет подтверждения от расстояния
# до цели. Нет подтвержд» — двадцать повторов одной мысли до самого предела.
# Разбор при этом был по делу и уложился в 500 знаков.
#
# Одна страница ответа на этом процессоре — это минуты: 528 токенов заняли 295
# секунд. Каждая лишняя сотня знаков повтора оплачивается временем, за которое
# торговый цикл ждёт.
#
# Поэтому просторно ровно там, где есть что сказать: разбор. Остальные поля
# отвечают на один вопрос каждое, и предложения-двух им хватает.
#
# УЖАТО 19 СЕНТЯБРЯ 2026 ПО ПЕРВОМУ ОТВЕТУ «ВОЙТИ». Отказ — это разбор и
# «почему»; вход — ещё условие, риск и встречный сценарий, и полный ответ
# ETHUSDT упёрся в 1200 токенов на поле trigger, просчитав 862 секунды.
# На этом процессоре каждый токен ответа — две трети секунды, и просторные
# поля стоят минут, а не байтов. Лучшие живые разборы укладывались в 400-670
# знаков, ужатие их не задевает.
REGIME_CHARS = 160
ANALYSIS_CHARS = 800
TRIGGER_CHARS = 160
WHY_CHARS = 240
RISK_CHARS = 180
ALT_CHARS = 240

# Ответ проверяющего короче: он не разбирает рынок, а называет возражения.
CRITIC_ISSUES_CHARS = 450
CRITIC_WORST_CHARS = 160


def _alt(values):
    """Перечисление строковых литералов: "A" | "B" | "C"."""
    return ' | '.join(f'"\\"{v}\\""' for v in values)


def _text(limit):
    """Правило строки с пределом длины."""
    return f'"\\"" ch{{1,{limit}}} "\\""'


def build(level_ids, prices=None, min_stop_pct=0.0, min_rr=0.0):
    """
    Грамматика под КОНКРЕТНЫЙ список уровней.

    Строится заново на каждый сетап: сколько уровней нашлось, столько и
    разрешено. Общей грамматики «L1..L12» быть не может — на сетапе с семью
    уровнями она позволила бы сослаться на несуществующий L9.

    Пустой список означает, что выбирать не из чего: тогда допустим только
    отказ, и грамматика это выражает прямо.

    Вероятность ограничена диапазоном 0.01-0.99 намеренно. Единица означала бы
    уверенность без сомнений, а на рынке её не бывает: такое число говорит не о
    сетапе, а о том, что модель себя не откалибровала.
    """
    if not level_ids:
        return _skip_only()

    plans, rules = _plans(level_ids, prices, min_stop_pct, min_rr)
    if not plans:
        # Меньше трёх уровней — сделки не выразить: вход, стоп и цель обязаны
        # быть разными уровнями. Разрешить вход здесь значило бы разрешить
        # стоп на цене входа.
        return _skip_only()

    head = ('"{" ws "\\"regime\\":" ws regime ws ","'
            ' ws "\\"analysis\\":" ws analysis ws ","'
            ' ws "\\"bias\\":" ws bias ws ","')
    body = '\n'.join(rules)
    # УСЛОВИЕ ВХОДА — ОБЪЕКТ, А НЕ ТЕКСТ. Пока оно было строкой, модель
    # писала «дождаться закрытия выше L3», а код ставил лимит немедленно:
    # половина её логики не доходила до сделки. Теперь условие исполняет
    # код: «now» — лимит на вход сразу, «close_above»/«close_below» + уровень
    # — ждать закрытия часовой свечи за уровнем.
    # Семь условий, и все исполняет код (strategy_llm._check_armed):
    #   now                      лимит на вход сразу, ждёт цену
    #   close_above / close_below      закрытие часа за уровнем
    #   close_*_with_volume            то же при объёме ≥ 1.5× медианы
    #   retest                   пробой уровня по ходу сделки и возврат к нему
    #   sweep_reclaim            вынос за уровень против сделки и возврат ≤ 3 св.
    with_level = ('close_above', 'close_below', 'close_above_with_volume',
                  'close_below_with_volume', 'retest', 'sweep_reclaim')
    when = ' | '.join(['"\\"now\\""'] + [
        f'"\\"{name}\\"" ws "," ws "\\"level\\":" ws lvl' for name in with_level])
    return f'''root     ::= enter | skip
enter    ::= {head} ws "\\"d\\":\\"enter\\"," ws plan ws "," ws "\\"trigger\\":" ws trigger ws "," ws "\\"cf\\":" ws cf ws "," ws "\\"p\\":" ws prob ws "," ws "\\"why\\":" ws why ws "," ws "\\"risk\\":" ws risk ws "," ws "\\"alt\\":" ws alt ws "}}"
skip     ::= {head} ws "\\"d\\":\\"skip\\"," ws "\\"cf\\":" ws cf ws "," ws "\\"why\\":" ws why ws "}}"
plan     ::= {' | '.join(plans)}
{body}
cf       ::= "{{" ws "\\"poi\\":" ws bool ws "," ws "\\"vp\\":" ws bool ws "," ws "\\"der\\":" ws bool ws "," ws "\\"smc\\":" ws bool ws "," ws "\\"flow\\":" ws bool ws "}}"
bool     ::= "true" | "false"
bias     ::= "\\"up\\"" | "\\"down\\"" | "\\"flat\\""
prob     ::= "0." [0-9] [1-9] | "0." [1-9] [0-9]
regime   ::= {_text(REGIME_CHARS)}
analysis ::= {_text(ANALYSIS_CHARS)}
trigger  ::= "{{" ws "\\"when\\":" ws when ws "," ws "\\"note\\":" ws tnote ws "}}"
when     ::= {when}
lvl      ::= {_alt(level_ids)}
tnote    ::= {_text(TRIGGER_CHARS)}
why      ::= {_text(WHY_CHARS)}
risk     ::= {_text(RISK_CHARS)}
alt      ::= {_text(ALT_CHARS)}
ch       ::= [^"\\\\\\x00-\\x1f]
ws       ::= [ \\n]{{0,2}}
'''


def critic():
    """
    Грамматика ответа проверяющего: подтвердить или отклонить, и почему.

    Отдельная и короткая: у критика нет уровней и плана — только вердикт о
    чужом плане. Общая грамматика позволила бы ему «войти» самому.
    """
    return f'''root     ::= "{{" ws "\\"verdict\\":" ws verdict ws "," ws "\\"issues\\":" ws issues ws "," ws "\\"worst\\":" ws worst ws "}}"
verdict  ::= "\\"confirm\\"" | "\\"reject\\""
issues   ::= {_text(CRITIC_ISSUES_CHARS)}
worst    ::= {_text(CRITIC_WORST_CHARS)}
ch       ::= [^"\\\\\\x00-\\x1f]
ws       ::= [ \\n]{{0,2}}
'''


def _plans(level_ids, prices=None, min_stop_pct=0.0, min_rr=0.0):
    """
    По одному правилу на каждую пару «направление + уровень входа».

    ЗАЧЕМ ЭТО, КОГДА ГЕОМЕТРИЮ УЖЕ ПРОВЕРЯЕТ КОД. Проверка отвергает готовый
    ответ, а здесь неверный ответ становится НЕВОЗМОЖНЫМ — как уже сделано с
    ценами: модель не придумывает число, потому что ей разрешены только
    идентификаторы из списка.

    Разница не теоретическая. 19 сентября 2026, в первый же день, когда модель
    начала отвечать целиком, два вердикта из трёх умерли на предохранителе
    геометрии: для лонга она выбирала цели НИЖЕ входа. Текст задачи прямо
    требует обратного — восьмимиллиардная модель этого не держит. Со стороны
    получалось «стратегия работает, но никогда не торгует».

    ПОРЯДОК СПИСКА — ЭТО ЦЕНА. Уровни приходят сверху вниз: llm_context
    сортирует их по убыванию цены и только потом нумерует. Значит «выше» — это
    раньше в списке, «ниже» — позже, и самих цен грамматике знать не нужно.

    Уровни входа, для которых нет ни одного стопа или ни одной цели, ветки не
    получают вовсе: лонг от самого верхнего уровня целиться некуда. Это
    заодно закрывает случай, когда вся разметка оказалась по одну сторону от
    цены — тогда останется только отказ, и он будет честным.
    """
    # РАССТОЯНИЯ — ТОЖЕ ГРАММАТИКОЙ. 19 сентября 2026 два первых плана
    # «войти» умерли на предохранителях: шорт XRP со стопом в 0.39% при
    # минимуме 1.5% и лонг DOGE с целью в 1.5% при стопе 1.7% (R:R 0.9).
    # Текст задания называет оба предела, модель их не держит — как раньше
    # не держала геометрию. Уровни с ценами известны, значит стоп ближе
    # минимума и цель ближе min_rr × минимум можно просто не разрешать:
    # неверный ответ становится невыразимым, а не отвергаемым.
    #
    # Цель проверяется по НЕОБХОДИМОМУ условию (расстояние ≥ min_rr × минимум
    # стопа): точный R:R зависит от выбранного стопа и остаётся за кодом.
    price_of = dict(zip(level_ids, prices)) if prices else {}

    def far_enough(a, b, pct):
        if not pct or a not in price_of or b not in price_of or not price_of[a]:
            return True
        return abs(price_of[a] - price_of[b]) / price_of[a] * 100 >= pct

    plans, rules = [], []
    for side in ('LONG', 'SHORT'):
        for index, entry in enumerate(level_ids):
            higher = list(level_ids[:index])
            lower = list(level_ids[index + 1:])
            stops, targets = (lower, higher) if side == 'LONG' else (higher, lower)
            stops = [s for s in stops if far_enough(entry, s, min_stop_pct)]
            targets = [t for t in targets
                       if far_enough(entry, t, min_rr * min_stop_pct)]
            if not stops or not targets:
                continue
            # ИМЯ ПРАВИЛА — ТОЛЬКО БУКВЫ, ЦИФРЫ И ДЕФИС. Подчёркивание
            # llama.cpp в именах не принимает: её разборщик читает имя до
            # первого недопустимого знака и падает с «expecting newline or
            # end at _l2». Проверки этого не ловили — они читают текст
            # грамматики сами, — и поломка вышла наружу только на сервере, в
            # журнале службы. Строчные буквы нужны referenced(): имя с
            # заглавной она прочитает наполовину.
            name = f'{side.lower()}-{entry.lower()}'
            rules.append(
                f'{name} ::= "\\"side\\":" ws {_alt([side])} ws "," ws '
                f'"\\"entry\\":" ws {_alt([entry])} ws "," ws '
                f'"\\"stop\\":" ws s-{name} ws "," ws '
                f'"\\"tp\\":" ws tp-{name} ws "," ws '
                f'"\\"inval\\":" ws s-{name}')
            # Уровень инвалидации — из того же набора, что и стоп: идея лонга
            # умирает ПОД входом, а не над ним.
            rules.append(f's-{name} ::= {_alt(stops)}')
            rules.append(f'tp-{name} ::= {_targets_rule(f"t-{name}")}')
            rules.append(f't-{name} ::= {_alt(targets)}')
            plans.append(name)
    return plans, rules


def _targets_rule(item='lv'):
    """
    От одной до MAX_TARGETS целей списком.

    Длины перечисляются явно: "[" t "]" | "[" t "," t "]" | ...
    Через повторение t* было бы короче, но тогда грамматика разрешила бы и
    пустой список целей — то есть вход без единого выхода.

    `item` — имя правила одной цели. У каждой пары «направление + вход» свой
    набор допустимых целей, поэтому общего правила на всех больше нет.
    """
    out = []
    for count in range(1, MAX_TARGETS + 1):
        body = ' ws "," ws '.join([item] * count)
        out.append(f'"[" ws {body} ws "]"')
    return ' | '.join(out)


def _skip_only():
    """
    Уровней нет — разрешён только отказ.

    Так бывает на ровном рынке и на короткой истории. Позволить в этом случае
    вход значило бы позволить сослаться на уровень, которого не существует.
    """
    return f'''root     ::= "{{" ws "\\"regime\\":" ws regime ws "," ws "\\"analysis\\":" ws analysis ws "," ws "\\"bias\\":" ws bias ws "," ws "\\"d\\":\\"skip\\"," ws "\\"cf\\":" ws cf ws "," ws "\\"why\\":" ws why ws "}}"
bias     ::= "\\"up\\"" | "\\"down\\"" | "\\"flat\\""
cf       ::= "{{" ws "\\"poi\\":" ws bool ws "," ws "\\"vp\\":" ws bool ws "," ws "\\"der\\":" ws bool ws "," ws "\\"smc\\":" ws bool ws "," ws "\\"flow\\":" ws bool ws "}}"
bool     ::= "true" | "false"
regime   ::= {_text(REGIME_CHARS)}
analysis ::= {_text(ANALYSIS_CHARS)}
why      ::= {_text(WHY_CHARS)}
ch       ::= [^"\\\\\\x00-\\x1f]
ws       ::= [ \\n]{{0,2}}
'''


def rules_of(grammar):
    """Имена определённых правил — для проверки, что ни одно не потеряно."""
    names = []
    for line in grammar.splitlines():
        if '::=' in line:
            names.append(line.split('::=')[0].strip())
    return names


def referenced(grammar):
    """
    Имена правил, на которые грамматика ссылается.

    Нужно ровно для одной проверки: каждое упомянутое правило определено.
    Опечатка в имени превращает грамматику в нерабочую, и llama.cpp скажет об
    этом только в момент вызова — то есть в бою.
    """
    import re
    out = set()
    for line in grammar.splitlines():
        if '::=' not in line:
            continue
        body = line.split('::=', 1)[1]
        # Убираем строковые литералы: внутри них слова — это текст, не правила.
        body = re.sub(r'"(?:[^"\\]|\\.)*"', ' ', body)
        # И символьные классы вида [^"\\\x00-\x1f]: это диапазоны, а не ссылки.
        # Без этой строки проверка сообщала о «неопределённых правилах» x00 и
        # x1f — то есть отправляла искать ошибку, которой нет.
        body = re.sub(r'\[[^\]]*\]', ' ', body)
        # Дефис входит в имя: llama.cpp допускает в именах буквы, цифры и
        # дефис, и правило tp-long-l2 без него читалось бы как три ссылки на
        # несуществующие tp, long и l2.
        for word in re.findall(r'[a-z][a-z0-9-]*[a-z0-9]|[a-z]', body):
            out.add(word)
    return out
