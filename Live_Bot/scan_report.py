"""
Воронка отсева: почему бот не открыл сделку по каждой паре.

Самый частый вопрос при наблюдении за ботом — «почему он ничего не делает».
Ответ бот уже знает: каждый сканер по каждой паре формулирует причину отказа
(«bias нейтрален», «confluence 4.2 < 4.7», «нет активных POI»). Но раньше эта
причина уходила только в лог, где терялась среди сотен строк.

Здесь причины собираются в сводку за последний цикл. По ней сразу видно, на
каком шаге стоит стена: если 15 пар из 16 отсеиваются на bias, дело не в
качестве зон, а в том, что рынок не даёт направления.

Модуль намеренно простой: словарь в памяти, без диска. Сводка живёт до
следующего цикла, история хранится в журнале сделок.
"""

import threading
from collections import Counter
from datetime import datetime

# Причины отказа приходят строками с числами внутри («confluence 4.2 < 4.7»),
# и без нормализации каждая пара давала бы отдельную строку в сводке.
#
# ПОРЯДОК ЗНАЧИМ: правила проверяются сверху вниз, и более частные должны
# стоять раньше общих. «нога BEARISH против bias BULLISH» содержит слово
# «bias», и при обратном порядке эта причина попадала бы в категорию
# «нет направления», хотя направление как раз есть — не совпал импульс.
_NORMALISE = (
    ('confluence', 'слабое подтверждение (confluence ниже порога)'),
    ('нога', 'импульс против направления или не той длины'),
    ('нет активных POI', 'нет свежих зон интереса'),
    ('цена уже прошла зону', 'цена уже прошла зону — вход не имеет смысла'),
    ('цена вне пред-входовой', 'цена ещё не подошла к зоне входа'),
    ('инвалидирован', 'сетап отменён — цена ушла за уровень'),
    ('кулдаун', 'пауза после недавней сделки по паре'),
    ('позиция или ордер', 'по паре уже есть позиция или ордер'),
    ('против старшего тренда', 'против старшего тренда'),
    ('дисконт', 'зона не в дисконте или премиуме'),
    ('OTE', 'зона вне OTE'),
    ('killzone', 'вне торговой сессии'),
    ('мало данных', 'мало истории по паре'),
    ('мало истории', 'мало истории по паре'),
    ('импульс не найден', 'импульс не найден'),
    ('импульс', 'импульс слишком мал'),
    ('RR', 'соотношение риска к прибыли ниже порога'),
    ('bias', 'нет направления на старшем таймфрейме'),
    ('чёрном списке', 'пара в чёрном списке'),
    ('низкая цена', 'слишком низкая цена инструмента'),
    ('объём', 'недостаточный объём торгов'),
    ('ошибка', 'ошибка сканирования'),
)

_lock = threading.Lock()
_current = {}     # стратегия -> накопление текущего цикла
_last = {}        # стратегия -> сводка завершённого цикла


def _label(reason):
    """Сводит частные формулировки к понятной категории."""
    if not reason:
        return 'сигнал найден'
    text = str(reason)
    for needle, label in _NORMALISE:
        if needle in text:
            return label
    return text[:60]


def begin(strategy):
    """Начало цикла сканирования по стратегии."""
    with _lock:
        _current[strategy] = {'started': datetime.now(), 'reasons': Counter(),
                              'pairs': 0, 'found': 0, 'examples': {}}


def record(strategy, pair, reason=None):
    """
    Фиксирует исход по одной паре. reason=None означает найденный сетап.

    Вызывается из сканеров вместо простого log() — чтобы причина попадала не
    только в текстовый лог, но и в сводку для дашборда.
    """
    with _lock:
        item = _current.get(strategy)
        if item is None:
            return
        item['pairs'] += 1
        if reason is None:
            item['found'] += 1
            return
        label = _label(reason)
        item['reasons'][label] += 1
        # Первый пример по каждой категории: помогает понять, насколько
        # близко пара была к сигналу («confluence 4.5 < 4.7» — почти прошла).
        item['examples'].setdefault(label, f'{pair}: {reason}')


def finish(strategy):
    """Завершение цикла: сводка становится доступной дашборду."""
    with _lock:
        item = _current.pop(strategy, None)
        if item is None:
            return
        _last[strategy] = {
            'at': item['started'].isoformat(timespec='seconds'),
            'pairs': item['pairs'],
            'found': item['found'],
            'reasons': [
                {'reason': name, 'count': count,
                 'example': item['examples'].get(name, '')}
                for name, count in item['reasons'].most_common()
            ],
        }


def snapshot():
    """Сводки последнего завершённого цикла по каждой стратегии."""
    with _lock:
        return {name: dict(data) for name, data in _last.items()}
