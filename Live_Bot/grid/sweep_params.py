"""
Ложный пробой границы коридора: параметры. Свои, ничего не заимствовано.

ОТКУДА ЭТА ФОРМУЛИРОВКА. Не из головы — из трёх собственных замеров, которые
все три говорят одно, и из внешних источников, которые объясняют почему.

    что торговали                       результат
    пробой уровня (вход на прорыве)     края нет, три оси проверены
    сетка (лимит НА краю коридора)      края нет ещё до издержек
    прокол с возвратом (вход ПОСЛЕ)     работает: 0.279 и 0.374 R

Источники дают механику: за границами коридора скапливаются стопы. Цена
выносит их, чтобы набрать крупный объём, и разворачивается. Лимит, стоящий на
краю, систематически покупает у того, кто сметает стопы, — а вход на пробое
оказывается той самой вынесенной стороной.

В терминах Вайкоффа это spring (прокол поддержки с возвратом) и upthrust
(прокол сопротивления с возвратом).

ЧЕМ ОТЛИЧАЕТСЯ ОТ НАШЕЙ ЖЕ СТРАТЕГИИ УРОВНЕЙ. Там любой уровень из пивотов и
цель на следующем уровне — отсюда отношение риска к прибыли около 2. Здесь
нужен ПОДТВЕРЖДЁННЫЙ коридор, а цель ставится на противоположном крае, то
есть в разы дальше. Именно короткая цель убила сетку: при RR 0.38 безубыток
требовал 72% попаданий.

ПРО ОБЪЁМ ЕСТЬ ПРОТИВОРЕЧИЕ, И ОНО МЕРИТСЯ. Вайкофф говорит, что spring
подтверждается НИЗКИМ объёмом на проколе: продавца нет, вынос технический.
Наша стратегия уровней требует ВЫСОКОГО объёма на возврате: за отбоем кто-то
стоит. Это разные утверждения о разных барах, и оба проверяются вариантами.
"""

import os


def _f(name, default):
    return float(os.getenv(f'SWEEP_{name}', default))


def _i(name, default):
    return int(os.getenv(f'SWEEP_{name}', default))


# ── Прокол ───────────────────────────────────────────────────────────────────
# Насколько глубоко цена должна выйти за границу, в ATR. Мелкое касание края —
# это ещё не вынос стопов, а просто подход.
PIERCE_ATR = _f('PIERCE_ATR', 0.25)
# За сколько баров должен случиться возврат внутрь. Дольше — это уже не вынос,
# а настоящий выход из коридора.
RECLAIM_BARS = _i('RECLAIM_BARS', 4)

# ── Подтверждение объёмом ────────────────────────────────────────────────────
VOLUME_WINDOW = _i('VOLUME_WINDOW', 24)
# Объём НА ПРОКОЛЕ не выше этой доли среднего (условие Вайкоффа). Ноль
# отключает проверку.
MAX_PIERCE_VOLUME = _f('MAX_PIERCE_VOLUME', 0.0)
# Объём НА ВОЗВРАТЕ не ниже этой доли среднего (условие нашей стратегии
# уровней). Ноль отключает.
MIN_RECLAIM_VOLUME = _f('MIN_RECLAIM_VOLUME', 0.0)

# ── Выход ────────────────────────────────────────────────────────────────────
# Запас за экстремум прокола до стопа, в ATR.
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.25)
# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.5)
# Куда целимся: 1.0 — противоположный край коридора, 0.5 — середина.
TARGET_FRAC = _f('TARGET_FRAC', 1.0)
MIN_RR = _f('MIN_RR', 1.0)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 72)
EXPIRY_BARS = _i('EXPIRY_BARS', 4)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 6)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 6.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
