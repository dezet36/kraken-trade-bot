"""
Сетка в коридоре: параметры. Свои, ни одно число не заимствовано у соседей.

ЗАЧЕМ ЭТА ИДЕЯ ПОСЛЕ ЧЕТЫРЁХ ЗАКРЫТЫХ. Не потому что красивая, а из-за
арифметики издержек — она и топила предыдущие:

    круг тейкером с проскальзыванием            0.210%
    круг мейкером (лимит вход + лимит выход)     0.040%

Здесь ОБА конца лимитные по построению: заявки стоят внутри коридора, и цена
приходит к ним сама, догонять её не надо. При шаге сетки 0.3% издержки съедают
13% прибыли уровня, а не всю её целиком, как у пробоя на пятиминутках.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ОБЫЧНОГО ГРИД-БОТА. У того нет стопа: цена падает — он
докупает, ещё падает — ещё докупает. Кривая доходности выглядит прекрасно
месяцами, потом за неделю уходит в ноль. Математически это продажа
волатильности: много мелких премий собрано, одна большая заплачена.

Здесь есть общий стоп за границей коридора и предел числа набранных уровней.
Без них мерилась бы не стратегия, а отсрочка убытка.

ПОРОГИ ВЗЯТЫ ИЗ ДАННЫХ, А НЕ НАЗНАЧЕНЫ. На часовых BTC, окно 48 баров, 9532
наблюдения:

    ширина коридора в ATR    25-й процентиль 5.9 · медиана 7.3 · 75-й 9.3
    пересечений середины     25-й процентиль 2   · медиана 4   · 75-й 6

Ширина не больше 6 ATR вместе с шестью пересечениями дают 13% окон. Коридор
бывает нечасто — так и должно быть: две трети времени рынок куда-то идёт.

Назначать пороги на глаз я за этот день пробовал дважды, и оба раза значение
оказывалось за пределами реального распределения.
"""

import os


def _f(name, default):
    return float(os.getenv(f'GRID_{name}', default))


def _i(name, default):
    return int(os.getenv(f'GRID_{name}', default))


# ── Что считается коридором ──────────────────────────────────────────────────
# Окно наблюдения, баров рабочего таймфрейма (48 часовых свечей).
WINDOW = _i('WINDOW', 48)

# Ширина коридора в величинах ATR одного бара. Нижняя четверть распределения.
MAX_WIDTH_ATR = _f('MAX_WIDTH_ATR', 6.0)

# Сколько раз цена пересекла середину коридора. ГЛАВНОЕ условие: именно оно
# отличает боковик от пологого тренда, который в рамку по ширине тоже влезает.
# В тренде пересечений одно-два, в боковике шесть-восемь.
MIN_CROSSES = _i('MIN_CROSSES', 6)

# ── Сетка ────────────────────────────────────────────────────────────────────
# Число уровней внутри коридора, считая обе стороны от середины.
LEVELS = _i('LEVELS', 6)

# Сколько уровней разрешено набрать одновременно. Без предела проход цены
# насквозь набирает всю лестницу, и экспозиция оказывается кратно больше
# заявленного риска — при том что стоп у всех уровней ОБЩИЙ и сработает разом.
MAX_FILLED = _i('MAX_FILLED', 4)

# ── Выход ────────────────────────────────────────────────────────────────────
# Запас за границей коридора до общего стопа, в ATR.
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.5)

# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума:
# круг стоит 0.04-0.21% от объёма, и при стопе 0.2% это заметная доля R.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.5)

# Сколько живёт заявка уровня, баров. Коридор не вечен: не набралось — снимаем.
EXPIRY_BARS = _i('EXPIRY_BARS', 24)

# Предел удержания набранного уровня.
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 72)

# ── Портфель ─────────────────────────────────────────────────────────────────
# Риск на ВЕСЬ коридор, а не на уровень: уровни делят его между собой. Стоп у
# них общий, и в плохом случае они проигрывают одновременно — считать их
# независимыми ставками значило бы занизить риск в MAX_FILLED раз.
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 8)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 2.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
