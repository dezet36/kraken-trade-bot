"""
Портфельные пределы. ОДНА реализация на оба пути — бумажный и боевой.

ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ. Правила стояли в двух местах: `PaperBroker.
_portfolio_room` и `TradeManager._portfolio_room`. Почти одинаковые, и
поддерживать их полагалось вручную.

Так это и сломалось. Коммит 256f242 добавил дневной стоп-кран — тронул
бумажный брокер, панель, настройки и тесты, а боевой путь не тронул вовсе. С
6 августа 2026 предел дневного убытка существовал в настройках, показывался в
панели, работал на бумаге — и НЕ ПРОВЕРЯЛСЯ на живых деньгах. Никто этого не
заметил, потому что замечать было нечем: копии никто не сверял.

Хуже того, панель в боевом режиме брала дневной итог у объекта, где такого
метода нет, и показывала ноль. То есть предохранителя не было, а приборная
доска показывала «сегодня $0.00» — не потому что не потеряли, а потому что не
спросили.

Отсюда правило: НОВОЕ ОГРАНИЧЕНИЕ ДОБАВЛЯЕТСЯ ТОЛЬКО СЮДА. Оба вызывающих
кода передают свои числа и получают общий ответ; проверка парности следит,
чтобы ни один не завёл собственную копию (tests/test_risk_gate.py).

Числа передаются готовыми, а не добываются здесь: у путей разные источники —
у бумажного депозиты раздельные по стратегиям, у боевого один счёт биржи.
Считать их здесь значило бы тащить в модуль оба мира.
"""

from logger import log

# Ноль означает «предела нет». Это НЕ описка и не забытая настройка: так
# ограничение выключается одним полем, не удаляя значение. Опасность в другом —
# выключенный предел ничем не отличается на вид от настроенного, поэтому
# `disabled_limits` называет их поимённо, а диагностика и панель показывают.
UNLIMITED = 0


def day_result(rows, deposit, today):
    """
    Итог закрытых СЕГОДНЯ сделок: сумма и доля депозита.

    Считается по журналу, а не по счётчику в памяти: счётчик обнуляется при
    перезапуске, и бот, перезапущенный посреди плохого дня, начинал бы его
    заново — ровно тогда, когда предел нужнее всего.

    `today` передаётся вызывающим и обязан быть в тех же часах, что и время
    закрытия в журнале. Журнал пишется в UTC, и в местный вечер два
    представления о дне расходятся: предел считал бы вчерашние сделки
    сегодняшними или наоборот.
    """
    pnl = 0.0
    for row in rows or ():
        if str(row.get('close_time', ''))[:10] != today:
            continue
        try:
            pnl += float(row.get('pnl_usd') or 0)
        except (TypeError, ValueError):
            continue
    pct = (pnl / deposit * 100) if deposit else 0.0
    return pnl, pct


def daily_stop_hit(day_pnl, day_pct, limit_pct):
    """
    Сработал ли дневной стоп-кран.

    Отдельно от предела портфеля не для симметрии: тот ограничивает риск,
    стоящий в рынке ОДНОВРЕМЕННО, и молчит, когда десять сделок закрылись в
    минус по очереди. Плохой день выглядит именно так — каждая сделка по
    правилам, а к вечеру депозита нет.

    Уже открытые позиции предел не трогает: они ведутся до своих стопов и
    целей. Закрывать их принудительно значило бы фиксировать убыток по худшей
    цене дня ровно тогда, когда рынок и так против.
    """
    if not limit_pct:
        return False, ''
    if day_pnl >= 0 or -day_pct < limit_pct:
        return False, ''
    return True, (f'дневной предел убытка: {day_pct:.2f}% при пределе '
                  f'{limit_pct:.2f}% — новые сделки до завтра не открываются')


def check(*, slots_used, max_positions, risk_used, deposit, adding,
          risk_limit_pct, day_pnl, day_pct, day_limit_pct):
    """
    Пропускают ли пределы ещё одну сделку. Возвращает (можно, причина).

    Порядок проверок не случаен: дневной стоп первым. Он говорит «сегодня
    больше не торгуем» — самое сильное из ограничений, и проверять после него
    что-то ещё бессмысленно.

    `adding` — риск НОВОЙ сделки в деньгах. Считает вызывающий: у бумажного
    пути это доля депозита СВОЕЙ стратегии, у боевого — доля общего счёта.
    """
    stopped, why = daily_stop_hit(day_pnl, day_pct, day_limit_pct)
    if stopped:
        return False, why

    if max_positions and slots_used >= max_positions:
        return False, (f'предел портфеля: занято {slots_used}/{max_positions} '
                       f'позиций')

    if not risk_limit_pct:
        return True, ''
    if deposit <= 0:
        return True, ''

    pct = risk_used / deposit * 100
    after = (risk_used + adding) / deposit * 100
    if after > risk_limit_pct:
        return False, (f'предел портфеля: под риском {pct:.1f}%, сделка добавит '
                       f'до {after:.1f}% при пределе {risk_limit_pct:.1f}%')
    return True, ''


# Последние успешно прочитанные пределы. Живут в памяти процесса и нужны
# ровно на случай, когда файл настроек вдруг не читается.
_last_good = None


def remember(max_positions, risk_limit_pct, day_limit_pct):
    """Запоминает пределы, которые удалось прочитать."""
    global _last_good
    _last_good = (max_positions, risk_limit_pct, day_limit_pct)


def settings_unavailable(exc):
    """
    Настройки не прочитались. Возвращает пределы, по которым всё же судить,
    либо None, если судить не по чему.

    ОТКАЗ ЧТЕНИЯ ФАЙЛА НЕ ДОЛЖЕН СНИМАТЬ ЗАЩИТУ. Здесь стояло «пропускаем, но
    громко»: занятый или битый файл настроек означал сделку вообще без
    проверки пределов. Заманчиво было бы, наоборот, запретить торговлю — но
    это тоже неверно: позиции уже в рынке, их надо вести, а остановка из-за
    сбоя ввода-вывода останавливает и ведение.

    Верный ответ третий: судить по последним значениям, которые точно
    читались. Они почти наверняка те же самые — настройки меняют редко, а
    файл ломается ещё реже.

    Совсем без них (сбой на первом же чтении после запуска) остаётся прежнее
    поведение: пропустить и сказать об этом прямо.
    """
    if _last_good is not None:
        log(f'⚠️ Пределы портфеля не прочитаны ({exc}) — беру последние '
            f'известные: позиций {_last_good[0]}, риск {_last_good[1]}%, '
            f'дневной {_last_good[2]}%.')
        return _last_good
    log(f'⚠️ Пределы портфеля не прочитаны ({exc}) и ни разу не читались с '
        f'запуска — сделка пропущена БЕЗ проверки пределов. Проверьте '
        f'настройки.')
    return None


def disabled_limits(max_positions, risk_limit_pct, day_limit_pct,
                    cost_limit_pct=None):
    """
    Какие пределы сейчас выключены — списком человеческих названий.

    Нужно потому, что выключенный предел выглядит настроенным: в поле стоит
    ноль, и на глаз это неотличимо от «ещё не задал». Диагностика и панель
    обязаны называть это прямо.
    """
    off = []
    if not max_positions:
        off.append('предел числа позиций')
    if not risk_limit_pct:
        off.append('предел риска портфеля')
    if not day_limit_pct:
        off.append('дневной предел убытка')
    # None — «не спрашивали». Прежние вызывающие про этот предел не знают, и
    # молчание для них правильнее выдумки.
    if cost_limit_pct is not None and not cost_limit_pct:
        off.append('предел расхода на вход')
    return off


def exposure_by_strategy(entries):
    """
    Сколько СВОЕГО депозита каждая стратегия держит под риском, заняв все свои
    слоты. Список пар (имя, проценты); проценты None — слотов без предела.

    entries — последовательность (имя, слотов, риск_на_сделку_%).

    СКЛАДЫВАТЬ ЭТИ ЧИСЛА НЕЛЬЗЯ, и прежняя версия (max_exposure) складывала.
    Она возвращала одну сумму и называла её «процент депозита» — но депозит у
    каждой стратегии СВОЙ И В ДЕНЬГАХ:

        FIBO $20 000 · LEVELS $9 200 · SMC $6 800 · RSIBB $4 000

    Полпроцента у фибо — это $100, полпроцента у боллинджера — $20. Сложение
    таких процентов даёт число, не относящееся ни к одному депозиту. Оно
    выглядело убедительно: диагностика показывала «до 40% депозита под риском
    одновременно», и по нему трижды предлагалось чинить то, что не сломано.

    Раздельность бюджетов не случайна — config объясняет, что доли общего
    котла убрали намеренно, чтобы правка у одной стратегии молча не двигала
    деньги у остальных. Складывающая функция возвращала эту связь чёрным
    ходом, через отчётность.

    Тот же запрет уже действует в панели для направлений: «сложив их, мы
    получили бы число, которое ничего не значит, зато выглядит убедительно».
    """
    out = []
    for name, slots, risk_pct in entries:
        out.append((name, None if not slots else slots * risk_pct))
    return out

def entry_cost_share(entry_price, sl_dist, fee_round_trip):
    """
    Какую долю РИСКА съедят комиссии за вход и выход. В долях единицы.

    Выводится из размера позиции и потому не требует его знать:

        объём  = риск / дистанция_стопа × цена
        расход = объём × ставка_туда-обратно
        доля   = расход / риск = цена / дистанция_стопа × ставка

    Отсюда видно главное: доля зависит ТОЛЬКО от того, насколько тесен стоп.
    Чем ближе стоп, тем больше объём на тот же риск — и тем дороже вход.

    ОТКУДА ЭТО. Разбор 364 сделок с сервера за 5–29 августа 2026: грязный
    итог +$34.94, комиссии −$661.03, чистый −$616.77. То есть стратегии
    сработали в ноль, а весь убыток — издержки. По стратегиям расход на
    сделку составил: FIBO 3.3% риска (стоп 3.10%), LEVELS 5.5%, RSIBB 5.4%,
    SMC 7.0% (стоп 1.19%, плечо 94x).
    """
    if sl_dist <= 0 or entry_price <= 0:
        return 0.0
    return entry_price / sl_dist * fee_round_trip


def cost_too_high(entry_price, sl_dist, fee_round_trip, limit_pct):
    """
    Не слишком ли дорог вход. Возвращает (дорого, доля_в_процентах, причина).

    Ноль в пределе означает «не проверять» — как и у остальных пределов.

    ЭТО ПРЕДЕЛ РАСХОДА, А НЕ ПРЕДСКАЗАНИЕ. Он не утверждает, что тесные
    стопы проигрывают, — он отказывается платить заведомо много. Разница
    важная, и вот почему.

    На выборке сервера порог 3% поднимал ожидание с −0.028R до +0.181R, и
    соблазн поставить его туда был силён. Но перестановочная проверка
    показала: настоящей экономией комиссий объясняется лишь 8% прибавки,
    остальное — отбор по исходу. А сам порог 3% выбран из семи опробованных,
    и с поправкой на перебор его p поднимается с 0.012 до ≈0.08. То есть
    «широкий стоп выгоднее» — гипотеза, а не факт.

    Поэтому предел по умолчанию стоит там, где оправдан одной арифметикой:
    отсекает крайние случаи (у RSIBB встречались входы по 12.4% риска), не
    трогая обычные. А чтобы гипотезу можно было проверить на новых данных, а
    не на тех же самых, доля издержек пишется в журнал каждой сделки.
    """
    share = entry_cost_share(entry_price, sl_dist, fee_round_trip) * 100
    if not limit_pct or share <= limit_pct:
        return False, share, ''
    return True, share, (f'вход слишком дорог: комиссии съедят {share:.1f}% '
                         f'риска при пределе {limit_pct:.1f}% — стоп стоит '
                         f'слишком тесно')
