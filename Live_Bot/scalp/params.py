"""
Параметры пробойной стратегии. СВОИ, ни один не заимствован у других.

Стратегии в этом проекте живут отдельно: у каждой свой файл параметров, своя
геометрия и свой замер. Заимствование чужого числа выглядит экономией, но
означает, что при перенастройке одной стратегии молча меняется другая — и
понять это можно только по разошедшейся доходности через месяцы.

ОТКУДА ЧИСЛА. Из правил, а не из подбора. Всё, что здесь стоит, взято из
описания самого приёма и из внешних источников по пробойной торговле, и ни
одно ещё не оптимизировалось под наши данные. Так и надо начинать: сначала
честная реализация правил, потом замер, и только потом — разговор о числах.
Подбор до замера даёт красивую кривую, которая не повторяется.

ГЛАВНОЕ ОГРАНИЧЕНИЕ — ИЗДЕРЖКИ. Вход по стоп-ордеру платит тейкерскую
комиссию и проскальзывание с обеих сторон: круг 0.21% от объёма. При стопе
0.2% это 1.05 R с каждой сделки, и никакой винрейт этого не окупает.
Поэтому MIN_STOP_PCT здесь не «защита от шума», как у других стратегий, а
арифметическая граница осмысленности.
"""

import os


def _f(name, default):
    return float(os.getenv(f'BRK_{name}', default))


def _i(name, default):
    return int(os.getenv(f'BRK_{name}', default))


# ── Таймфреймы ───────────────────────────────────────────────────────────────
TF_SIGNAL = os.getenv('BRK_TF_SIGNAL', '5m')     # поиск прижатия и пробоя
TF_LEVEL = os.getenv('BRK_TF_LEVEL', '1h')       # уровни ищутся на старшем ТФ

# ── Уровни ───────────────────────────────────────────────────────────────────
# Уровень тем ценнее, чем больше раз цену от него отбивали: два касания — это
# уже не случайность, а место, где кто-то стоит.
PIVOT_N = _i('PIVOT_N', 2)                       # окно локального экстремума
TOLERANCE_PCT = _f('TOLERANCE_PCT', 0.15)        # касания в пределах 0.15% — один уровень
MIN_TOUCHES = _i('MIN_TOUCHES', 2)
MAX_AGE_BARS = _i('MAX_AGE_BARS', 240)           # уровень старше 10 суток (1h) забыт
NEAREST_LEVELS = _i('NEAREST_LEVELS', 2)         # сколько ближайших рассматриваем

# ── Прижатие ─────────────────────────────────────────────────────────────────
# Сжатие диапазона перед пробоем — то, чего не было в прежнем замере голого
# пробоя канала, и то, что внешние источники называют главным признаком
# настоящего пробоя. Реализовано как NR-условие: диапазон последних баров
# должен быть узким относительно волатильности.
SQUEEZE_BARS = _i('SQUEEZE_BARS', 12)            # окно прижатия (12 x 5м = час)
# Порог взят ИЗ ДАННЫХ, а не назначен. Отношение «диапазон 12 баров к ATR
# одного бара» на 5-минутках BTC распределено так:
#
#     5-й процентиль 2.40 · 25-й 3.07 · медиана 3.70 · 75-й 4.47
#
# Первое моё значение было 1.6 — ниже пятого процентиля, то есть «прижатие»
# не случалось почти никогда: на двадцати тысячах баров нашёлся один сетап.
# Ошибка была в единицах: диапазон ДВЕНАДЦАТИ баров сравнивался с ATR ОДНОГО.
# Берём нижнюю четверть — это и есть «рынок замер» без вымирания сетапов.
SQUEEZE_ATR = _f('SQUEEZE_ATR', 3.0)             # диапазон окна <= 3 ATR
NEAR_ATR = _f('NEAR_ATR', 0.8)                   # «вплотную к уровню» в ATR
NEAR_MIN_BARS = _i('NEAR_MIN_BARS', 5)           # столько баров из окна — вплотную

# ── Пробой ───────────────────────────────────────────────────────────────────
# Закрытие ЗА уровнем, а не прокол тенью: тень за уровнем — это чаще снятие
# ликвидности, чем пробой. Ровно на этом прежний замер и потерял деньги.
BREAK_ATR = _f('BREAK_ATR', 0.25)                # насколько закрытие ушло за уровень
VOLUME_WINDOW = _i('VOLUME_WINDOW', 20)
VOLUME_RATIO = _f('VOLUME_RATIO', 1.2)           # объём >= 120% среднего

# ── Вход ─────────────────────────────────────────────────────────────────────
# Два способа, оба меряются:
#   break  — сразу на пробое; не пропустишь импульс, но платишь тейкера
#   retest — лимит на возврате к пробитому уровню; мейкерская комиссия и
#            отсев ложных пробоев, но часть импульсов уходит без нас
ENTRY_MODE = os.getenv('BRK_ENTRY_MODE', 'break')
RETEST_OFFSET_ATR = _f('RETEST_OFFSET_ATR', 0.1)  # насколько не доводим лимит до уровня
RETEST_MAX_BARS = _i('RETEST_MAX_BARS', 12)       # сколько ждём возврата

# ── Стоп и цель ──────────────────────────────────────────────────────────────
# Стоп за границу прижатия: если цена вернулась внутрь диапазона, пробой не
# состоялся, и держать нечего. Буфер 0.25 ATR — чтобы не выносило тенью.
# box — за границу прижатия, level — сразу за пробитый уровень. Что лучше,
# решает замер: широкий стоп реже выносит, узкий даёт крупнее позицию, но
# дороже обходится в издержках на единицу риска.
STOP_MODE = os.getenv('BRK_STOP_MODE', 'box')
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.25)
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.5)           # см. про издержки в шапке
TARGET_RANGE_MULT = _f('TARGET_RANGE_MULT', 1.0)  # цель = высота прижатия
MIN_TARGET_R = _f('MIN_TARGET_R', 1.5)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 72)          # 6 часов на 5м — это скальп

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 4)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 2.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
