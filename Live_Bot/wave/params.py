"""
Волновая стратегия (Эллиотт): параметры. Свои, ничего не заимствовано.

ЧТО ИЗ ТЕОРИИ ВООБЩЕ МОЖНО ПРОВЕРИТЬ. У Эллиотта ровно три правила, которые
названы нерушимыми; всё остальное в теории — «рекомендации», то есть предмет
вкуса аналитика. Правила такие:

    1. волна 2 не откатывает больше 100% волны 1;
    2. волна 3 не самая короткая из 1, 3 и 5;
    3. волна 4 не заходит в ценовую область волны 1.

Только первое правило можно проверить В МОМЕНТ ВХОДА — остальные два требуют
уже состоявшихся волн 3, 4 и 5, то есть годятся для разметки постфактум, но не
для решения. Поэтому здесь торгуется единственный сетап, который правила
делают самодостаточным: вход в начале волны 3.

ПРАВИЛО 1 ДАЁТ СТОП, А НЕ ФИЛЬТР. Это редкий случай, когда стоп не назначается
из головы и не подбирается по ATR: если цена ушла за начало волны 1, разметка
недействительна — не «плохо пошло», а сетап перестал существовать. Стоп стоит
ровно там.

ГЕОМЕТРИЯ СЛЕДУЕТ ИЗ ЭТОГО САМА, и она приятная. Обозначим A — начало волны 1,
B — её конец, C — дно волны 2, r — глубина отката. Тогда

    расстояние до стопа = (1 − r) × волна1
    расстояние до цели  = (ext − 1 + r) × волна1        (цель = A + ext × волна1)
    отношение           = (ext − 1 + r) / (1 − r)

При цели 1.618 это 1.6 для отката 0.382, 2.2 для 0.5, 3.2 для 0.618 и 6.6 для
0.786. Чем глубже откат, тем выгоднее сделка — и тем ближе она к собственной
недействительности. Ровно этот размен и меряется.

ПОРОГ ЗИГЗАГА РЕШАЕТ ВСЁ, и это не наша догадка, а признание самих источников:
мелкий порог считает шум, крупный показывает разметку тогда, когда движение уже
закончилось. Поэтому он вынесен главной осью замера, а не деталью.

ЧЕСТНО ПРО РОДСТВО С НАШЕЙ ЖЕ СЕТКОЙ ФИБОНАЧЧИ. Вход лимитом на откате импульса
с целью за его концом — это и есть FIBO. Волновая стратегия отличается двумя
вещами, и обе меряются:

    что                     FIBO                волна
    отбор импульса          любой по величине   пивот зигзага + сравнение с
                                                предыдущим коленом
    цель                    +25% за конец       расширение 1.618 от начала

И тут наши собственные данные говорят против: дальние цели у FIBO уже мерились,
цель 0.50 дала −0.007 и −0.032, дальше хуже. Цель Эллиотта попадает в этот же
диапазон. Значит вопрос ставится узко: делает ли отбор по волновой разметке
дальнюю цель работающей там, где на произвольном импульсе она не работает.

ЧЕГО ЗДЕСЬ НЕТ. Волн 4 и 5: для них нужны четыре подтверждённых пивота, сетапов
становится втрое меньше, а правило 3 требует уже измеренной волны 3. Сначала
проверяется главное утверждение, потом надстройки — иначе нечем объяснить, что
именно не сработало.
"""

import os


def _f(name, default):
    return float(os.getenv(f'WAVE_{name}', default))


def _i(name, default):
    return int(os.getenv(f'WAVE_{name}', default))


def _s(name, default):
    return os.getenv(f'WAVE_{name}', default)


# ── Разметка ─────────────────────────────────────────────────────────────────
ATR_PERIOD = _i('ATR_PERIOD', 14)
# Разворот на столько ATR подтверждает пивот зигзага. Главная ось замера.
REVERSAL_ATR = _f('REVERSAL_ATR', 2.5)
# Волна 1 не короче этого числа ATR — иначе размечается дрожание, а не импульс.
MIN_WAVE_ATR = _f('MIN_WAVE_ATR', 3.0)
# Волна 1 не короче предыдущего колена, умноженного на это число. Механический
# заменитель фразы «это начало новой последовательности, а не продолжение
# старой». Ноль отключает проверку.
MIN_LEG_RATIO = _f('MIN_LEG_RATIO', 0.0)

# ── Волна 2 ──────────────────────────────────────────────────────────────────
# Допустимая глубина отката. Верх строго меньше 1.0: ровно там правило 1
# перестаёт выполняться, и сетап исчезает вместе со своим стопом.
MIN_RETRACE = _f('MIN_RETRACE', 0.382)
MAX_RETRACE = _f('MAX_RETRACE', 0.90)

# ── Вход ─────────────────────────────────────────────────────────────────────
# 'limit'  — заявка на уровне ENTRY_RETRACE сразу после подтверждения волны 1;
# 'market' — вход по рынку, когда дно волны 2 подтверждено как пивот.
# Первое даёт лучшую цену, второе — подтверждённую разметку. Это два разных
# утверждения о том, что вообще является сигналом, и они меряются порознь.
ENTRY_MODE = _s('ENTRY_MODE', 'limit')
ENTRY_RETRACE = _f('ENTRY_RETRACE', 0.5)

# ── Выход ────────────────────────────────────────────────────────────────────
# Цель как расширение волны 1 от её начала: 1.618 — канон, 1.0 — конец волны 1.
TARGET_EXT = _f('TARGET_EXT', 1.618)
# Запас за начало волны 1 до стопа, в ATR. Правило 1 говорит «за A», но ровно на
# уровне A стоит слишком много чужих стопов.
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.25)
# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.5)
MIN_RR = _f('MIN_RR', 1.5)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 96)
EXPIRY_BARS = _i('EXPIRY_BARS', 12)

# ── Полная разметка 1-2-3-4-5 (wave/impulse.py) ──────────────────────────────
# Допуск близости отношения к типичному, ОТНОСИТЕЛЬНЫЙ. Промах на 0.05 при цели
# 0.5 и при цели 2.618 — разная точность, и одной линейкой их мерить нельзя.
FIB_TOLERANCE = _f('FIB_TOLERANCE', 0.15)
# Пускать ли усечённую волну 5 (не превысила вершину третьей). Для сетапа
# «вход в конце волны 4» усечение — это провал цели, а не деталь разметки.
ALLOW_TRUNCATION = os.getenv('WAVE_ALLOW_TRUNCATION', '').lower() in ('1', 'true')
# Куда целимся в волне 5: 'equality' — повтор волны 1 (правило равенства),
# 'w1_618' — 61.8% волны 1, 'net_382' — 38.2% чистого хода волн 1-3.
TARGET_MODE = _s('TARGET_MODE', 'equality')
# Минимальная уверенность разметки по Фибоначчи, 0..1. Ноль отключает отбор —
# так меряется, добавляет ли скоринг хоть что-нибудь.
MIN_FIB_SCORE = _f('MIN_FIB_SCORE', 0.0)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 6)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 6.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
