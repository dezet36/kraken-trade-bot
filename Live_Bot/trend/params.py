"""
Пробой канала на ДЛИННОМ горизонте: параметры. Свои, ничего не заимствовано.

ПОЧЕМУ ПРОБОЙ МЕРИТСЯ В ТРЕТИЙ РАЗ. Дважды он был отвергнут, и оба раза на
скальперском горизонте: сигнал на пятиминутках, уровни на часе, удержание часы.
Голый пробой канала дал −0.455 R с интервалом [−0.64; −0.26]; пробой после
прижатия с подтверждением закрытием и объёмом — тоже минус.

Здесь проверяется ДРУГОЕ, и у различия есть числовое основание, а не надежда.

1. ИЗДЕРЖКИ. Вход стоп-ордером платит тейкера с обеих сторон: круг 0.21%.
   При стопе 0.5%, типичном для скальпинга, это 0.42 R С КАЖДОЙ СДЕЛКИ —
   никакой край такого не переживёт. На длинном горизонте стоп 2-3%, и тот же
   круг стоит 0.07 R, вшестеро дешевле. Ровно это рассуждение сработало у
   Боллинджера: переход с пятиминуток на час вдвое срезал издержки и перевёл
   знак через ноль.

2. ГОРИЗОНТ. За два дня трижды измерено одно и то же: на КОРОТКОМ горизонте
   уход за уровень возвращается — вынос ликвидности, ложный пробой коридора,
   отбой. Продолжается ли уход на ДЛИННОМ — другой вопрос, и он не проверялся.

3. ДОКАЗАТЕЛЬНАЯ БАЗА. У следования за трендом, в отличие от волн Эллиотта,
   она есть: временной моментум подтверждён рецензируемыми работами и
   многолетним живым результатом управляющих фондов. Это не гарантия для
   крипты, но принципиально другая исходная позиция.

ГЛАВНЫЙ РИСК ЗДЕСЬ НЕ В ИДЕЕ, А В ЧИСЛЕ СДЕЛОК. Канал в неделю при удержании в
дни даст 30-80 сделок на период, и интервалы получатся широкие. Если выйдет
меньше тридцати — замер не состоялся, и это надо назвать, а не делать вид.

ВЫХОД ПО ПРОТИВОПОЛОЖНОМУ КАНАЛУ — классика этого жанра, и он взят сознательно
вместо фиксированной цели. Смысл следования за трендом в том, что редкие
крупные движения окупают частые мелкие убытки; фиксированная цель срезает
именно те сделки, ради которых всё затевается. Замер выходов на четырёх
стратегиях это подтвердил: резать рано вредило всем, давать дойти — помогало.
"""

import os


def _f(name, default):
    return float(os.getenv(f'TREND_{name}', default))


def _i(name, default):
    return int(os.getenv(f'TREND_{name}', default))


def _s(name, default):
    return os.getenv(f'TREND_{name}', default)


# ── Канал ────────────────────────────────────────────────────────────────────
TIMEFRAME = _s('TIMEFRAME', '1h')
ATR_PERIOD = _i('ATR_PERIOD', 14)
# Длина канала в часах. 168 — неделя. Это главная ось замера: слишком короткий
# канал возвращает нас к скальпингу, где край уже дважды не найден.
CHANNEL = _i('CHANNEL', 168)
# Канал выхода: обычно короче входного, иначе позиция держится слишком долго.
EXIT_CHANNEL = _i('EXIT_CHANNEL', 72)

# ── Вход ─────────────────────────────────────────────────────────────────────
# Пробоем считается ЗАКРЫТИЕ за границей, а не прокол тенью. Тень за
# экстремумом — это снятие стопов, и торговать её мы уже пробовали трижды.
BREAK_ON_CLOSE = _s('BREAK_ON_CLOSE', 'yes') != 'no'
# Насколько закрытие должно уйти за границу, в ATR.
BREAK_ATR = _f('BREAK_ATR', 0.10)

# ── Выход ────────────────────────────────────────────────────────────────────
# Стоп в ATR от входа. Широкий сознательно: смысл жанра в том, чтобы пережить
# откат внутри тренда, а не выйти на первом же.
STOP_ATR = _f('STOP_ATR', 3.0)
# Пол по расстоянию до стопа — арифметика издержек.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 1.0)
# Куда выходим: 'channel' — противоположный канал (классика жанра),
# 'target' — фиксированная цель в единицах риска.
EXIT_MODE = _s('EXIT_MODE', 'channel')
TARGET_R = _f('TARGET_R', 3.0)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 720)      # 30 суток
EXPIRY_BARS = _i('EXPIRY_BARS', 1)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 8)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 24.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
