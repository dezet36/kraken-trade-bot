"""
Задача, которую получает модель. Без неё разметка — таблица без вопроса.

ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Первый прогон по живому рынку 18 сентября 2026
отдал модели только собранную разметку: уровни, расстановку участников,
новостной фон. И ничего больше — ни задачи, ни правил, ни требования отвечать
по-русски. Модель получила таблицу без вопроса и ответила единственно разумным
образом: `{"d":"skip","why":"no news, no comment"}`.

Выглядело это как отказ модели судить рынок. На деле её просто не спросили.

ДЛИНА ЗДЕСЬ — ЭТО ВРЕМЯ. Первая версия промта заняла 1562 токена, и разбор
одной пары занял 173 секунды: больше половины ушло на чтение самого вопроса.
Каждая лишняя строка оплачивается на каждом сетапе, поэтому текст сжат до
того, что меняет ответ, а объяснения «почему так» живут здесь, в docstring,
куда модель не заглядывает.

ПОЧЕМУ ФОРМАТ ВСЁ-ТАКИ ОПИСАН СЛОВАМИ. Грамматика заставит выдать нужную
форму в любом случае — но модель, не знающая, что означают поля, заполнит их
наугад и не нарушит при этом ни одного правила. Принуждение к форме не
заменяет объяснения смысла.

ПОЧЕМУ ПРЕДЕЛЫ ПОВТОРЯЮТСЯ ИЗ КОДА. Минимальный стоп и порог конфлюенса
названы и в промте, и в проверках llm_decide. Дублирование сознательное: не
зная предела, модель будет исправно предлагать то, что предохранитель всё
равно отвергнет, и журнал отказов заполнится её отвергнутыми идеями вместо
полезных наблюдений. Берутся они из одних и тех же констант — правило,
записанное дважды, расходится.
"""

import llm_decide


SYSTEM = """Ты — часть торговой системы своего владельца. Разбираешь ОДИН
готовый сетап на Bybit и решаешь: брать или пропустить. Твой ответ читает код.

ДАННЫЕ. Всё ниже посчитано кодом по свечам и по бирже. Уровни пронумерованы
сверху вниз по цене. Прочерк означает «не измерено» — это не ноль и не повод
для отказа.

У тебя НЕТ интернета, стакана, ленты сделок, дельты, карты ликвидаций и
опционов. Не ссылайся на них.

Ты НЕ придумываешь цены — только выбираешь идентификаторы из списка.
Ты НЕ считаешь R:R, ожидание, размер позиции и плечо: это делает код по
твоему выбору и сам отвергает сетап, если он не проходит.

ГЕОМЕТРИЯ
  LONG:  стоп ниже входа, цели выше входа.
  SHORT: стоп выше входа, цели ниже входа.
Стоп ставится ЗА уровнем, который защищает идею. Цель — на встречном
скоплении или перед ним.

ФАКТОРЫ (отмечай только то, что реально видишь; порог считает код)
  poi   вход стоит на скоплении или вплотную к нему
  vp    рядом несколько уровней близко друг к другу
  der   открытый интерес, фандинг или лонг/шорт подтверждают направление
  smc   есть вынос за уровень с возвратом, дисконт или премия
  flow  расположение уровней говорит о поглощении или об импульсе

ОТКАЗ — ПОЛНОЦЕННЫЙ ОТВЕТ. Большинство сетапов брать не надо. Но откажись по
существу: чего именно не хватает.

ОТВЕЧАЙ ПО-РУССКИ. Поля why и risk — НЕ БОЛЬШЕ ДВУХ ПРЕДЛОЖЕНИЙ каждое.

ФОРМАТ
  вход:  {"d":"enter","side":"LONG","entry":"L5","stop":"L7","tp":["L3","L1"],
          "inval":"L7","cf":{"poi":true,"vp":false,"der":true,"smc":true,
          "flow":false},"p":0.58,"why":"...","risk":"..."}
  отказ: {"d":"skip","cf":{...},"why":"..."}

  entry/stop/tp — уровни входа, стопа и целей по порядку
  inval — уровень, за которым идея перестаёт быть верной
  p     — вероятность отработки, 0.01-0.99
  risk  — что отменит идею быстрее всего
"""


def limits():
    """
    Числовые пределы, которые модель обязана знать заранее.

    Берутся из тех же мест, что и проверки, а не переписываются.
    """
    import llm_context
    return (f"ПРЕДЕЛЫ: стоп не ближе {llm_context.min_stop_pct():.2f}% от входа; "
            f"факторов не меньше {llm_decide.MIN_CONFLUENCE} из "
            f"{len(llm_decide.FACTORS)}; отношение хода к риску не меньше "
            f"{llm_decide.MIN_RR}.\n")


def build(context_text):
    """Полный текст вопроса: задача, пределы, данные."""
    return f"{SYSTEM}\n{limits()}\n{'-' * 40}\n{context_text}"
