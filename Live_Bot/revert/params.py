"""
Возврат после импульса: параметры. Свои, ни одно число не заимствовано.

ПОЧЕМУ ЭТА ИДЕЯ ВООБЩЕ РАССМАТРИВАЕТСЯ ПОСЛЕ ЧЕТЫРЁХ ЗАКРЫТЫХ. Не потому что
она красивая, а потому что арифметика издержек её не запрещает заранее — в
отличие от пробоя, где запрещала, и мы это увидели только после трёх замеров.

    круг издержек        тейкер оба   мейкер вход + тейкер стоп   мейкер оба
    при стопе 0.5%           0.42 R                     0.25 R       0.08 R

Вход лимитом ПРОТИВ движения исполняется мейкером по построению: импульс сам
приходит к заявке, её не надо догонять. Цель — тоже лимит. Тейкера платит
только стоп. При винрейте 40% круг выходит 0.091% вместо 0.210%, то есть
0.18 R при стопе 0.5% вместо 0.42.

Это единственный рычаг, который меняет издержки в пять раз. Ни один фильтр
отбора, проверенный за сегодня, столько не двигал.

ЧТО ЗДЕСЬ НАМЕРЕННО ОТСУТСТВУЕТ. Фильтров нет. Сначала меряется голая идея:
есть ли край у возврата вообще. Фильтры добавляются к тому, что работает, а
не к тому, что надо спасти, — этому научил пробой, где четыре признака отбора
не сдвинули результат ни на сотую.
"""

import os


def _f(name, default):
    return float(os.getenv(f'REV_{name}', default))


def _i(name, default):
    return int(os.getenv(f'REV_{name}', default))


# ── Что считается резким движением ───────────────────────────────────────────
# Окно и размер. Шесть пятиминуток — полчаса: достаточно, чтобы движение было
# импульсом, а не дрейфом, и достаточно коротко для скальпа.
IMPULSE_BARS = _i('IMPULSE_BARS', 6)
# Размер в ATR одного бара. Порог возьмём из данных при первом же прогоне —
# так же, как пришлось сделать для прижатия, где значение «на глаз» оказалось
# ниже пятого процентиля и дало один сетап на двадцать тысяч баров.
IMPULSE_ATR = _f('IMPULSE_ATR', 3.0)
# Движение должно быть НАПРАВЛЕННЫМ, а не размахом внутри окна: доля баров,
# закрывшихся по ходу движения.
DIRECTIONAL = _f('DIRECTIONAL', 0.6)

# ── Вход ─────────────────────────────────────────────────────────────────────
# Лимит ставится ЗА экстремум по ходу движения: импульс должен продлиться ещё
# немного, чтобы нас набрать. Это и делает вход мейкерским — и заодно
# отсеивает случаи, где движение выдохлось раньше нашей цены.
ENTRY_OFFSET_ATR = _f('ENTRY_OFFSET_ATR', 0.3)
# Сколько баров живёт заявка. Не дождались — сетап протух.
EXPIRY_BARS = _i('EXPIRY_BARS', 6)

# ── Выход ────────────────────────────────────────────────────────────────────
# Цель — доля импульса, отсчитанная от входа обратно. Полный возврат ждать
# незачем: это скальп, и чем ближе цель, тем чаще она берётся.
TARGET_FRAC = _f('TARGET_FRAC', 0.5)
# Стоп — за продолжение движения. Считается от входа в ATR.
STOP_ATR = _f('STOP_ATR', 1.0)
# Пол по расстоянию до стопа — арифметика издержек, а не защита от шума.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.4)
MIN_RR = _f('MIN_RR', 1.0)
MAX_HOLD_BARS = _i('MAX_HOLD_BARS', 36)

# ── Портфель ─────────────────────────────────────────────────────────────────
RISK_PCT = _f('RISK_PCT', 0.5)
MAX_POSITIONS = _i('MAX_POSITIONS', 4)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 1.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)
