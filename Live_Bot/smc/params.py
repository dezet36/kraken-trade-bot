# ── Структура целей ──────────────────────────────────────────────────────────
# fib    — все цели по расширениям сетки (−0.27 / −0.62 / −1.0), как в §10.2;
# hybrid — первая цель на фиксированном кратном риска, остальные по сетке.
#
# Зачем нужен hybrid: расширения отсчитываются ЗА конец импульса, а вход стоит
# глубоко в коррекции. Цене нужно пройти всю ногу обратно И выйти за неё, чтобы
# дать хотя бы первый тейк. По факту три четверти сделок не доходят ни до одной
# цели и умирают чистым стопом. Близкая первая цель конвертирует часть этих
# движений в частичную фиксацию.
# hybrid — первая цель на фиксированном кратном риска, остальные по сетке.
# ПРИНЯТ по кругу 6 с множителем 1.5R.
#
# Основание. Разбор 471 сделки: сделка в среднем проходит 2.7R в нашу сторону,
# но 68-70% не фиксируют НИ ОДНОЙ цели — расширения сетки отсчитываются за
# конец импульса, а вход стоит глубоко в коррекции. Близкая первая цель
# переводит часть таких движений в частичную фиксацию:
#     доля сделок без единой цели  65-71% -> 38-50%
#     медвежья просадка            24.4%  -> 14.0%
#     бычья просадка               12.9%  -> 11.0%
#     средний R                    0.566/0.288 -> 0.545/0.319 (разница — шум)
# По режимам рынка hybrid 1.5R даёт 0.862 / 0.467 / 0.351 против 0.431 / 0.345
# / 0.446 у сетки, и ДВА режима из трёх впервые имеют доверительный интервал
# целиком выше нуля вместо одного.
#
# liquidity — цели на непротестированных пулах ликвидности (§14.2).
# ПРОВЕРЕНО И ОТВЕРГНУТО, круг 7 (research/smc_v7.py). Идея выглядит
# безупречно — методичка предписывает ставить тейки на пулах ликвидности, а
