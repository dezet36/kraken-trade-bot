# ── Сессионный фильтр входов: ВЫКЛЮЧЕН 2026-08-05 ────────────────────────────
# Стоял блок часов 12-16 UTC (американская сессия). Обоснование было такое:
# бэктест на 6 месяцах и 10 парах, сетапы этих часов «убыточны в 5 месяцах из
# 6». Настораживало то, КАК выбирались часы: пять худших из двадцати четырёх на
# полугоде данных найдутся всегда, даже если время суток не значит ничего.
#
# Разбивка по часу входа на двух периодах (research/sessions_hours.py, 3000
# сделок) показала обратное. Часы 12-16 не хуже остальных — они ЛУЧШЕ, и на
# обоих периодах в одну сторону:
#
#     бык 2025-26      12-16: +0.145 R против +0.069   (разность накрывает ноль)
#     медведь 2022-23  12-16: +0.152 R против +0.048   (разность накрывает ноль)
#     оба вместе       12-16: +0.149 R против +0.057   [+0.010; +0.173] — есть
#
# То есть фильтр отбрасывал 24% сделок, и это была лучшая четверть. Прежнее
# обоснование опровергнуто на данных вдвое большего объёма и на втором,
# независимом периоде.
#
# Оговорка о методе: это разбивка ОДНОГО прогона без фильтра по часу входа, а
# не полный A/B самого фильтра — тот менял бы ещё и занятость слотов. Для
# вопроса «оправдан ли блок» этого достаточно: утверждение, ради которого он
# ставился, неверно. Точную величину выигрыша от снятия покажет A/B.
#
# Переменная оставлена: значение задаётся через env, пустая строка (по
# умолчанию) — фильтра нет. Список часов можно вернуть, не трогая код.
