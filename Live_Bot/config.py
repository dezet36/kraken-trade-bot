# Взвешивание по краю НА СДЕЛКУ, которое напрашивалось первым, оказалось ХУЖЕ
# равных долей на всех трёх периодах (-19.4%). Причина: сумма R — это край,
# умноженный на число возможностей. У стратегии уровней край вшестеро выше, но
# сделок вчетверо меньше, и по краю ей досталось бы 54-59% капитала при вкладе
# в общий итог вдвое меньшем.
#
# ЧЕГО ЗАМЕР НЕ ПОКАЗАЛ, И ЭТО ВАЖНЕЕ ПРИБАВКИ: просадку из сумм посчитать
# нельзя, складывать кривые надо по времени. Доли концентрируют капитал в
# FIBO, и совокупная просадка может вырасти. Проверочных периодов всего три:
