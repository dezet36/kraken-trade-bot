_DEFAULT_BALANCES = {'FIBO': 20_000, 'LEVELS': 9_200, 'SMC': 6_800,
                     'RSIBB': 4_000,
                     # Пятая стратегия — разбор сетапов языковой моделью.
                     # Депозит выбран оператором 19 сентября 2026: третий по
                     # величине после фибо, при том что преимущество ещё не
                     # замерено. Ставка крупная, и переключатель режима у неё
                     # поэтому тем важнее.
                     'LLM': 10_000}


def _own_balance(name):
    """
    Депозит стратегии: своя настройка, иначе своё число.

    ОБЩЕГО УРОВНЯ ЗДЕСЬ НЕТ, И ЭТО НЕ ПРОПУСК. Строка выше объясняет почему:
    депозиты перестали быть долями общего котла, чтобы правка у одной
    стратегии молча не двигала деньги у остальных. PAPER_START_BALANCE — как
    раз мера того котла, и вернуть её сюда значило бы вернуть ту связь.

    Прежняя формулировка обещала три уровня — «своя настройка важнее общей,
    общая важнее числа», — и осталась от старого устройства. Кода она не
    описывала: PAPER_START_BALANCE не читался и не читается.
    """
    private = os.getenv(f'PAPER_START_BALANCE_{name}', '').strip()
    if private:
        return float(private)
    return float(_DEFAULT_BALANCES[name])


PAPER_START_BALANCES = {name: _own_balance(name) for name in _DEFAULT_BALANCES}

