# ДОЛИ КАПИТАЛА ИЗМЕРЕНЫ, А НЕ НАЗНАЧЕНЫ ПОРОВНУ (research/sizing.py, 2026-08-08).
#
# Правило проверялось скользящим окном: доля на период считалась по ПРОШЛЫМ
# периодам, первый уходил на обучение. Из четырёх правил приёмку прошло одно —
# доля пропорциональна СУММЕ R стратегии: лучше равных долей на всех трёх
# проверочных периодах, прибавка к совокупному итогу +21.4%.
