"""
Параметры стратегии уровней. СОБСТВЕННЫЕ, ни один не взят у SMC или фибо.

Стратегия, живущая на чужих настройках, не проверяется, а примеряется: её
результат тогда говорит не о ней, а о том, насколько ей подошли параметры
соседа. Порог стопа, число слотов, кулдаун — часть стратегии.

Числа обоснованы замером (research/levels_gerchik.py, два независимых
периода). Где обоснования нет — так и написано.

ГЛАВНОЕ, ЧТО ПОКАЗАЛ ЗАМЕР. Работает не уровень сам по себе, а связка из
двух вещей, и по отдельности ни одна не работает:

    подтверждение входа   цена должна проколоть уровень и вернуться;
                          без него -1104 R против +138 R
    объём на возврате     защита уровня крупным участником;
                          цель на уровне БЕЗ объёма даёт на медведе минус

Критерии «силы уровня» из классики — число касаний, зеркальность, круглые
числа, скорость подхода — проверены по отдельности и НЕ подтвердились ни
разу. Требование трёх касаний роняет отношение дохода к просадке с 7.85 до
0.99. Поэтому в стратегии их нет.
"""

import os


def _f(name, default):
    try:
        return float(os.getenv(f'LEVELS_{name}', default))
    except (TypeError, ValueError):
        return default


def _i(name, default):
    try:
        return int(os.getenv(f'LEVELS_{name}', default))
    except (TypeError, ValueError):
        return default


# ── Построение уровня ────────────────────────────────────────────────────────
# Допуск, в пределах которого касания считаются касаниями ОДНОЙ цены.
TOLERANCE_PCT = _f('TOLERANCE_PCT', 0.20)

# Глубина фрактала: экстремум с PIVOT_N барами по обе стороны. Он становится
# известен через PIVOT_N баров ПОСЛЕ себя — раньше уровень строить нельзя,
# это было бы знанием будущего.
PIVOT_N = _i('PIVOT_N', 2)

# Минимум касаний. Два — «дважды развернулось на одной цене». Три и больше
# проверены и оказались хуже.
MIN_TOUCHES = _i('MIN_TOUCHES', 2)

# Окно поиска касаний одного уровня, баров рабочего ТФ (600 ч ~ 25 дней).
MAX_SPAN_BARS = _i('MAX_SPAN_BARS', 600)

# После этого уровень считается устаревшим.
MAX_AGE_BARS = _i('MAX_AGE_BARS', 720)

# Сколько ближайших к цене уровней рассматривается. Замер показал полную
# нечувствительность к этому числу (1, 2 и 4 доказуемы одинаково), поэтому
# берём середину.
NEAREST_LEVELS = _i('NEAREST_LEVELS', 2)

# ── Вход ─────────────────────────────────────────────────────────────────────
TRIGGER_ATR = _f('TRIGGER_ATR', 1.0)     # ближе этого к уровню — рассматриваем
MIN_GAP_ATR = _f('MIN_GAP_ATR', 0.1)     # ближе этого — цена уже там

# Подтверждение: прокол не меньше PIERCE_ATR и возврат за уровень в пределах
# RECLAIM_BARS свечей.
PIERCE_ATR = _f('PIERCE_ATR', 0.15)
RECLAIM_BARS = _i('RECLAIM_BARS', 4)

# Объём свечи возврата к среднему за VOLUME_WINDOW. Рабочий диапазон 1.2-1.5
# (оба доказуемы на двух периодах); выше 2.0 бычий период теряется.
VOLUME_WINDOW = _i('VOLUME_WINDOW', 48)
VOLUME_RATIO = _f('VOLUME_RATIO', 1.5)

# Сколько живёт заявка после подтверждения.
EXPIRY_HOURS = _f('EXPIRY_HOURS', 24.0)

# ── Риск ─────────────────────────────────────────────────────────────────────
# Стоп за экстремум прокола плюс запас.
STOP_PAD_ATR = _f('STOP_PAD_ATR', 0.10)

# Не ближе этого в процентах цены: круг издержек ~0.16% цены, при стопе 0.4%
# это 0.4 R на сделку — заведомый проигрыш при любом сигнале.
MIN_STOP_PCT = _f('MIN_STOP_PCT', 0.8)

# Цель — СЛЕДУЮЩИЙ уровень по ходу сделки, но не ближе MIN_TARGET_R.
# Фиксированная кратность риску проверена и работает хуже.
MIN_TARGET_R = _f('MIN_TARGET_R', 1.5)

# Запасная цель, если следующего уровня впереди нет.
FALLBACK_RR = _f('FALLBACK_RR', 3.0)

# ── Портфель ─────────────────────────────────────────────────────────────────
MAX_POSITIONS = _i('MAX_POSITIONS', 6)
COOLDOWN_HOURS = _f('COOLDOWN_HOURS', 6.0)
MAX_SAME_DIRECTION = _i('MAX_SAME_DIRECTION', 0)   # 0 — без лимита
MAX_HOLD_HOURS = _f('MAX_HOLD_HOURS', 168.0)

# Рабочий таймфрейм и глубина истории.
TIMEFRAME = os.getenv('LEVELS_TIMEFRAME', '1h')
LOOKBACK = _i('LOOKBACK', 900)
