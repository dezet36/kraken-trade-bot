#!/bin/bash
# Сторож памяти llama-server: перезапускает модель, пока она не начала
# дочитывать собственные веса с диска.
#
# ЗАЧЕМ. Веса (15.9 ГБ) загружены через mmap и лежат в страничном кэше.
# Анонимная память самого llama-server РАСТЁТ со временем и вытесняет их.
# Замер 24.09.2026:
#
#   сразу после старта   RssAnon 0.74 ГБ   RssFile 15.93 ГБ   чтение 108 бл/с
#   через 21 час         RssAnon 8.80 ГБ   RssFile  9.14 ГБ   чтение 55000 бл/с
#
# То есть за сутки из памяти вылетело 6.8 ГБ весов, и модель стала читать их
# с диска на каждом токене: скорость упала с 2.0-2.6 до 1.35 ток/с, разбор
# вырос с 21 до 34 минут, iowait с 0% до 10%.
#
# ПРИЧИНА найдена 25.09.2026: кэш подсказок llama-server в ОЗУ (--cache-ram,
# 8 ГиБ по умолчанию), рос на 1.4-1.7 ГБ в час. Выключен в
# kraken-llm.service; сторож остаётся страховкой на случай другого роста.
#
# ПОРОГ. Весам нужно 15.93 ГБ, всего в машине ~19.5 ГБ пригодных. Значит
# анонимная память обязана оставаться ниже примерно 3 ГБ, иначе вытеснение
# начинается. Берём 2.5 ГБ.
#
# КОГДА МОЖНО. Перезапуск в середине разбора стоит получаса машинного
# времени, поэтому — только когда модель свободна. Спрашиваем её саму
# (/slots), а не журнал: по строкам «отдал модели» / «модель: N вход» с
# 24.09 сторож дважды убивал переделки (равные секунды, запас 240 с), а с
# 25.09 отказы кода без модели («нет законного плана») выглядели бы в
# журнале вечным разбором. Вердикт живёт в памяти бота — «забран ли
# циклом», как у restart_when_idle.sh, для перезапуска МОДЕЛИ не нужно.
LOG=/opt/kraken/bot_data/llm_guard.log
LIMIT_GB=2.5
WAIT=3600
SLOTS=http://127.0.0.1:8788/slots

# cron зовёт каждые 30 минут, а заход ждёт до WAIT=3600 — без замка два
# захода работают одновременно. 25.09.2026 06:03 модель перезапустили двое.
exec 9>/run/lock/kraken_llm_guard.lock
flock -n 9 || exit 0

# PID из systemd, а не pgrep -f: тот находит и любую оболочку, в чьей
# командной строке встретилось слово llama-server.
P=$(systemctl show -p MainPID --value kraken-llm)
[ -z "$P" ] || [ "$P" = "0" ] && exit 0

anon_gb=$(awk '/^RssAnon/{printf "%.2f", $2/1048576}' "/proc/$P/status" 2>/dev/null)
[ -z "$anon_gb" ] && exit 0
over=$(awk -v a="$anon_gb" -v l="$LIMIT_GB" 'BEGIN{print (a>l)?1:0}')
[ "$over" -eq 0 ] && exit 0

idle() { ! curl -s -m 5 "$SLOTS" | grep -q '"is_processing":true'; }

deadline=$(( $(date +%s) + WAIT ))
while [ $(date +%s) -lt $deadline ]; do
  # Между фазами одного разбора (прогрев, мысль, ответ, переделка) слот
  # свободен миллисекунды, настоящий простой — минуты до следующей пары:
  # свободна дважды через 3 с — значит, свободна.
  if idle && sleep 3 && idle; then
    systemctl restart kraken-llm
    sleep 60
    Q=$(systemctl show -p MainPID --value kraken-llm)
    now=$(awk '/^RssAnon/{printf "%.2f", $2/1048576}' "/proc/$Q/status" 2>/dev/null)
    res=$(awk '/^RssFile/{printf "%.2f", $2/1048576}' "/proc/$Q/status" 2>/dev/null)
    echo "$(date -u +%FT%TZ) анонимная память ${anon_gb} ГБ > ${LIMIT_GB} — модель перезапущена; стало anon ${now} ГБ, весов в памяти ${res} ГБ" >> "$LOG"
    exit 0
  fi
  sleep 30
done
echo "$(date -u +%FT%TZ) анонимная память ${anon_gb} ГБ > ${LIMIT_GB}, но разбор шёл весь час — отложено до следующего захода" >> "$LOG"
